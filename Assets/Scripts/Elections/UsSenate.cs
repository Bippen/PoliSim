using System;
using System.Collections.Generic;
using System.Globalization;
using PoliSim.Data;

namespace PoliSim.Elections
{
    /// <summary>
    /// PS-6 US-15 (`docs/specs/USA_STAGE_PLAN.md`, "The Senate as a chamber"): THE SENATE OF RECORD, BY DATE. Elias's ruling F8 - R-US1 (a): "whatever the game
    /// does not elect is seated on its record's dates"; R-US10 (a): each independent "counted with the conference it caucuses with, sourced and dated" (Sinema's
    /// caucus a reading he ruled, G3). Read senator by senator from US-12's table (<see cref="Generated.UsPresidentialReturns.SenateSeats"/>, generated by
    /// `Tools/us_senate_prep.pl` from the Senate's own pages and held by `GeneratedCatalogCheck`), never typed:
    /// <list type="bullet">
    /// <item><description><b>The chamber.</b> Two senators from each state, in three classes (Art. I §3 cl. 1 and 2, NARA's transcript, quoted in
    /// `ElectionsData/usa/records_by_date.md` §4): its members are twice the states the roster carries.</description></item>
    /// <item><description><b>A seat is held from the oath and not on the last day</b>, so the roster on a day is the Senate at that day's end, and a seat between a
    /// departure and the next oath is vacant (the catalog's readings 1-3, `ElectionsData/usa/senate_record.md`). A vacant seat is nobody's: the sides sum to the
    /// members seated.</description></item>
    /// <item><description><b>A senator's side</b> is the party key his letter reads - D is DEM, R is REP; an independent, and a Democrat from the day he became one
    /// (D/I), is counted with the conference the catalog names for him (R-US10 (a)). One who caucuses with neither is the question G3 left open, not a build
    /// item: the read throws, naming him, rather than seat a third unit the chamber's two sides cannot hold.</description></item>
    /// <item><description><b>The Vice President's vote</b> (Art. I §3 cl. 4): "The Vice President of the United States shall be President of the Senate, but shall
    /// have no Vote, unless they be equally divided." An equal division of the chamber goes to the Vice President's party - the record's own case is the 117th
    /// Congress's, the Vice President's "tie-breaking vote established a Democratic majority in the Senate" ([SEN-LEAD-H], records_by_date.md §1b;
    /// <see cref="MajorityOf"/>) - and an equal vote is the Vice President's to decide (<see cref="Carries"/>). Which Vice President, and so which party, is
    /// PS-6 US-28's one derivation (<see cref="UsTermLimit.TryVicePresidentOn"/>, the record's tickets held to NARA's pages by `TermLimitDiagnostic`), read here
    /// through <see cref="VicePresidentParty"/>.</description></item>
    /// <item><description><b>Before the record's first day</b> (<see cref="RecordOpens"/>, the catalog's first named day) the roster is not whole - it holds only
    /// the senators who served from then on - so nothing is seated there (<see cref="Seating.Covered"/>).</description></item>
    /// <item><description><b>Past the record's reach</b> (<see cref="RecordReach"/>, the catalog's last named day) the Senate of that day stands - nothing after it is
    /// on record (R-US1 (a): "the 119th stands, said on screen"; the words are <see cref="WorldClock.SecondChamberStanding"/>).</description></item>
    /// </list>
    /// Every answer here is a pure function of the date and the generated catalog, whoever the player is (R-US5); the day loop seats it for the player's
    /// country only (`SimulationManager.SeatTheRecordOnItsDate`), as it seats the House of record.
    /// </summary>
    public static class UsSenate
    {
        /// <summary>Art. I §3 cl. 1 ([CONST], records_by_date.md §4): "The Senate of the United States shall be composed of two Senators from each State".</summary>
        public const int SenatorsPerState = 2;

        /// <summary>Art. I §3 cl. 2 ([CONST], records_by_date.md §4): "they shall be divided as equally as may be into three Classes".</summary>
        public const int Classes = 3;

        /// <summary>One seat held on a day: the state, the class, the senator, the letter the state's page prints for him on that day (D, R or I - a D/I
        /// senator reads D before the day he became an independent and I from it) and the side he is counted for (DEM or REP; an independent's the conference
        /// he caucuses with, R-US10 (a)).</summary>
        public readonly struct Seat
        {
            public readonly string State;
            public readonly int Class;
            public readonly string Senator;
            public readonly string Party;
            public readonly string Side;

            public Seat(string state, int @class, string senator, string party, string side) { State = state; Class = @class; Senator = senator; Party = party; Side = side; }
        }

        /// <summary>The Senate at a day's end: the seats held, by state and class; the seats per side; the independents per side; the members (twice the
        /// states); the day the roster was read on (the day asked, or the record's reach where the day is past it); whether the record covers the day. Read-only
        /// to its readers: <see cref="UsSenate.On"/> hands the same object to every world that asks for the same day.</summary>
        public sealed class Seating
        {
            internal readonly List<Seat> seats = new List<Seat>();
            internal readonly Dictionary<string, int> bySide = new Dictionary<string, int>();
            internal readonly Dictionary<string, int> independentsBySide = new Dictionary<string, int>();

            public DateTime On { get; internal set; }
            public DateTime Read { get; internal set; }
            public int Members { get; internal set; }
            /// <summary>False before the record's first day (<see cref="RecordOpens"/>): no seat is held, and nothing is seated from it.</summary>
            public bool Covered { get; internal set; }
            public IReadOnlyList<Seat> Seats => seats;
            public IReadOnlyDictionary<string, int> BySide => bySide;
            public IReadOnlyDictionary<string, int> IndependentsBySide => independentsBySide;

            public int Vacant => Covered ? Members - seats.Count : 0;

            public int Independents
            {
                get { int n = 0; foreach (int v in independentsBySide.Values) { n += v; } return n; }
            }
        }

        private readonly struct Row
        {
            public readonly string State, Senator, Party, Caucus;
            public readonly int Class;
            public readonly DateTime Took, Left, IndependentFrom;

            public Row(string state, int @class, string senator, string party, string caucus, DateTime took, DateTime left, DateTime independentFrom)
            {
                State = state; Class = @class; Senator = senator; Party = party; Caucus = caucus; Took = took; Left = left; IndependentFrom = independentFrom;
            }
        }

        private static Row[] _rows;
        private static int _states;
        private static DateTime _opens, _reach;
        private static Seating _last;

        private static DateTime Day(string iso) => DateTime.ParseExact(iso, "yyyy-MM-dd", CultureInfo.InvariantCulture);

        private static void Load()
        {
            if (_rows != null) { return; }
            var rows = new List<Row>();
            var states = new HashSet<string>();
            foreach (var s in Generated.UsPresidentialReturns.SenateSeats)
            {
                rows.Add(new Row(s.State, s.Class, s.Senator, s.Party, s.Caucus, Day(s.Took), s.Left == "-" ? DateTime.MaxValue : Day(s.Left),
                    s.IndependentFrom == "-" ? DateTime.MaxValue : Day(s.IndependentFrom)));
                states.Add(s.State);
            }
            DateTime opens = DateTime.MaxValue, reach = DateTime.MinValue;
            foreach (var on in Generated.UsPresidentialReturns.SenateOn) { DateTime d = Day(on.Day); if (d > reach) { reach = d; } if (d < opens) { opens = d; } }
            _states = states.Count;
            _opens = opens;
            _reach = reach;
            _rows = rows.ToArray();
        }

        /// <summary>The record's first day - the first day the catalog names (the 115th Congress's opening; senate_record.md: the roster holds every senator of
        /// the window and every one whose service ended from the day after it). Before it the roster is not whole, and no Senate is seated.</summary>
        public static DateTime RecordOpens { get { Load(); return _opens; } }

        /// <summary>The record's reach - the last day the catalog names (the New Senators page's capture, senate_record.md reading 7). Past it the Senate of that
        /// day stands.</summary>
        public static DateTime RecordReach { get { Load(); return _reach; } }

        /// <summary>The chamber's members: two senators from each state the roster carries (Art. I §3 cl. 1).</summary>
        public static int Members { get { Load(); return SenatorsPerState * _states; } }

        /// <summary>The party key a catalog letter is counted for - D is DEM, R is REP; null for any other letter (an independent is his caucus's).</summary>
        private static string KeyOf(string letter) => letter == "D" ? "DEM" : letter == "R" ? "REP" : null;

        /// <summary>The Senate at the end of <paramref name="date"/> by the record - past the record's reach, the reach's (the last of record stands); before the
        /// record's first day, an empty seating that is not <see cref="Seating.Covered"/>. The same object for the same day asked twice in a row (a pure function
        /// of the date and the catalog; a view reads it every frame).</summary>
        public static Seating On(DateTime date)
        {
            Load();
            DateTime day = date.Date;
            if (_last != null && _last.On == day) { return _last; }
            DateTime read = day > _reach ? _reach : day;
            var seating = new Seating { On = day, Read = read, Members = SenatorsPerState * _states, Covered = day >= _opens };
            if (!seating.Covered) { _last = seating; return seating; }
            foreach (Row r in _rows)
            {
                if (r.Took > read || read >= r.Left) { continue; }   // from the oath's day; not on the last day (readings 1 and 2)
                bool independent = r.Party == "I" || (r.Party == "D/I" && read >= r.IndependentFrom);
                string letter = independent ? "I" : r.Party == "D/I" ? "D" : r.Party;
                string side = independent ? KeyOf(r.Caucus) : KeyOf(letter);
                if (side == null)
                {
                    // R-US10 (a) seats an independent with his conference; one with none is G3's open question - never a third unit invented here
                    throw new InvalidOperationException($"{r.Senator} ({r.State}, class {r.Class}) holds a seat on {read:yyyy-MM-dd} as '{r.Party}' with no conference the catalog names - an independent in no caucus is an open question (R-US10, G3), not seated");
                }
                seating.seats.Add(new Seat(r.State, r.Class, r.Senator, letter, side));
                seating.bySide[side] = (seating.bySide.TryGetValue(side, out int n) ? n : 0) + 1;
                if (independent) { seating.independentsBySide[side] = (seating.independentsBySide.TryGetValue(side, out int m) ? m : 0) + 1; }
            }
            seating.seats.Sort((a, b) => a.State != b.State ? string.CompareOrdinal(a.State, b.State) : a.Class.CompareTo(b.Class));
            _last = seating;
            return seating;
        }

        /// <summary>
        /// The party that holds the chamber's majority: the side with more seats than any other; on an equal division between the sides at the top, the Vice
        /// President's party where it is one of them (Art. I §3 cl. 4; the 117th's 50-50 Senate, [SEN-LEAD-H]); null where no side holds a seat, or the division
        /// is equal and the Vice President's party is not among the sides tied.
        /// </summary>
        public static string MajorityOf(IReadOnlyDictionary<string, int> seats, string vicePresidentParty)
        {
            if (seats == null) { return null; }
            string best = null;
            int most = 0;
            bool equal = false;
            foreach (KeyValuePair<string, int> kv in seats)
            {
                if (kv.Value > most) { best = kv.Key; most = kv.Value; equal = false; }
                else if (kv.Value == most && most > 0) { equal = true; }
            }
            if (!equal) { return best; }
            return vicePresidentParty != null && seats.TryGetValue(vicePresidentParty, out int theirs) && theirs == most ? vicePresidentParty : null;
        }

        /// <summary>True where the majority of <paramref name="seats"/> is decided by the Vice President's vote - an equal division between the sides at the top.</summary>
        public static bool EquallyDivided(IReadOnlyDictionary<string, int> seats)
        {
            if (seats == null) { return false; }
            int most = 0, atMost = 0;
            foreach (int v in seats.Values) { if (v > most) { most = v; atMost = 1; } else if (v == most && most > 0) { atMost++; } }
            return atMost > 1;
        }

        /// <summary>
        /// Art. I §3 cl. 4: a vote of the Senate carries with more yeas than nays, fails with more nays, and where the Senate is "equally divided" the Vice
        /// President's vote decides it - <paramref name="vicePresidentYea"/>, the side the Vice President's party takes. The model holds no absent Vice President:
        /// the vote is always cast on an equal division (DECLARED). Bills through the Senate, cloture and the Vice President on passage are US-18's; this is the rule
        /// they read.
        /// </summary>
        public static bool Carries(int yeas, int nays, bool vicePresidentYea) => yeas > nays || (yeas == nays && vicePresidentYea);

        /// <summary>The Vice President's party in a world on a date - whose vote decides an equal division: the party of the Vice President in office by PS-6
        /// US-28's one derivation (<see cref="UsTermLimit.TryVicePresidentOn"/>: the running mate on the sworn contest's ticket, else the Vice President of record
        /// by date from the record's tickets, held to NARA's pages by `TermLimitDiagnostic`); where it names none, the party of the presidency in office (one
        /// ticket). Null where the country is not governed by a presidency and no Vice President is held.</summary>
        public static string VicePresidentParty(Country country, DateTime date)
        {
            if (UsTermLimit.TryVicePresidentOn(country, date, out _, out string party, out _) && !string.IsNullOrEmpty(party)) { return party; }
            return country?.Government != null && country.Government.Kind == WorldClock.ExecutiveKind.Presidency ? country.Government.PmParty : null;
        }

        /// <summary>The Congress sitting on a date by [SEN-DIV]'s numbering (<see cref="Generated.UsPresidentialReturns.SenateDivision"/>): the number of the
        /// Congress whose party-division stretches fall inside the House of record's term that holds the date (`WorldClock.ChamberAt`, each row one Congress's
        /// two years by [SEN-DATES]); 0 where none of [SEN-DIV]'s rows is on record for that term (the 120th's, elected after the record's date) or the date is
        /// before the House rows begin.</summary>
        public static int CongressOn(DateTime date)
        {
            WorldClock.ChamberOfRecord house = WorldClock.ChamberAt(CountryId.USA, date);
            if (date.Date < house.Convened) { return 0; }
            foreach (var d in Generated.UsPresidentialReturns.SenateDivision)
            {
                DateTime from = Day(d.HoldsFrom);
                if (from >= house.Convened && from < house.Until) { return d.Congress; }
            }
            return 0;
        }

        /// <summary>The last Congress on record by [SEN-DIV], with the House of record's term that holds it - the Congress whose Senate stands past the record.</summary>
        public static bool TryLastCongressOfRecord(out int congress, out WorldClock.ChamberOfRecord term)
        {
            congress = 0;
            term = default;
            DateTime latest = DateTime.MinValue;
            foreach (var d in Generated.UsPresidentialReturns.SenateDivision)
            {
                DateTime from = Day(d.HoldsFrom);
                if (from > latest) { latest = from; congress = d.Congress; }
            }
            if (congress == 0) { return false; }
            term = WorldClock.ChamberAt(CountryId.USA, latest);
            return true;
        }

        /// <summary>A Congress's number as the Senate's pages print it: 118th, 119th, 121st.</summary>
        public static string Ordinal(int n)
        {
            int last2 = n % 100, last = n % 10;
            string suffix = last2 >= 11 && last2 <= 13 ? "th" : last == 1 ? "st" : last == 2 ? "nd" : last == 3 ? "rd" : "th";
            return n.ToString(CultureInfo.InvariantCulture) + suffix;
        }
    }
}
