using PoliSim.Data.Generated;

namespace PoliSim.Data
{
    /// <summary>
    /// pbr (K314; K293's filing, `Reviews/2026-10-30_pbr_prereg.md`): **THE PENSION BENEFIT RATIO.** The pension line is pensioners × the average pension,
    /// and the average pension is the benefit ratio × the average wage. Until pbr the line carried the statutory headcount at the going wage alone (K292's
    /// DECLARED "the pension line has no benefit ratio"), so the average pension kept its ratio to the average wage for ever; both sources project that ratio
    /// falling under the law as legislated.
    ///
    /// <para><b>The path, B.</b> The EU five: the Ageing Report 2024's Table II.1.79, "Benefit ratio (total public pensions, gross, %)" - "the average pension
    /// as a share of the average gross wage" (Institutional Paper 279, Table I.1.16's note), cut-off 1 December 2023 - one figure a year 2022-2070. The USA:
    /// DERIVED from CBO's 2026 Long-Term Projections for Social Security (publication 62556) as the Ageing Report defines its own - the average benefit
    /// (outlays × GDP / OASDI beneficiaries) over the average covered wage (covered earnings / covered workers), 2026-2100. Generated by `Tools/pbr_prep.pl`
    /// into <see cref="PensionBenefitRatioPath"/>; nothing here types a figure.</para>
    ///
    /// <para><b>Only the ratio is taken</b> (D-19 (b)'s idiom, `PopulationCohorts.RebasedTarget`): `SimulationManager.IndexSpendingLines` multiplies the
    /// pension line's real term by B(the year it indexes into) / B(the year of the last index, `Country.PensionBenefitRatioYear`), whose reference is the
    /// epoch's year (`Country.CaptureStructuralBases`) - so the path is rebased on each country's own opening year and the seed's sourced line is untouched.
    /// With B flat it is K292's rule to the bit.</para>
    ///
    /// <para><b>Ruled (Code's recommendation, Elias's standing instruction; the prereg's amendment 1):</b> B holds flat past the source's last year (2070 for the
    /// EU five, 2100 for the USA) - DECLARED: neither source publishes beyond it, and held, the line follows K292's caseload rule exactly; a pension-age bill
    /// does not move B - DECLARED (in the notional accounts a later age buys a larger annuity; not modelled); there is no pension-indexation lever - DECLARED,
    /// FILED. Before CBO's first year (the USA opens in 2024) B is 2026's [AUTHORED-DRAFT].</para>
    ///
    /// <para><b>What is not carried: the coverage ratio</b> (DECLARED, K315). The headcount stays PN-1's statutory one, which a bill moves; the Ageing Report's
    /// coverage falls as effective exit ages rise and Sweden's and Italy's statutes keep indexing past the dates the game's statute publishes.</para>
    /// </summary>
    public static class PensionBenefitRatio
    {
        /// <summary>⚠ PROBE ONLY: set by an instrument to hold B flat (every ratio 1) - the prereg's (A0) 4 neutrality run, and an attribution. The game never
        /// sets it.</summary>
        public static bool ProbeSuspended;

        /// <summary>Whether the country has a path (the six have).</summary>
        public static bool Has(CountryId id) => PensionBenefitRatioPath.Ratio.ContainsKey(id);

        /// <summary>B in <paramref name="year"/>, per cent: the generated path's figure, held at its first year before it and at its last year after it (ruled);
        /// 1 where the country has no path or the probe holds B flat - a ratio of two of these is then 1 exactly.</summary>
        public static float At(CountryId id, int year)
        {
            if (ProbeSuspended || !PensionBenefitRatioPath.Ratio.TryGetValue(id, out float[] path) || path.Length == 0) { return 1f; }
            int i = year - PensionBenefitRatioPath.FirstYear(id);
            if (i < 0) { i = 0; }
            if (i > path.Length - 1) { i = path.Length - 1; }
            return path[i];
        }

        /// <summary>B's ratio between two years - <paramref name="year"/> over <paramref name="fromYear"/>; 1 where <paramref name="fromYear"/> is unset (0, an older
        /// save) or the two read the same figure.</summary>
        public static float Ratio(CountryId id, int fromYear, int year)
        {
            if (fromYear <= 0) { return 1f; }
            float from = At(id, fromYear);
            return from > 0f ? At(id, year) / from : 1f;
        }

        /// <summary>The ratio the next boundary is projected to carry - B one year past the last index over B at it (the NEXT YEAR projection,
        /// `SimulationManager.ProjectedRealTerm`). An estimate of the year the next boundary indexes into, as the projection's price term is of its prices.</summary>
        public static float ProjectedRatio(Country country) =>
            country == null || country.PensionBenefitRatioYear <= 0 ? 1f : Ratio(country.Id, country.PensionBenefitRatioYear, country.PensionBenefitRatioYear + 1);

        /// <summary>B's index on the country's opening year at <paramref name="year"/> - what the line has carried since the seed (the diagnostics' printout).</summary>
        public static float IndexOnOpening(CountryId id, int openingYear, int year) => Ratio(id, openingYear, year);
    }
}
