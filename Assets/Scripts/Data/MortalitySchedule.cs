using System;
using System.Collections.Generic;
using PoliSim.Data.Generated;

namespace PoliSim.Data
{
    /// <summary>
    /// MF q29 (docs/RULINGS_2026-10-18.md q29; K140, docs/RULINGS_2026-10-23.md): LIFE EXPECTANCY IS DERIVED FROM MORTALITY.
    ///
    /// <para><b>The form, the smallest true one.</b> The model carries no mortality schedule of its own: the cohort substrate's survival is
    /// deaths and net migration together (CohortStepRates' own warning). So life expectancy at birth is the PERIOD life expectancy of a SOURCED
    /// schedule scaled by the model's mortality drivers:</para>
    /// <para>m(x, t) = c × m_seed(x) × R(x, t) × M × (1 + k) at ages under 75 (without the (1 + k) above),</para>
    /// <para>where m_seed is the seed year's age-specific death rates (Eurostat's life table for the EU five, the Census projection's 2024 rates
    /// for the USA), R the projection's own improvement - the one each population path already follows (EUROPOP2023 for the EU five, the Census
    /// 2023 projection for the USA), so the trend is never a second assumption beside the pyramid's; c the calibration that puts the seed year's
    /// e0 on the country's sourced figure (Country.BaselineLifeExpectancy); M the state's mortality multiplier (EconomyState.MortalityMultiplier
    /// - poverty and universal healthcare, K140); and k the treatable excess spread over ages 0-74 IN PROPORTION TO THE SCHEDULE'S OWN RATES
    /// (review M-3), so the extra deaths fall where deaths do: Δ, the treatable deaths per person-year the health family carries above the
    /// trend's own (treatable mortality is the OECD/Eurostat age-standardised rate of deaths under 75 that timely care averts: a treatable death is
    /// a death, the identity HealthFamily.DeathRateFor already reads), moves the 0-74 rate standardised on the schedule's own stationary
    /// population by exactly Δ - k = Δ ÷ that standardised rate. The schedule's stationary population stands in for the OECD standard population,
    /// which is not fetched (declared). Every figure is in LongRunAnchors, generated by Tools/q29_longrun_prep.pl.</para>
    ///
    /// <para><b>The arithmetic, declared.</b> Single years 0..94 and the open 95+: q = m / (1 + m/2) at every closed age (a = 1/2 throughout,
    /// the infant year included), L = l - d/2, the open interval's L = l / m. Tools/q29_longrun_prep.pl prints its e0 on each seed schedule beside
    /// the publisher's own; the calibration c carries what is left, so the seed year reads the sourced figure exactly. Before
    /// the first anchor year the schedule holds at that year's; between two anchor years the log of R is interpolated; after the last
    /// anchor R holds.</para>
    /// </summary>
    public static class MortalitySchedule
    {
        /// <remarks>SOURCED - the age at which the treatable-mortality definition stops: the OECD/Eurostat list of avoidable causes of mortality counts
        /// deaths under 75.</remarks>
        public const int TreatableAgeLimit = 75;

        /// <remarks>CONVENTION - a floor on a scaled death rate, so a zero rate never reaches a division (the open interval) or a standardisation; the
        /// treatable factor is at least a tenth and cannot write a negative rate. It sits far below every sourced rate.</remarks>
        private const double MinRate = 1e-6;

        /// <remarks>CONVENTION - a symmetric guard on the treatable factor (1 + k): it stays within a tenth and ten times, so a fall cannot drive the
        /// 0-74 rates into MinRate while a rise of the same log size runs free; no treatable mortality the health family's own clamp allows reaches it.</remarks>
        private const double MaxTreatableFactor = 10.0;

        private static readonly Dictionary<CountryId, double[][]> LogRatio = new Dictionary<CountryId, double[][]>();
        private static readonly Dictionary<CountryId, KeyValuePair<float, double>> Calibrations = new Dictionary<CountryId, KeyValuePair<float, double>>();
        private static readonly object Gate = new object();

        /// <summary>True where the country carries a sourced schedule.</summary>
        public static bool Has(CountryId id) => LongRunAnchors.SeedMortality.ContainsKey(id) && LongRunAnchors.MortalityRatio.ContainsKey(id);

        /// <summary>The trend schedule at a (fractional) calendar year: m_seed(x) × R(x, year), uncalibrated.</summary>
        public static double[] TrendSchedule(CountryId id, double year)
        {
            float[] seed = LongRunAnchors.SeedMortality[id];
            double[][] logRatio = LogRatios(id);
            int[] anchors = LongRunAnchors.AnchorYears;
            var m = new double[LongRunAnchors.AgeCount];
            int hi = 0;
            while (hi < anchors.Length && anchors[hi] < year) { hi++; }
            for (int x = 0; x < m.Length; x++)
            {
                double lr;
                if (hi == 0) { lr = logRatio[0][x]; }
                else if (hi >= anchors.Length) { lr = logRatio[anchors.Length - 1][x]; }
                else
                {
                    double w = (year - anchors[hi - 1]) / (anchors[hi] - anchors[hi - 1]);
                    lr = logRatio[hi - 1][x] + w * (logRatio[hi][x] - logRatio[hi - 1][x]);
                }
                m[x] = seed[x] * Math.Exp(lr);
            }
            return m;
        }

        /// <summary>Period life expectancy at birth of <paramref name="m"/> scaled by <paramref name="scale"/>, with <paramref name="treatableExcess"/>
        /// deaths per person-year spread over ages 0-74 in proportion to the scaled rates (TreatableFactor) - the arithmetic the type's summary declares.</summary>
        public static double LifeExpectancyAtBirth(double[] m, double scale, double treatableExcess)
        {
            double factor = TreatableFactor(m, scale, treatableExcess);
            double l = 1.0, t = 0.0;
            int last = m.Length - 1;
            for (int x = 0; x < last; x++)
            {
                double rate = Math.Max(MinRate, scale * m[x] * (x < TreatableAgeLimit ? factor : 1.0));
                double q = Math.Min(1.0, rate / (1.0 + 0.5 * rate));
                double d = l * q;
                t += l - 0.5 * d;
                l -= d;
            }
            t += l / Math.Max(MinRate, scale * m[last]);
            return t;
        }

        /// <summary>The treatable factor 1 + k: k = Δ ÷ the 0-74 rate of the scaled schedule standardised on its own stationary population (L(x) over
        /// ages 0-74 as weights), so the factor moves that standardised rate by exactly Δ. 1 where Δ is zero; guarded within MaxTreatableFactor.</summary>
        public static double TreatableFactor(double[] m, double scale, double treatableExcess)
        {
            if (treatableExcess == 0.0) { return 1.0; }
            double l = 1.0, weights = 0.0, weighted = 0.0;
            for (int x = 0; x < TreatableAgeLimit; x++)
            {
                double rate = Math.Max(MinRate, scale * m[x]);
                double q = Math.Min(1.0, rate / (1.0 + 0.5 * rate));
                double d = l * q;
                double lx = l - 0.5 * d;
                weights += lx;
                weighted += lx * rate;
                l -= d;
            }
            double standardised = weighted / Math.Max(MinRate, weights);
            double factor = 1.0 + treatableExcess / Math.Max(MinRate, standardised);
            return Math.Max(1.0 / MaxTreatableFactor, Math.Min(MaxTreatableFactor, factor));
        }

        /// <summary>The calibration c: the scale on the seed year's schedule whose e0 is <paramref name="baselineLifeExpectancy"/>. Solved by bisection
        /// once per country and baseline, and cached.</summary>
        public static double Calibration(CountryId id, float baselineLifeExpectancy)
        {
            lock (Gate)
            {
                if (Calibrations.TryGetValue(id, out KeyValuePair<float, double> hit) && hit.Key == baselineLifeExpectancy) { return hit.Value; }
            }
            double[] seed = TrendSchedule(id, LongRunAnchors.SeedYear);
            double lo = 0.25, hi = 4.0;   // e0 falls as the scale rises
            for (int i = 0; i < 80; i++)
            {
                double mid = 0.5 * (lo + hi);
                if (LifeExpectancyAtBirth(seed, mid, 0.0) > baselineLifeExpectancy) { lo = mid; } else { hi = mid; }
            }
            double c = 0.5 * (lo + hi);
            lock (Gate) { Calibrations[id] = new KeyValuePair<float, double>(baselineLifeExpectancy, c); }
            return c;
        }

        /// <summary>The treatable deaths per person-year above the trend's own: (treatable mortality − its trended anchor) per 100 000. Zero at the
        /// seed, on the trend, and for a country without the health family.</summary>
        public static double TreatableExcessRate(Country country)
        {
            HealthSeeds s = country.Health;
            if (s == null || !s.Seeded || s.TreatableMortality <= 0f || country.State.TreatableMortality <= 0f) { return 0.0; }
            return (country.State.TreatableMortality - HealthFamily.TrendedAnchor(s)) / 100000.0;
        }

        /// <summary>The fractional calendar year of a date: its year plus the elapsed share of it.</summary>
        public static double YearOf(DateTime date)
            => date.Year + (date.DayOfYear - 1) / (double)(DateTime.IsLeapYear(date.Year) ? 366 : 365);

        /// <summary>THE DERIVATION: life expectancy at birth in <paramref name="year"/> at the state's mortality multiplier and treatable excess.
        /// NaN where the country carries no schedule.</summary>
        public static double LifeExpectancy(Country country, double year)
        {
            if (!Has(country.Id)) { return double.NaN; }
            double c = Calibration(country.Id, country.BaselineLifeExpectancy);
            return LifeExpectancyAtBirth(TrendSchedule(country.Id, year), c * country.State.MortalityMultiplier, TreatableExcessRate(country));
        }

        private static double[][] LogRatios(CountryId id)
        {
            lock (Gate)
            {
                if (LogRatio.TryGetValue(id, out double[][] cached)) { return cached; }
                float[][] ratio = LongRunAnchors.MortalityRatio[id];
                var lr = new double[ratio.Length][];
                for (int a = 0; a < ratio.Length; a++)
                {
                    lr[a] = new double[ratio[a].Length];
                    for (int x = 0; x < ratio[a].Length; x++) { lr[a][x] = Math.Log(Math.Max(1e-9, (double)ratio[a][x])); }
                }
                LogRatio[id] = lr;
                return lr;
            }
        }
    }
}
