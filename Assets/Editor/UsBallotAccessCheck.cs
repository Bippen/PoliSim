using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using PoliSim.Data;
using PoliSim.Elections;
using PoliSim.Elections.Generated;
using PoliSim.UI;
using UnityEngine;

namespace PoliSim.EditorTools
{
    /// <summary>
    /// S7 (Design's return of 2026-10-30, section 7; SP-6b): <b>an independent's ballot access is the summary's, the US map is Design's, and the model does what
    /// the plan_prereg says</b>. Re-reads NASS's saved summary (its digest against the generated part's), the READ table and the CSV `Tools/us_ballot_prep.pl`
    /// wrote (their digests over their text with LF line ends, the CSV's rows field for field), and holds: every jurisdiction of the catalog's electors in force
    /// in 2024 has one row with the catalog's electors; a count is a count or BILLED, never zero; a BILLED rule says why. The tiles (`CampaignTiles.UsStates`,
    /// generated by `Tools/s7_tiles.pl`): one per jurisdiction, each cell once, on the grid, the HQ's map for the USA, and every US region the staging names
    /// matched to exactly one tile. The model (`UsBallotAccess`) on fixtures: filed is on the ballot whatever the day; unfiled past the deadline is lost;
    /// a BILLED rule cannot be filed; short signatures are refused and a fee paid instead is allowed; the price per signature BILLED; rule (b) zeroes a column
    /// and keeps the whole; the night with the independent on no ballot is the count's own College; at the least share for one elector it wins one and just
    /// under it none. The DECLARED ink clears the ring's fence against the seated US inks. THE TEETH: one byte more in the CSV gives another digest; a count
    /// planted one higher is not the CSV's. A stale catalog is regenerated by the tool, never retyped: `perl Tools/us_ballot_prep.pl`.
    /// Prints `US BALLOT ACCESS: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class UsBallotAccessCheck
    {
        private const string CsvRelative = "ElectionsData/usa/ballot_access_2024.csv";
        private const string ReadRelative = "ElectionsData/usa/ballot_access_read_2024.tsv";
        private const string Header = "state,electors,signatures,signatures_basis,deadline,deadline_basis,fee_usd,fee_route,fee_basis";

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);

        private static string Sha(byte[] bytes)
        {
            using (SHA256 sha = SHA256.Create()) { return string.Concat(sha.ComputeHash(bytes).Select(b => b.ToString("x2"))); }
        }

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== UsBallotAccessCheck (S7, SP-6b): an independent's ballot access, the US map, the model ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("US BALLOT ACCESS: FAIL - " + what); }
            }
            try
            {
                string root = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
                string usa = Path.Combine(root, "ElectionsData", "usa");

                // the summary, the READ table and the CSV, byte for byte
                string pdf = Path.Combine(usa, UsBallotAccess2024.SummaryPath.Replace('/', Path.DirectorySeparatorChar));
                Check(File.Exists(pdf) && Sha(File.ReadAllBytes(pdf)) == UsBallotAccess2024.SummaryDigest, F("{0} is the bytes the run read", UsBallotAccess2024.SummaryPath));
                string read = File.ReadAllText(Path.Combine(root, ReadRelative.Replace('/', Path.DirectorySeparatorChar)), Encoding.UTF8).Replace("\r\n", "\n");
                Check(Sha(Encoding.UTF8.GetBytes(read)) == UsBallotAccess2024.ReadDigest, F("{0} (its text with LF line ends) is the READ table the catalog was generated from", ReadRelative));
                string text = File.ReadAllText(Path.Combine(root, CsvRelative.Replace('/', Path.DirectorySeparatorChar)), Encoding.UTF8).Replace("\r\n", "\n");
                Check(Sha(Encoding.UTF8.GetBytes(text)) == UsBallotAccess2024.SourceDigest, F("{0} (its text with LF line ends) is the digest the generated part carries", CsvRelative));
                List<string[]> rows = text.Split('\n').Where(l => l.Length > 0 && !l.StartsWith("#", StringComparison.Ordinal)).Select(l => l.Split(',')).ToList();
                bool headed = rows.Count > 0 && string.Join(",", rows[0]) == Header;
                if (headed) { rows.RemoveAt(0); }
                bool same = headed && rows.Count == UsBallotAccess2024.Rows.Length && rows.Zip(UsBallotAccess2024.Rows, (c, g) => c.Length == 9 && c[0] == g.State
                    && c[1] == g.Electors.ToString(CultureInfo.InvariantCulture) && c[2] == (g.Signatures < 0 ? string.Empty : g.Signatures.ToString(CultureInfo.InvariantCulture))
                    && c[3] == g.SignaturesBasis && c[4] == g.Deadline && c[5] == g.DeadlineBasis && c[6] == (g.FeeUsd < 0 ? string.Empty : g.FeeUsd.ToString(CultureInfo.InvariantCulture))
                    && c[7] == g.FeeRoute && c[8] == g.FeeBasis).All(x => x);
                Check(same, F("the CSV's {0} rows are the generated part's, field for field", rows.Count));

                // every jurisdiction of 2024 once, with the catalog's electors; a count or BILLED, never zero
                var electors = new Dictionary<string, int>(StringComparer.Ordinal);
                foreach (var s in UsPresidentialReturns.States) { if (s.Year == 2024) { electors[s.State] = s.Electors; } }
                var wrong = new List<string>();
                foreach (var r in UsBallotAccess2024.Rows)
                {
                    if (!electors.TryGetValue(r.State, out int ev) || ev != r.Electors) { wrong.Add(r.State + " electors"); }
                    if (r.Signatures == 0 || (r.Signatures < 0 && !r.SignaturesBasis.StartsWith("BILLED: ", StringComparison.Ordinal))) { wrong.Add(r.State + " signatures"); }
                    if (r.Deadline.Length == 0 && !r.DeadlineBasis.StartsWith("BILLED: ", StringComparison.Ordinal)) { wrong.Add(r.State + " deadline"); }
                    if (r.Deadline.Length > 0 && !DateTime.TryParseExact(r.Deadline, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out DateTime _)) { wrong.Add(r.State + " deadline date"); }
                    if (r.Quote != "-" && r.Quote.Length < 20) { wrong.Add(r.State + " quote"); }
                }
                int distinct = UsBallotAccess2024.Rows.Select(r => r.State).Distinct().Count();
                Check(wrong.Count == 0 && distinct == electors.Count && UsBallotAccess2024.Rows.Length == electors.Count,
                    F("one row a jurisdiction of 2024 ({0} rows, {1} jurisdictions), each with the catalog's electors, a count or BILLED with its reason, a deadline or BILLED{2}",
                        UsBallotAccess2024.Rows.Length, electors.Count, wrong.Count == 0 ? string.Empty : " - " + string.Join(", ", wrong)));
                int billedCount = UsBallotAccess2024.Rows.Count(r => r.Signatures < 0), billedDeadline = UsBallotAccess2024.Rows.Count(r => r.Deadline.Length == 0);
                sb.Append(F("      read: {0} counts BILLED, {1} deadlines BILLED (printed, not judged - each is a source not on disk)\n", billedCount, billedDeadline));

                // the tiles: Design's map, one per jurisdiction, the HQ's for the USA, every staging region on one tile
                CampaignTiles.TileMap map = CampaignTiles.UsStates;
                var cells = new HashSet<(int, int)>();
                var tileWrong = new List<string>();
                foreach (CampaignTiles.Tile t in map.Tiles)
                {
                    if (!electors.ContainsKey(t.Id)) { tileWrong.Add(t.Id + " is no jurisdiction"); }
                    if (!cells.Add((t.Column, t.Row))) { tileWrong.Add(t.Id + " shares its cell"); }
                    if (t.Column < 0 || t.Column >= map.Columns || t.Row < 0 || t.Row >= map.Rows) { tileWrong.Add(t.Id + " is off the grid"); }
                }
                Check(tileWrong.Count == 0 && map.Tiles.Select(t => t.Id).Distinct().Count() == electors.Count && map.Tiles.Length == electors.Count,
                    F("the US map is a tile a jurisdiction, each on its own cell of the {0} x {1} grid{2}", map.Columns, map.Rows, tileWrong.Count == 0 ? string.Empty : " - " + string.Join(", ", tileWrong)));
                RegionAudience[] regions = UsRegions.Regions(new DateTime(2024, 11, 5), out double _, out int _, out string why);
                string[] names = regions.Select(r => r.Name).ToArray();
                int unmatched = names.Count(n => map.Tiles.Count(t => CampaignTiles.RegionOf(map, t, names) >= 0 && names[CampaignTiles.RegionOf(map, t, names)] == n) != 1);
                Check(ReferenceEquals(CampaignTiles.For(CountryId.USA, CampaignContest.Chamber, names), map) && names.Length == electors.Count && unmatched == 0,
                    F("the HQ draws the US map for the USA, and each of the staging's {0} regions is on exactly one tile ({1} not){2}", names.Length, unmatched, why != null ? " - " + why : string.Empty));

                // the model on fixtures
                DateTime poll = new DateTime(2024, 11, 5);
                IReadOnlyList<UsBallotAccess.Rule> rules = UsBallotAccess.Rules(poll);
                UsBallotAccess.Rule counted = rules.FirstOrDefault(r => !r.Billed && !r.FeeInstead && r.Signatures > 0);
                UsBallotAccess.Rule fee = rules.FirstOrDefault(r => r.FeeInstead && !r.Billed);
                UsBallotAccess.Rule billed = rules.FirstOrDefault(r => r.Billed);
                Check(counted != null && fee != null && billed != null && UsBallotAccess.Rules(new DateTime(2028, 11, 7)).Count == 0,
                    F("the fixtures exist: a counted rule ({0}), a fee-instead rule ({1}), a BILLED rule ({2}); a year not on disk holds no rules", counted?.State, fee?.State, billed?.State));
                if (counted != null && fee != null && billed != null)
                {
                    DateTime before = counted.Deadline.Value.AddDays(-1), after = counted.Deadline.Value.AddDays(1);
                    var p = new UsBallotAccess.Petition { State = counted.State };
                    bool off = UsBallotAccess.StandingOf(counted, p, before) == UsBallotAccess.Standing.Off;
                    p.Gathered = counted.Signatures - 1;
                    bool collecting = UsBallotAccess.StandingOf(counted, p, before) == UsBallotAccess.Standing.Collecting;
                    bool shortRefused = !UsBallotAccess.CanFile(counted, p, before, out string _);
                    bool lost = UsBallotAccess.StandingOf(counted, p, after) == UsBallotAccess.Standing.Lost && !UsBallotAccess.CanFile(counted, p, after, out string _);
                    p.Gathered = counted.Signatures;
                    bool filed = UsBallotAccess.File(counted, p, before, out string _) && UsBallotAccess.StandingOf(counted, p, after) == UsBallotAccess.Standing.OnBallot && !UsBallotAccess.CanFile(counted, p, before, out string _);
                    var pf = new UsBallotAccess.Petition { State = fee.State };
                    bool byFee = UsBallotAccess.CanFile(fee, pf, fee.Deadline.Value, out string _);
                    var pb = new UsBallotAccess.Petition { State = billed.State, Gathered = 1000000 };
                    bool billedRefused = UsBallotAccess.StandingOf(billed, pb, poll.AddYears(-1)) == UsBallotAccess.Standing.Billed && !UsBallotAccess.CanFile(billed, pb, poll.AddYears(-1), out string _);
                    Check(off && collecting && shortRefused && lost && filed && byFee && billedRefused && double.IsNaN(UsBallotAccess.PricePerSignatureUsd),
                        F("the drive's rule on {0}: off before any signature {1}, collecting {2}, one short refused {3}, lost past the deadline {4}, filed is on the ballot after it {5}; {6} files by the fee {7}; {8} BILLED cannot be filed {9}; the price per signature BILLED {10}",
                            counted.State, off, collecting, shortRefused, lost, filed, fee.State, byFee, billed.State, billedRefused, double.IsNaN(UsBallotAccess.PricePerSignatureUsd)));
                }
                double[] shares = { 0.40, 0.45, 0.05, 0.10 };
                double[] offShares = UsBallotAccess.Off(shares, 3);
                Check(offShares[3] == 0.0 && Math.Abs(offShares.Sum() - 1.0) < 1e-12 && Math.Abs(offShares[0] / offShares[1] - shares[0] / shares[1]) < 1e-12 && shares[3] == 0.10,
                    F("rule (b): the independent off a ballot - its {0:0.00} to zero, the others {1:0.000} / {2:0.000} / {3:0.000} in proportion, the whole kept, the input untouched",
                        shares[3], offShares[0], offShares[1], offShares[2]));

                // the night: on no ballot it is the count's own College; at the least share for one elector it wins one, just under it none
                ElectoralCollege.Jurisdiction[] college = ElectoralCollege.FromNationalShares(2020, 2024, new[] { 0.483, 0.498, 0.019 }, out ElectoralCollege.StateCall[] states, out double _);
                int[] ev2 = ElectoralCollege.Allocate(college, 2);
                UsBallotAccess.NightReading none = UsBallotAccess.Night(states, 0.05, new string[0], 2020);
                var everywhere = new HashSet<string>(rules.Where(r => !r.Billed).Select(r => r.State));
                double least = UsBallotAccess.LeastShareForOneElector(states, everywhere, 2020);
                UsBallotAccess.NightReading at = UsBallotAccess.Night(states, least, everywhere, 2020), under = UsBallotAccess.Night(states, least - 0.001, everywhere, 2020);
                Check(none.Electors == 0 && none.ElectorsRep == ev2[ElectoralCollege.Republican] && none.ElectorsDem == ev2[ElectoralCollege.Democrat] && none.NotOnBallot.Count == states.Length && none.NationalShare == 0.0
                      && at.Electors >= 1 && under.Electors == 0 && at.Electors + at.ElectorsRep + at.ElectorsDem == ElectoralCollege.TotalElectors && at.Nearest.All(n => n.OnBallot && !n.Won),
                    F("the night: on no ballot the College is the count's ({0}-{1}); the least share for an elector {2:0.00} % wins {3} (at {4}), {5:0.00} % none; every elector counted once",
                        none.ElectorsRep, none.ElectorsDem, 100.0 * least, at.Electors, at.Places.Where(x => x.Won).Select(x => x.Code).FirstOrDefault(), 100.0 * (least - 0.001)));
                Check(UsBallotAccess.HouseContingency.Split(' ').Length <= 8 && UsBallotAccess.HouseContingencyRule.Contains("12th Amendment"),
                    "For Code 4: the House contingency's words are a slip fragment, the Twelfth Amendment named");

                // the DECLARED ink: the ring's step, clear of the seated US inks
                bool clear = PartyCreationFlow.InkClear(CountryId.USA, GameController.IndependentInkStep, out string nearest, out float distance);
                Check(clear && GameController.IndependentInk() == PoliSimTheme.CreatedInkCandidate(GameController.IndependentInkStep),
                    F("the independent's ink, ring step {0} (DECLARED), clears the fence: {1:0.000} from {2}, the fence {3:0.00}", GameController.IndependentInkStep, distance, nearest, PoliSimTheme.NudgeTolerance));

                // THE TEETH
                Check(Sha(Encoding.UTF8.GetBytes(text + "\n")) != UsBallotAccess2024.SourceDigest, "planted: one byte more in the CSV gives another digest, which the check would refuse");
                var plantedRow = UsBallotAccess2024.Rows.First(r => r.Signatures > 0);
                Check(rows.Any(c => c[0] == plantedRow.State && c[2] != (plantedRow.Signatures + 1).ToString(CultureInfo.InvariantCulture)), F("planted: {0}'s count one higher is not the CSV's", plantedRow.State));
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "US BALLOT ACCESS: PASS - the rules are the summary's, the map Design's, and the model the plan_prereg's." : F("US BALLOT ACCESS: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }
    }
}
