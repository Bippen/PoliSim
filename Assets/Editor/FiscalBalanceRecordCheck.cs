using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Newtonsoft.Json.Linq;
using PoliSim.Data;
using PoliSim.Elections.Generated;
using UnityEngine;

namespace PoliSim.EditorTools
{
    /// <summary>
    /// K62 (Elias's ruling of 2026-10-23: "the pre-run fiscal years are seeded from a sourced annual balance series"): <b>the generated balance record
    /// is its sources</b>. Holds the two raw files under `ElectionsData/macro/raw/fiscal_balance/` against that folder's `SHA256SUMS.txt` and against the
    /// digests `Generated.FiscalBalanceRecord` carries; re-reads them on its own - Eurostat's JSON-stat (gov_10dd_edpt1: every dimension but the country
    /// and the year a single member, and that member B9, S13, PC_GDP, annual) and OMB's Table 1.2 workbook (its title, its columns, the Total
    /// Surplus or Deficit (-) column, read back to the one decimal OMB prints); holds the CSV `Tools/fiscal_balance_prep.pl` wrote against the
    /// generated table's digest; and fails while any year of the generated table is not the source's, any source year from the table's first on is
    /// missing from it, or a year's opening day is not its fiscal calendar's (1 January; the USA's federal year from 1 October of the year before).
    /// A stale table is regenerated by the tool, never retyped: `perl Tools/fiscal_balance_prep.pl`.
    /// Prints `FISCAL BALANCE RECORD: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class FiscalBalanceRecordCheck
    {
        private const string Folder = "ElectionsData/macro/raw/fiscal_balance/";
        private const string Eurostat = "eurostat_gov_10dd_edpt1_B9_S13_PC_GDP.json", Omb = "omb_hist01z2_fy2027.xlsx";
        private const string CsvPath = "ElectionsData/macro/fiscal_balance.csv";

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== FiscalBalanceRecordCheck (K62): the pre-run fiscal years' record against its sources ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("FISCAL BALANCE RECORD: FAIL - " + what); }
            }
            try
            {
                string[] sums = File.ReadAllText(PathOf(Folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n").Split('\n');
                byte[] eu = File.ReadAllBytes(PathOf(Folder + Eurostat)), us = File.ReadAllBytes(PathOf(Folder + Omb));
                string euDigest = Sha(eu), usDigest = Sha(us);
                Check(sums.Contains(euDigest + " *" + Eurostat) && euDigest == FiscalBalanceRecord.EurostatDigest, F("{0} {1}: listed in SHA256SUMS.txt and the digest the generated table carries", Eurostat, euDigest));
                Check(sums.Contains(usDigest + " *" + Omb) && usDigest == FiscalBalanceRecord.OmbDigest, F("{0} {1}: listed in SHA256SUMS.txt and the digest the generated table carries", Omb, usDigest));
                byte[] csv = File.ReadAllBytes(PathOf(CsvPath));
                string csvDigest = Sha(Encoding.UTF8.GetBytes(Encoding.UTF8.GetString(csv).Replace("\r\n", "\n")));
                Check(csvDigest == FiscalBalanceRecord.SourceDigest, F("{0} {1}: the digest the generated table carries", CsvPath, csvDigest));

                var source = new Dictionary<CountryId, SortedDictionary<int, double>>();
                // Eurostat JSON-stat 2.0
                JObject j = JObject.Parse(Encoding.UTF8.GetString(eu));
                string[] ids = j["id"].Select(t => (string)t).ToArray();
                int[] size = j["size"].Select(t => (int)t).ToArray();
                var want = new Dictionary<string, string> { { "freq", "A" }, { "unit", "PC_GDP" }, { "sector", "S13" }, { "na_item", "B9" } };
                bool single = true;
                for (int d = 0; d < ids.Length; d++)
                {
                    if (ids[d] == "geo" || ids[d] == "time") { continue; }
                    string member = ((JObject)j["dimension"][ids[d]]["category"]["index"]).Properties().Single().Name;
                    single &= size[d] == 1 && want.TryGetValue(ids[d], out string w) && w == member;
                }
                Check(single, "Eurostat: every dimension but geo and time a single member, and that member A, PC_GDP, S13, B9");
                var geoOf = new Dictionary<string, CountryId> { { "SE", CountryId.Sweden }, { "DE", CountryId.Germany }, { "FR", CountryId.France }, { "IT", CountryId.Italy }, { "PL", CountryId.Poland } };
                var geoIndex = (JObject)j["dimension"]["geo"]["category"]["index"];
                var timeIndex = (JObject)j["dimension"]["time"]["category"]["index"];
                foreach (JProperty g in geoIndex.Properties())
                {
                    if (!geoOf.TryGetValue(g.Name, out CountryId id)) { Check(false, "Eurostat: an unexpected geo " + g.Name); continue; }
                    var years = source[id] = new SortedDictionary<int, double>();
                    foreach (JProperty t in timeIndex.Properties())
                    {
                        int flat = 0;
                        for (int d = 0; d < ids.Length; d++) { int p = ids[d] == "geo" ? (int)g.Value : ids[d] == "time" ? (int)t.Value : 0; flat = flat * size[d] + p; }
                        JToken v = j["value"][flat.ToString(CultureInfo.InvariantCulture)];
                        if (v != null) { years[int.Parse(t.Name, CultureInfo.InvariantCulture)] = (double)v; }
                    }
                }
                // OMB Table 1.2
                using (var zip = new ZipArchive(new MemoryStream(us), ZipArchiveMode.Read))
                {
                    string Entry(string name) { using (var r = new StreamReader(zip.GetEntry(name).Open(), Encoding.UTF8)) { return r.ReadToEnd(); } }
                    List<string> strings = Regex.Matches(Entry("xl/sharedStrings.xml"), "<si>(.*?)</si>", RegexOptions.Singleline).Cast<Match>().Select(m => Regex.Replace(m.Groups[1].Value, "<[^>]+>", "")).ToList();
                    var cell = new Dictionary<string, string>();
                    foreach (Match c in Regex.Matches(Entry("xl/worksheets/sheet1.xml"), "<c r=\"([A-Z]+[0-9]+)\"([^>]*?)(?:/>|>(?:<f>.*?</f>)?(?:<v>(.*?)</v>)?</c>)", RegexOptions.Singleline))
                    {
                        if (!c.Groups[3].Success) { continue; }
                        cell[c.Groups[1].Value] = c.Groups[2].Value.Contains("t=\"s\"") ? strings[int.Parse(c.Groups[3].Value, CultureInfo.InvariantCulture)] : c.Groups[3].Value;
                    }
                    string At(string r) => cell.TryGetValue(r, out string v) ? v : "";
                    Check(At("A1").StartsWith("Table 1.2 - SUMMARY OF RECEIPTS, OUTLAYS, AND SURPLUSES OR DEFICITS", StringComparison.Ordinal) && At("A2") == "Year" && At("C2") == "Total"
                          && At("C3") == "Receipts" && At("D3") == "Outlays" && At("E3") == "Surplus or Deficit (-)",
                        "OMB: the sheet is Table 1.2, its columns Year / Total: Receipts, Outlays, Surplus or Deficit (-)");
                    var years = source[CountryId.USA] = new SortedDictionary<int, double>();
                    for (int row = 1; row <= 400; row++)
                    {
                        string y = At("A" + row), v = At("E" + row);
                        if (!Regex.IsMatch(y, "^[0-9]{4}$") || !double.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out double x)) { continue; }   // "*" and "-*" (0.05 percent or less) are left out
                        years[int.Parse(y, CultureInfo.InvariantCulture)] = Math.Round(x, 1, MidpointRounding.AwayFromZero);
                    }
                }

                foreach (CountryId id in (CountryId[])Enum.GetValues(typeof(CountryId)))
                {
                    (int Year, int OpensYear, int OpensMonth, int OpensDay, double Percent)[] table = FiscalBalanceRecord.For(id);
                    if (!source.TryGetValue(id, out SortedDictionary<int, double> years)) { Check(table.Length == 0, F("{0}: no source holds it, and the table holds no year", id)); continue; }
                    int first = table.Length > 0 ? table[0].Year : int.MaxValue;
                    bool calendar = table.All(t => new DateTime(t.OpensYear, t.OpensMonth, t.OpensDay) == (id == CountryId.USA ? new DateTime(t.Year - 1, 10, 1) : new DateTime(t.Year, 1, 1)));
                    bool every = table.Length > 0 && table.All(t => years.TryGetValue(t.Year, out double s) && s == t.Percent) && years.Keys.Where(y => y >= first).All(y => table.Any(t => t.Year == y));
                    Check(every && calendar, F("{0}: the table's {1} year(s) from {2} are the source's, every source year from {2} on is in it, each opening on its fiscal calendar's day - {3}", id, table.Length, first,
                        string.Join(" ", table.Select(t => F("{0}:{1:0.0}", t.Year, t.Percent)))));
                }
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "FISCAL BALANCE RECORD: PASS - the stored Eurostat and OMB files are the ones listed, and the generated record is their figures." : F("FISCAL BALANCE RECORD: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }

        private static string Sha(byte[] bytes)
        {
            using (var sha = SHA256.Create()) { return BitConverter.ToString(sha.ComputeHash(bytes)).Replace("-", string.Empty).ToLowerInvariant(); }
        }

        private static string PathOf(string relative) => Path.Combine(Path.GetFullPath(Path.Combine(Application.dataPath, "..")), relative);

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);
    }
}
