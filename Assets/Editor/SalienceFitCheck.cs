    /// <summary>
    /// A-LOOP q5 (2026-10-19, `docs/specs/A_LOOP_PLAN.md` §6 (3)): <b>the event-salience jumps and decays are the fit</b>. Re-reads the series
    /// `Tools/aloop_salience_fit.pl` read out of the stored Eurobarometer Volume A workbooks (`docs/generated/EB_QA3_SERIES.tsv`), holds it against the
    /// digest the generated constants carry (its text with LF line ends) and every workbook it names against its digest - its own bytes
    /// (`docs/reference/raw/aloop/eb/`) and that folder's `SHA256SUMS.txt` - then refits every class exactly as the tool's header defines it: the jump
    /// at the survey (the units' mean rise from the pre- to the post-wave; its interval the jackknife over units or, for one unit, the sampling
    /// interval of two proportions); the decay (the rate a day minimising the squared distance of the units' mean excess at each decay wave from
    /// J exp(−λ t), on the tool's grid refined by golden section; its interval the jackknife); the jump back-cast to the event's day (each unit's rise
    /// times exp(λ × its days from event to post-wave), averaged; its interval the jackknife, or the sampling interval scaled - REPORTED, never
    /// landed); the hold (the units' mean days from event to post-wave, rounded half up); and whether the class is generated (the decay resolved and
    /// the survey jump's interval clear of zero). The game lands the survey jump, held for the hold, then decaying. Fails while `Generated.EventSalienceFit` is not the fit, or
    /// while `EventSalience` reads anything but the generated constants. What it does NOT redo: reading the workbooks' cells (the tool's OLE2 / BIFF8
    /// and XML readers) - the cells are held by the series' digest and the workbooks', not re-extracted here.
    /// A stale constant is regenerated by the tool, never retyped: `perl Tools/aloop_salience_fit.pl`.
    /// Prints `SALIENCE FIT: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class SalienceFitCheck
    {
        private const string Series = "docs/generated/EB_QA3_SERIES.tsv";
        private const string Folder = "docs/reference/raw/aloop/eb/";
        private const double Relative = 1e-7;   // the golden section's own resolution in a flat minimum, between two languages' arithmetic

        private sealed class Row { public string Class, Unit; public int Step, Wave; public double Date, Share, N, Event; }

        private sealed class Fit
        {
            public List<string> Units; public double Jump, Lambda, Back, Lag; public int Edge;
            public Dictionary<string, Row> Pre, Post;
        }

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== SalienceFitCheck (A-LOOP q5): the event-salience jumps and decays refit on the stored Eurobarometer QA3 series ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("SALIENCE FIT: FAIL - " + what); }
            }
            try
            {
                string sums = File.ReadAllText(PathOf(Folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n");
                var listed = new HashSet<string>(sums.Split('\n'));
                string text = File.ReadAllText(PathOf(Series), Encoding.UTF8).Replace("\r\n", "\n");
                string seriesDigest = Sha(Encoding.UTF8.GetBytes(text));
                Check(seriesDigest == EventSalienceFit.SeriesDigest, F("the series' digest {0} (its text with LF line ends) is the one the constants carry ({1})", seriesDigest, EventSalienceFit.SeriesDigest));
                var rows = new List<Row>();
                int sources = 0, sourcesHeld = 0;
                foreach (string raw in text.Split('\n'))
                {
                    if (raw.Length == 0 || raw[0] == '#') { continue; }
                    string[] f = raw.Split('\t');
                    if (f[0] == "source")
                    {
                        sources++;
                        string digest = Sha(File.ReadAllBytes(PathOf(Folder + f[2])));
                        bool held = digest == f[3] && listed.Contains(digest + " *" + f[2]);
                        if (held) { sourcesHeld++; } else { Check(false, F("EB{0}'s workbook {1}: its SHA-256 {2} is not the one the series names ({3}) or SHA256SUMS.txt lists", f[1], f[2], digest, f[3])); }
                    }
                    else if (f[0] == "row")
                    {
                        rows.Add(new Row
                        {
                            Class = f[1], Unit = f[2], Step = int.Parse(f[3], CultureInfo.InvariantCulture), Wave = int.Parse(f[4], CultureInfo.InvariantCulture),
                            Date = D(f[5]), Share = D(f[6]), N = f[7].Length > 0 ? D(f[7]) : double.NaN, Event = D(f[8]),
                        });
                    }
                }
                Check(sources > 0 && sourcesHeld == sources, F("{0} of {1} workbooks the series names are held by their digests (the bytes and SHA256SUMS.txt)", sourcesHeld, sources));
                Check(rows.Count == EventSalienceFit.SeriesRows, F("the series carries {0} rows (the constants were fitted on {1})", rows.Count, EventSalienceFit.SeriesRows));

                foreach (SalienceClass c in (SalienceClass[])Enum.GetValues(typeof(SalienceClass)))
                {
                    string name = c.ToString();
                    List<Row> mine = rows.Where(r => r.Class == name).ToList();
                    if (mine.Count == 0) { Check(false, name + ": no rows in the series"); continue; }
                    Fit fit = FitRows(mine);
                    int n = fit.Units.Count;
                    double jlo, jhi, blo, bhi, llo = double.NaN, lhi = double.NaN;
                    if (n >= 2)
                    {
                        var jj = new List<double>(); var ll = new List<double>(); var bb = new List<double>();
                        foreach (string drop in fit.Units) { Fit g = FitRows(mine.Where(r => r.Unit != drop).ToList()); jj.Add(g.Jump); ll.Add(g.Lambda); bb.Add(g.Back); }
                        double t = Tq(n - 1);
                        jlo = fit.Jump - t * JackSe(jj); jhi = fit.Jump + t * JackSe(jj);
                        llo = fit.Lambda - t * JackSe(ll); lhi = fit.Lambda + t * JackSe(ll);
                        blo = fit.Back - t * JackSe(bb); bhi = fit.Back + t * JackSe(bb);
                    }
                    else
                    {
                        Row p0 = fit.Pre[fit.Units[0]], p1 = fit.Post[fit.Units[0]];
                        double se = Math.Sqrt(p1.Share * (1 - p1.Share) / p1.N + p0.Share * (1 - p0.Share) / p0.N);
                        jlo = fit.Jump - Z * se; jhi = fit.Jump + Z * se;
                        double scale = Math.Exp((fit.Edge == 0 ? fit.Lambda : 0.0) * fit.Lag);
                        blo = jlo * scale; bhi = jhi * scale;
                    }
                    bool generate = fit.Edge == 0 && jlo > 0;
                    int hold = generate ? (int)Math.Floor(fit.Lag + 0.5) : 0;
                    StoredFit k = Stored(c);
                    sb.Append(F("    {0,-9} -> {1,-11} n {2,2}; jump at the survey {3:+0.0000;-0.0000} (95 % {4:+0.0000;-0.0000} .. {5:+0.0000;-0.0000}); on the event's day {6:+0.0000;-0.0000} (95 % {7:+0.0000;-0.0000} .. {8:+0.0000;-0.0000}, {9:F1} days back); lambda {10:F6} a day (95 % {11} .. {12}); half-life {13}; {14}\n",
                        name, EventSalience.IssueOf(c), n, fit.Jump, jlo, jhi, fit.Back, blo, bhi, fit.Lag, fit.Lambda,
                        double.IsNaN(llo) ? "none" : llo.ToString("F6", CultureInfo.InvariantCulture), double.IsNaN(lhi) ? "none" : lhi.ToString("F6", CultureInfo.InvariantCulture),
                        fit.Edge == 0 ? F("{0:F1} days", Math.Log(2.0) / fit.Lambda) : "none",
                        generate ? F("GENERATED, held {0} days", hold) : fit.Edge < 0 ? "inert: no decay the series resolves" : fit.Edge > 0 ? "inert: gone before the first decay wave" : "inert: the jump's interval does not exclude zero"));
                    Check(k.Generated == generate && k.Units == n && Near(fit.Jump, k.SurveyJump) && Near(jlo, k.SurveyJumpLower) && Near(jhi, k.SurveyJumpUpper) && Near(fit.Lag, k.Lag)
                          && Near(fit.Back, k.EventDay) && Near(blo, k.EventDayLower) && Near(bhi, k.EventDayUpper) && Near(fit.Lambda, k.Lambda) && Near(llo, k.LambdaLower) && Near(lhi, k.LambdaUpper)
                          && k.HoldDays == hold && k.Landed == (generate ? k.SurveyJump : 0.0),
                        F("{0}: the stored constants are the fit (generated {1}/{2}, n {3}/{4}, survey jump {5:R}/{6:R}, hold {7}/{8}, back-cast {9:R}/{10:R}, lambda {11:R}/{12:R}); a stale one is regenerated: perl Tools/aloop_salience_fit.pl",
                            name, generate, k.Generated, n, k.Units, fit.Jump, k.SurveyJump, hold, k.HoldDays, fit.Back, k.EventDay, fit.Lambda, k.Lambda));
                    Check(EventSalience.JumpOf(c) == (generate ? (float)k.SurveyJump : 0f) && EventSalience.LambdaOf(c) == (generate ? k.Lambda : 0.0) && EventSalience.HoldDaysOf(c) == hold,
                        F("{0}: the game reads the fit (EventSalience.JumpOf {1:R}, LambdaOf {2:R}, HoldDaysOf {3}; zero for an inert class)", name, EventSalience.JumpOf(c), EventSalience.LambdaOf(c), EventSalience.HoldDaysOf(c)));
                }
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "SALIENCE FIT: PASS - the stored series and workbooks are the ones listed, and every class's jump and decay is their fit." : F("SALIENCE FIT: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }

        private const double Z = 1.959963984540054;   // DERIVED: the normal's 97.5 % point, the tool's

        private static Fit FitRows(List<Row> rows)
        {
            var pre = new Dictionary<string, Row>(StringComparer.Ordinal); var post = new Dictionary<string, Row>(StringComparer.Ordinal);
            var at = new SortedDictionary<int, Dictionary<string, Row>>();
            foreach (Row r in rows)
            {
                if (r.Step == -1) { pre[r.Unit] = r; }
                else if (r.Step == 0) { post[r.Unit] = r; }
                else { if (!at.TryGetValue(r.Step, out Dictionary<string, Row> d)) { at[r.Step] = d = new Dictionary<string, Row>(StringComparer.Ordinal); } d[r.Unit] = r; }
            }
            List<string> units = pre.Keys.Where(post.ContainsKey).OrderBy(u => u, StringComparer.Ordinal).ToList();
            double jump = 0; foreach (string u in units) { jump += post[u].Share - pre[u].Share; } jump /= units.Count;
            var steps = new List<(int, double, double, int)>();
            foreach (KeyValuePair<int, Dictionary<string, Row>> kv in at)
            {
                List<string> inStep = units.Where(kv.Value.ContainsKey).ToList();
                if (inStep.Count == 0) { continue; }
                double e = 0, dt = 0;
                foreach (string u in inStep) { e += kv.Value[u].Share - pre[u].Share; dt += kv.Value[u].Date - post[u].Date; }
                steps.Add((kv.Key, e / inStep.Count, dt / inStep.Count, inStep.Count));
            }
            (double lambda, int edge) = Decay(jump, steps);
            double lb = edge == 0 ? lambda : 0.0, back = 0, lag = 0;
            foreach (string u in units) { double d = post[u].Date - post[u].Event; back += (post[u].Share - pre[u].Share) * Math.Exp(lb * d); lag += d; }
            back /= units.Count; lag /= units.Count;
            return new Fit { Units = units, Jump = jump, Lambda = lambda, Edge = edge, Back = back, Lag = lag, Pre = pre, Post = post };
        }

        /// <summary>The tool's `decay`: the grid's best rate, refined by golden section between its neighbours; the edge flags as the tool's.</summary>
        private static (double, int) Decay(double j, List<(int Step, double Excess, double Dt, int In)> steps)
        {
            if (!(j > 0) || steps.Count == 0) { return (0, -1); }
            double Sse(double l) { double s = 0; foreach (var st in steps) { double d = st.Excess - j * Math.Exp(-l * st.Dt); s += d * d; } return s; }
            double Grid(int i) => EventSalienceFit.LambdaLow * Math.Pow(EventSalienceFit.LambdaHigh / EventSalienceFit.LambdaLow, (double)i / EventSalienceFit.GridPoints);
            double best = double.NaN; int bi = 0;
            for (int i = 0; i <= EventSalienceFit.GridPoints; i++) { double s = Sse(Grid(i)); if (double.IsNaN(best) || s < best) { best = s; bi = i; } }
            if (bi == 0 || bi == EventSalienceFit.GridPoints) { return (Grid(bi), bi == 0 ? -1 : 1); }
            double a = Grid(bi - 1), b = Grid(bi + 1), g = (Math.Sqrt(5) - 1) / 2;
            double c = b - g * (b - a), d2 = a + g * (b - a), fc = Sse(c), fd = Sse(d2);
            for (int it = 0; it < 100; it++)
            {
                if (fc < fd) { b = d2; d2 = c; fd = fc; c = b - g * (b - a); fc = Sse(c); }
                else { a = c; c = d2; fc = fd; d2 = a + g * (b - a); fd = Sse(d2); }
            }
            double lambda = (a + b) / 2, first = steps.Min(st => st.Dt);
            return (lambda, j * Math.Exp(-lambda * first) < EventSalienceFit.Resolution ? 1 : 0);
        }

        private static double JackSe(List<double> v)
        {
            double m = v.Average(), ss = 0; foreach (double x in v) { ss += (x - m) * (x - m); }
            return Math.Sqrt((v.Count - 1) / (double)v.Count * ss);
        }

        /// <summary>P(|T| &lt; t) for Student's t with integer <paramref name="nu"/> degrees of freedom (Abramowitz &amp; Stegun 26.7.3-4), the tool's.</summary>
        private static double TwoSided(double t, int nu)
        {
            double th = Math.Atan2(t, Math.Sqrt(nu)), s = Math.Sin(th), c = Math.Cos(th), sum = 1, term = 1;
            const double pi = 3.141592653589793;   // DERIVED: the tool's own figure for pi, so both evaluate one series
            if (nu % 2 == 1)
            {
                if (nu == 1) { return 2 * th / pi; }
                for (int k = 2; k <= nu - 3; k += 2) { term *= (double)k / (k + 1) * c * c; sum += term; }
                return 2 / pi * (th + s * c * sum);
            }
            for (int k = 1; k <= nu - 3; k += 2) { term *= (double)k / (k + 1) * c * c; sum += term; }
            return s * sum;
        }

        private static double Tq(int nu) { double lo = 0, hi = 1000; for (int i = 0; i < 200; i++) { double m = (lo + hi) / 2; if (TwoSided(m, nu) < 0.95) { lo = m; } else { hi = m; } } return (lo + hi) / 2; }

        private struct StoredFit
        {
            public bool Generated; public int Units;
            public double SurveyJump, SurveyJumpLower, SurveyJumpUpper, Lag, EventDay, EventDayLower, EventDayUpper, Lambda, LambdaLower, LambdaUpper, Landed;
            public int HoldDays;
        }

        private static StoredFit Stored(SalienceClass c)
        {
            switch (c)
            {
                case SalienceClass.Economy: return new StoredFit { Generated = EventSalienceFit.EconomyGenerated, Units = EventSalienceFit.EconomyUnits, SurveyJump = EventSalienceFit.EconomySurveyJump, SurveyJumpLower = EventSalienceFit.EconomySurveyJumpLower, SurveyJumpUpper = EventSalienceFit.EconomySurveyJumpUpper, Lag = EventSalienceFit.EconomyEventToSurveyDays, EventDay = EventSalienceFit.EconomyEventDayJump, EventDayLower = EventSalienceFit.EconomyEventDayJumpLower, EventDayUpper = EventSalienceFit.EconomyEventDayJumpUpper, Landed = EventSalienceFit.EconomyJump, HoldDays = EventSalienceFit.EconomyHoldDays, Lambda = EventSalienceFit.EconomyMeasuredLambda, LambdaLower = EventSalienceFit.EconomyLambdaLower, LambdaUpper = EventSalienceFit.EconomyLambdaUpper };
                case SalienceClass.Health: return new StoredFit { Generated = EventSalienceFit.HealthGenerated, Units = EventSalienceFit.HealthUnits, SurveyJump = EventSalienceFit.HealthSurveyJump, SurveyJumpLower = EventSalienceFit.HealthSurveyJumpLower, SurveyJumpUpper = EventSalienceFit.HealthSurveyJumpUpper, Lag = EventSalienceFit.HealthEventToSurveyDays, EventDay = EventSalienceFit.HealthEventDayJump, EventDayLower = EventSalienceFit.HealthEventDayJumpLower, EventDayUpper = EventSalienceFit.HealthEventDayJumpUpper, Landed = EventSalienceFit.HealthJump, HoldDays = EventSalienceFit.HealthHoldDays, Lambda = EventSalienceFit.HealthMeasuredLambda, LambdaLower = EventSalienceFit.HealthLambdaLower, LambdaUpper = EventSalienceFit.HealthLambdaUpper };
                case SalienceClass.Migration: return new StoredFit { Generated = EventSalienceFit.MigrationGenerated, Units = EventSalienceFit.MigrationUnits, SurveyJump = EventSalienceFit.MigrationSurveyJump, SurveyJumpLower = EventSalienceFit.MigrationSurveyJumpLower, SurveyJumpUpper = EventSalienceFit.MigrationSurveyJumpUpper, Lag = EventSalienceFit.MigrationEventToSurveyDays, EventDay = EventSalienceFit.MigrationEventDayJump, EventDayLower = EventSalienceFit.MigrationEventDayJumpLower, EventDayUpper = EventSalienceFit.MigrationEventDayJumpUpper, Landed = EventSalienceFit.MigrationJump, HoldDays = EventSalienceFit.MigrationHoldDays, Lambda = EventSalienceFit.MigrationMeasuredLambda, LambdaLower = EventSalienceFit.MigrationLambdaLower, LambdaUpper = EventSalienceFit.MigrationLambdaUpper };
                case SalienceClass.Security: return new StoredFit { Generated = EventSalienceFit.SecurityGenerated, Units = EventSalienceFit.SecurityUnits, SurveyJump = EventSalienceFit.SecuritySurveyJump, SurveyJumpLower = EventSalienceFit.SecuritySurveyJumpLower, SurveyJumpUpper = EventSalienceFit.SecuritySurveyJumpUpper, Lag = EventSalienceFit.SecurityEventToSurveyDays, EventDay = EventSalienceFit.SecurityEventDayJump, EventDayLower = EventSalienceFit.SecurityEventDayJumpLower, EventDayUpper = EventSalienceFit.SecurityEventDayJumpUpper, Landed = EventSalienceFit.SecurityJump, HoldDays = EventSalienceFit.SecurityHoldDays, Lambda = EventSalienceFit.SecurityMeasuredLambda, LambdaLower = EventSalienceFit.SecurityLambdaLower, LambdaUpper = EventSalienceFit.SecurityLambdaUpper };
                case SalienceClass.Crime: return new StoredFit { Generated = EventSalienceFit.CrimeGenerated, Units = EventSalienceFit.CrimeUnits, SurveyJump = EventSalienceFit.CrimeSurveyJump, SurveyJumpLower = EventSalienceFit.CrimeSurveyJumpLower, SurveyJumpUpper = EventSalienceFit.CrimeSurveyJumpUpper, Lag = EventSalienceFit.CrimeEventToSurveyDays, EventDay = EventSalienceFit.CrimeEventDayJump, EventDayLower = EventSalienceFit.CrimeEventDayJumpLower, EventDayUpper = EventSalienceFit.CrimeEventDayJumpUpper, Landed = EventSalienceFit.CrimeJump, HoldDays = EventSalienceFit.CrimeHoldDays, Lambda = EventSalienceFit.CrimeMeasuredLambda, LambdaLower = EventSalienceFit.CrimeLambdaLower, LambdaUpper = EventSalienceFit.CrimeLambdaUpper };
                default: return new StoredFit { Generated = EventSalienceFit.NaturalGenerated, Units = EventSalienceFit.NaturalUnits, SurveyJump = EventSalienceFit.NaturalSurveyJump, SurveyJumpLower = EventSalienceFit.NaturalSurveyJumpLower, SurveyJumpUpper = EventSalienceFit.NaturalSurveyJumpUpper, Lag = EventSalienceFit.NaturalEventToSurveyDays, EventDay = EventSalienceFit.NaturalEventDayJump, EventDayLower = EventSalienceFit.NaturalEventDayJumpLower, EventDayUpper = EventSalienceFit.NaturalEventDayJumpUpper, Landed = EventSalienceFit.NaturalJump, HoldDays = EventSalienceFit.NaturalHoldDays, Lambda = EventSalienceFit.NaturalMeasuredLambda, LambdaLower = EventSalienceFit.NaturalLambdaLower, LambdaUpper = EventSalienceFit.NaturalLambdaUpper };
            }
        }

        private static bool Near(double a, double b) => (double.IsNaN(a) && double.IsNaN(b)) || Math.Abs(a - b) <= Relative * Math.Max(1e-3, Math.Abs(b));

        private static double D(string s) => double.Parse(s, NumberStyles.Float, CultureInfo.InvariantCulture);

        private static string Sha(byte[] bytes)
        {
            using (var sha = SHA256.Create()) { return BitConverter.ToString(sha.ComputeHash(bytes)).Replace("-", string.Empty).ToLowerInvariant(); }
        }

        private static string PathOf(string relative) => Path.Combine(Path.GetFullPath(Path.Combine(Application.dataPath, "..")), relative);

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);
    }
