    /// <summary>
    /// A-LOOP q5 (2026-10-19, `docs/specs/A_LOOP_PLAN.md` §6 (3)): <b>the event-salience jumps and decays are the fit</b>. Re-reads the series
    /// `Tools/aloop_salience_fit.pl` read out of the stored Eurobarometer Volume A workbooks (`docs/generated/EB_QA3_SERIES.tsv`), holds it against the
    /// digest the generated constants carry (its text with LF line ends) and every workbook it names against its digest - its own bytes
    /// (`docs/reference/raw/aloop/eb/`) and that folder's `SHA256SUMS.txt` - then refits every class exactly as the tool's header defines it: the jump
    /// at the survey (the units' mean rise from the pre- to the post-wave; its interval the jackknife over units or, for one unit, the sampling
    /// interval of two proportions); the decay (the rate a day minimising the squared distance of the units' mean excess at each decay wave from
    /// J exp(−λ t), on the tool's grid refined by golden section; its interval the jackknife); the jump back-cast to the event's day (each unit's rise
    /// times exp(λ × its days from event to post-wave), averaged; its interval the jackknife, or the sampling interval scaled - REPORTED, never
    /// landed); the hold (the units' mean days from event to post-wave, rounded half up); and whether the class is generated (the decay resolved and
    /// the survey jump's interval clear of zero). The game lands the survey jump, held for the hold, then decaying. Fails while `Generated.EventSalienceFit` is not the fit, or
    /// while `EventSalience` reads anything but the generated constants. What it does NOT redo: reading the workbooks' cells (the tool's OLE2 / BIFF8
    /// and XML readers) - the cells are held by the series' digest and the workbooks', not re-extracted here.
    /// Since K69 (Elias, 2026-10-23) every figure above is read at the excess's PEAK - the post-wave or the decay wave whose units' mean excess is the
    /// largest - the decay fitted on the waves after it (the tool's amendment (6)); and the USA's conversion is refit from the series' base rows and the
    /// stored Gallup table, which is held against its digest (`UsConversion`).
    /// A stale constant is regenerated by the tool, never retyped: `perl Tools/aloop_salience_fit.pl`.
    /// Prints `SALIENCE FIT: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class SalienceFitCheck
    {
        private const string Series = "docs/generated/EB_QA3_SERIES.tsv";
        private const string Folder = "docs/reference/raw/aloop/eb/";
        private const double Relative = 1e-7;   // the golden section's own resolution in a flat minimum, between two languages' arithmetic

        private sealed class Row { public string Class, Unit; public int Step, Wave; public double Date, Share, N, Event; }

        private sealed class Fit
        {
            public List<string> Units; public double Jump, First, Lambda, Back, Lag, FirstLag; public int Edge, Peak;
            public Dictionary<string, Row> Pre, Post, AtPeak;
        }

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== SalienceFitCheck (A-LOOP q5): the event-salience jumps and decays refit on the stored Eurobarometer QA3 series ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("SALIENCE FIT: FAIL - " + what); }
            }
            try
            {
                string sums = File.ReadAllText(PathOf(Folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n");
                var listed = new HashSet<string>(sums.Split('\n'));
                string text = File.ReadAllText(PathOf(Series), Encoding.UTF8).Replace("\r\n", "\n");
                string seriesDigest = Sha(Encoding.UTF8.GetBytes(text));
                Check(seriesDigest == EventSalienceFit.SeriesDigest, F("the series' digest {0} (its text with LF line ends) is the one the constants carry ({1})", seriesDigest, EventSalienceFit.SeriesDigest));
                var rows = new List<Row>();
                var bases = new List<double>();
                var gallup = new List<(string Month, double Total)>();
                string gallupFile = null, gallupDigest = null;
                int sources = 0, sourcesHeld = 0;
                foreach (string raw in text.Split('\n'))
                {
                    if (raw.Length == 0 || raw[0] == '#') { continue; }
                    string[] f = raw.Split('\t');
                    if (f[0] == "base") { bases.Add(D(f[3])); continue; }
                    if (f[0] == "gallupsource") { gallupFile = f[1]; gallupDigest = f[2]; continue; }
                    if (f[0] == "gallup") { gallup.Add((f[1], D(f[2]))); continue; }
                    if (f[0] == "source")
                    {
                        sources++;
                        string digest = Sha(File.ReadAllBytes(PathOf(Folder + f[2])));
                        bool held = digest == f[3] && listed.Contains(digest + " *" + f[2]);
                        if (held) { sourcesHeld++; } else { Check(false, F("EB{0}'s workbook {1}: its SHA-256 {2} is not the one the series names ({3}) or SHA256SUMS.txt lists", f[1], f[2], digest, f[3])); }
                    }
                    else if (f[0] == "row")
                    {
                        rows.Add(new Row
                        {
                            Class = f[1], Unit = f[2], Step = int.Parse(f[3], CultureInfo.InvariantCulture), Wave = int.Parse(f[4], CultureInfo.InvariantCulture),
                            Date = D(f[5]), Share = D(f[6]), N = f[7].Length > 0 ? D(f[7]) : double.NaN, Event = D(f[8]),
                        });
                    }
                }
                Check(sources > 0 && sourcesHeld == sources, F("{0} of {1} workbooks the series names are held by their digests (the bytes and SHA256SUMS.txt)", sourcesHeld, sources));
                Check(rows.Count == EventSalienceFit.SeriesRows, F("the series carries {0} rows (the constants were fitted on {1})", rows.Count, EventSalienceFit.SeriesRows));
                UsConversion(bases, gallup, gallupFile, gallupDigest, Check);
                OutOfSample(Check, sb);

                foreach (SalienceClass c in (SalienceClass[])Enum.GetValues(typeof(SalienceClass)))
                {
                    string name = c.ToString();
                    List<Row> mine = rows.Where(r => r.Class == name).ToList();
                    if (mine.Count == 0) { Check(false, name + ": no rows in the series"); continue; }
                    Fit fit = FitRows(mine);
                    int n = fit.Units.Count;
                    double jlo, jhi, blo, bhi, llo = double.NaN, lhi = double.NaN;
                    if (n >= 2)
                    {
                        var jj = new List<double>(); var ll = new List<double>(); var bb = new List<double>();
                        foreach (string drop in fit.Units) { Fit g = FitRows(mine.Where(r => r.Unit != drop).ToList(), fit.Peak); jj.Add(g.Jump); ll.Add(g.Lambda); bb.Add(g.Back); }
                        double t = Tq(n - 1);
                        jlo = fit.Jump - t * JackSe(jj); jhi = fit.Jump + t * JackSe(jj);
                        llo = fit.Lambda - t * JackSe(ll); lhi = fit.Lambda + t * JackSe(ll);
                        blo = fit.Back - t * JackSe(bb); bhi = fit.Back + t * JackSe(bb);
                    }
                    else
                    {
                        Row p0 = fit.Pre[fit.Units[0]], p1 = fit.AtPeak[fit.Units[0]];   // K69: the peak's wave against the pre-wave
                        double se = Math.Sqrt(p1.Share * (1 - p1.Share) / p1.N + p0.Share * (1 - p0.Share) / p0.N);
                        jlo = fit.Jump - Z * se; jhi = fit.Jump + Z * se;
                        double scale = Math.Exp((fit.Edge == 0 ? fit.Lambda : 0.0) * fit.Lag);
                        blo = jlo * scale; bhi = jhi * scale;
                    }
                    bool generate = fit.Edge == 0 && jlo > 0;
                    int hold = generate ? (int)Math.Floor(fit.Lag + 0.5) : 0;
                    int firstHold = !generate ? 0 : fit.Peak == 0 ? hold : (int)Math.Floor(fit.FirstLag + 0.5);   // K94: the first wave's level held this long, then the ramp to the peak
                    StoredFit k = Stored(c);
                    sb.Append(F("    {0,-9} -> {1,-11} n {2,2}; jump at the survey {3:+0.0000;-0.0000} (95 % {4:+0.0000;-0.0000} .. {5:+0.0000;-0.0000}); on the event's day {6:+0.0000;-0.0000} (95 % {7:+0.0000;-0.0000} .. {8:+0.0000;-0.0000}, {9:F1} days back); lambda {10:F6} a day (95 % {11} .. {12}); half-life {13}; {14}\n",
                        name, EventSalience.IssueOf(c), n, fit.Jump, jlo, jhi, fit.Back, blo, bhi, fit.Lag, fit.Lambda,
                        double.IsNaN(llo) ? "none" : llo.ToString("F6", CultureInfo.InvariantCulture), double.IsNaN(lhi) ? "none" : lhi.ToString("F6", CultureInfo.InvariantCulture),
                        fit.Edge == 0 ? F("{0:F1} days", Math.Log(2.0) / fit.Lambda) : "none",
                        generate ? F("GENERATED, held {0} days", hold) : fit.Edge < 0 ? "inert: no decay the series resolves" : fit.Edge > 0 ? "inert: gone before the first decay wave" : "inert: the jump's interval does not exclude zero"));
                    Check(k.Generated == generate && k.Units == n && Near(fit.Jump, k.SurveyJump) && Near(jlo, k.SurveyJumpLower) && Near(jhi, k.SurveyJumpUpper) && Near(fit.Lag, k.Lag)
                          && Near(fit.Back, k.EventDay) && Near(blo, k.EventDayLower) && Near(bhi, k.EventDayUpper) && Near(fit.Lambda, k.Lambda) && Near(llo, k.LambdaLower) && Near(lhi, k.LambdaUpper)
                          && k.HoldDays == hold && k.Landed == (generate ? k.SurveyJump : 0.0) && k.PeakStep == fit.Peak && Near(fit.First, k.FirstWave)
                          && k.FirstHoldDays == firstHold && k.RampDays == hold - firstHold,
                        F("{0}: the stored constants are the fit (generated {1}/{2}, n {3}/{4}, survey jump {5:R}/{6:R}, hold {7}/{8}, back-cast {9:R}/{10:R}, lambda {11:R}/{12:R}, peak step {13}/{14}); a stale one is regenerated: perl Tools/aloop_salience_fit.pl",
                            name, generate, k.Generated, n, k.Units, fit.Jump, k.SurveyJump, hold, k.HoldDays, fit.Back, k.EventDay, fit.Lambda, k.Lambda, fit.Peak, k.PeakStep));
                    // K69: the jump is read at the excess's peak - the largest mean excess over the post-wave and every decay wave, never a smaller one
                    Check(fit.Jump >= fit.First && Near(fit.Jump, Math.Max(fit.First, PeakOf(mine))),
                        F("{0}: K69 - the jump {1:+0.0000;-0.0000} is the excess at its peak (step {2}; the post-wave's own rise {3:+0.0000;-0.0000})", name, fit.Jump, fit.Peak, fit.First));
                    Check(EventSalience.FirstLevelOf(c) == (generate ? (float)k.FirstWave : 0f) && EventSalience.FirstHoldDaysOf(c) == firstHold && EventSalience.RampDaysOf(c) == hold - firstHold,
                        F("{0}: K94 - the game ramps from the first wave's level {1:R} held {2} days to the peak over {3} days (the fit: {4:R}, {5}, {6})", name, EventSalience.FirstLevelOf(c), EventSalience.FirstHoldDaysOf(c), EventSalience.RampDaysOf(c),
                            generate ? (float)k.FirstWave : 0f, firstHold, hold - firstHold));
                    // review L-3: a generated class lands its first wave's rise on the event's day, so that rise must be positive - a refit with a
                    // non-positive first wave under a later peak would land a fall, or nothing, and fails here until ruled
                    Check(!generate || fit.First > 0.0, F("{0}: L-3 - a generated class's first-wave rise is positive ({1:+0.0000;-0.0000})", name, fit.First));
                    Check(EventSalience.JumpOf(c) == (generate ? (float)k.SurveyJump : 0f) && EventSalience.LambdaOf(c) == (generate ? k.Lambda : 0.0) && EventSalience.HoldDaysOf(c) == hold,
                        F("{0}: the game reads the fit (EventSalience.JumpOf {1:R}, LambdaOf {2:R}, HoldDaysOf {3}; zero for an inert class)", name, EventSalience.JumpOf(c), EventSalience.LambdaOf(c), EventSalience.HoldDaysOf(c)));
                }
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "SALIENCE FIT: PASS - the stored series and workbooks are the ones listed, and every class's jump and decay is their fit." : F("SALIENCE FIT: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }

        /// <summary>K69's USA: the stored Gallup table held against its digest (its own bytes, its folder's SHA256SUMS.txt and the series' gallupsource
        /// row), its Total row re-read from the file and held to the series' gallup rows, and the generated bases and conversion recomputed - Gallup's the
        /// mean of its Totals, Eurobarometer's the mean of the base rows (each a member's summed QA3 shares in a wave), the conversion their ratio.</summary>
        private static void UsConversion(List<double> bases, List<(string Month, double Total)> gallup, string gallupFile, string gallupDigest, Action<bool, string> check)
        {
            if (gallupFile == null) { check(false, "K69: the series carries no gallupsource row"); return; }
            string folder = Path.GetDirectoryName(gallupFile).Replace('\\', '/') + "/";
            string name = Path.GetFileName(gallupFile);
            byte[] bytes = File.ReadAllBytes(PathOf(gallupFile));
            string digest = Sha(bytes);
            var listed = new HashSet<string>(File.ReadAllText(PathOf(folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n").Split('\n'));
            check(digest == gallupDigest && digest == EventSalienceFit.GallupDigest && listed.Contains(digest + " *" + name),
                F("K69: Gallup's table {0} is held by its digest {1} (its bytes, its folder's SHA256SUMS.txt, the series and the constants)", gallupFile, digest));
            string[] months = null; double[] totals = null;
            foreach (string raw in Encoding.UTF8.GetString(bytes).Replace("\r\n", "\n").Split('\n'))
            {
                string[] f = raw.Split('\t');
                if (months == null && f.Length > 1 && f[0].Length == 0 && System.Text.RegularExpressions.Regex.IsMatch(f[1], "^[A-Z][a-z]{2}-[0-9]{2}$")) { months = f.Skip(1).ToArray(); }
                if (f.Length > 1 && f[0] == "Total") { totals = f.Skip(1).Select(v => double.Parse(v.TrimEnd('%'), NumberStyles.Integer, CultureInfo.InvariantCulture) / 100.0).ToArray(); }
            }
            bool same = months != null && totals != null && months.Length == totals.Length && totals.Length == gallup.Count;
            for (int i = 0; same && i < gallup.Count; i++) { same &= months[i] == gallup[i].Month && Near(totals[i], gallup[i].Total); }
            check(same, F("K69: Gallup's Total row re-read from its file is the series' ({0} months: {1})", gallup.Count, string.Join(", ", gallup.Select(g => g.Month + " " + g.Total.ToString("0.00", CultureInfo.InvariantCulture)))));
            double gBase = gallup.Count > 0 ? gallup.Sum(g => g.Total) / gallup.Count : double.NaN;
            double eBase = bases.Count > 0 ? bases.Sum() / bases.Count : double.NaN;
            check(gallup.Count == EventSalienceFit.GallupMonths && bases.Count == EventSalienceFit.BaseRows && Near(gBase, EventSalienceFit.GallupBase) && Near(eBase, EventSalienceFit.EurobarometerBase)
                  && Near(gBase / eBase, EventSalienceFit.UsConversion) && bases.All(b => b > 1.0 && b < 2.05),
                F("K69: the bases are the tables' - Gallup {0:F4} mentions a respondent over {1} months, Eurobarometer {2:F4} over {3} member-waves ({4:F2} .. {5:F2}, two answers at most, the sheets' whole per cents); the USA's conversion {6:F4} (stored {7:F4})",
                    gBase, gallup.Count, eBase, bases.Count, bases.Count > 0 ? bases.Min() : double.NaN, bases.Count > 0 ? bases.Max() : double.NaN, gBase / eBase, EventSalienceFit.UsConversion));
        }

        private const string K102Folder = "ElectionsData/usa/raw/salience/k102/";

        /// <summary>A table cell as a share: a whole per cent over 100, or NaN for "*" (under half a per cent) and "--" (not mentioned) - the tool's `kval`.</summary>
        private static double KVal(string v)
        {
            v = Regex.Replace(v, @"\s+", " ").Trim().TrimEnd('%');
            return Regex.IsMatch(v, "^[0-9]+$") ? int.Parse(v, CultureInfo.InvariantCulture) / 100.0 : double.NaN;
        }

        /// <summary>The tool's `ktable`: a stored Gallup table as its month columns and its rows by label - the Datawrapper dataset (tab-separated) or the
        /// trends page's first table (months in its scope="col" cells, each row's label in its scope="row" cell).</summary>
        private static (List<string> Months, Dictionary<string, List<double>> Rows) KTable(string name, byte[] bytes)
        {
            var months = new List<string>(); var rows = new Dictionary<string, List<double>>(StringComparer.Ordinal);
            string text = Encoding.UTF8.GetString(bytes);
            string Clean(string s) => Regex.Replace(s, @"\s+", " ").Trim();
            if (name.EndsWith(".csv", StringComparison.Ordinal))
            {
                foreach (string raw in text.Replace("\r\n", "\n").Split('\n'))
                {
                    string[] f = raw.Split('\t'); if (f.Length < 2) { continue; }
                    if (months.Count == 0 && f[0].Length == 0 && Regex.IsMatch(f[1], "^[A-Z][a-z]{2}[- ][0-9]")) { months.AddRange(f.Skip(1)); continue; }
                    string label = Clean(Regex.Replace(f[0], "<[^>]+>", "")); if (label.Length == 0) { continue; }
                    rows[label] = f.Skip(1).Select(KVal).ToList();
                }
                return (months, rows);
            }
            Match t = Regex.Match(text, "<table.*?</table>", RegexOptions.Singleline);
            if (!t.Success) { return (months, rows); }
            foreach (Match m in Regex.Matches(t.Value, "<th colspan=\"1\" scope=\"col\">(.*?)</th>", RegexOptions.Singleline)) { months.Add(Clean(m.Groups[1].Value)); }
            foreach (Match tr in Regex.Matches(t.Value, "<tr>(.*?)</tr>", RegexOptions.Singleline))
            {
                Match l = Regex.Match(tr.Groups[1].Value, "<th scope=\"row\">(.*?)</th>", RegexOptions.Singleline);
                if (!l.Success) { continue; }
                string label = System.Net.WebUtility.HtmlDecode(Clean(Regex.Replace(l.Groups[1].Value, "<[^>]+>", "")));
                rows[label] = Regex.Matches(tr.Groups[1].Value, "<td[^>]*>(.*?)</td>", RegexOptions.Singleline).Cast<Match>().Select(c => KVal(c.Groups[1].Value)).ToList();
            }
            return (months, rows);
        }

        /// <summary>K102 (Elias, 2026-10-24): the USA's conversion tested out of sample, by the criterion the tool's header declared before the figures -
        /// every stored Gallup table held by its digest (its bytes and k102/SHA256SUMS.txt), each tested year's base, the surging item's rise and the
        /// share ratio re-read from the tables and held to the generated constants, the verdict recomputed. 2015's page must carry no text table (it is
        /// BILLED). The verdict itself is a READING printed for Elias (it failed, and K103 dropped the conversion - the game lands the USA's jump at scale one; this is the record of why):
        /// what fails this check is a generated figure or verdict that is not the stored tables' test.</summary>
        private static void OutOfSample(Action<bool, string> check, StringBuilder sb)
        {
            var listed = new HashSet<string>(File.ReadAllText(PathOf(K102Folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n").Split('\n'));
            byte[] Bytes(string name)
            {
                byte[] b = File.ReadAllBytes(PathOf(K102Folder + name));
                check(listed.Contains(Sha(b) + " *" + name), F("K102: {0} is held by its digest {1} (k102/SHA256SUMS.txt)", name, Sha(b)));
                return b;
            }
            check(!Encoding.UTF8.GetString(Bytes("wayback_gallup_mip_page_20150915083712.html")).ToLowerInvariant().Contains("<table"), "K102: 2015's stored trends page carries no text table (its table is an image) - the year is BILLED");
            var years = new[]
            {
                (Year: 2020, Item: "Coronavirus/Diseases", Class: SalienceClass.Health, Pre: "Feb 2020", Post: new[] { "Apr 2020", "May 2020", "Jun 2020", "Jul 2020", "Aug 2020", "Sep 2020" }, Files: new[] { "wayback_gallup_mip_page_20201028085700.html" },
                 Columns: EventSalienceFit.K102Columns2020, Base: EventSalienceFit.K102Base2020, Rise: EventSalienceFit.K102Rise2020, Eb: EventSalienceFit.K102EbJump2020, Ratio: EventSalienceFit.K102Ratio2020),
                (Year: 2022, Item: "High cost of living/Inflation", Class: SalienceClass.Economy, Pre: "Feb 2022", Post: new[] { "Mar 2022", "Apr 2022", "May 2022", "Jun 2022", "Jul 2022", "Aug 2022" }, Files: new[] { "wayback_gallup_mip_page_20220425021115.html", "gallup_mip_vEKjO_1_dataset.csv" },
                 Columns: EventSalienceFit.K102Columns2022, Base: EventSalienceFit.K102Base2022, Rise: EventSalienceFit.K102Rise2022, Eb: EventSalienceFit.K102EbJump2022, Ratio: EventSalienceFit.K102Ratio2022),
            };
            bool baseStable = true; int nearer = 0;
            foreach (var y in years)
            {
                var total = new Dictionary<string, double>(StringComparer.Ordinal); var item = new Dictionary<string, double>(StringComparer.Ordinal);
                string suffix = " " + y.Year.ToString(CultureInfo.InvariantCulture);
                foreach (string file in y.Files)
                {
                    (List<string> months, Dictionary<string, List<double>> rows) = KTable(file, Bytes(file));
                    if (!rows.ContainsKey("Total") || !rows.ContainsKey(y.Item)) { check(false, F("K102 {0}: {1} carries no Total row or no '{2}' row", y.Year, file, y.Item)); return; }
                    for (int i = 0; i < months.Count; i++)
                    {
                        if (!months[i].EndsWith(suffix, StringComparison.Ordinal) || total.ContainsKey(months[i])) { continue; }
                        total[months[i]] = rows["Total"][i]; item[months[i]] = rows[y.Item][i];
                    }
                }
                if (!item.ContainsKey(y.Pre) || y.Post.Any(m => !item.ContainsKey(m))) { check(false, F("K102 {0}: a pre or post column is missing from the stored tables", y.Year)); return; }
                double gBase = total.Values.Average();
                double peak = y.Post.Max(m => double.IsNaN(item[m]) ? 0.0 : item[m]);
                double rise = peak - item[y.Pre];
                double eb = Stored(y.Class).SurveyJump;
                double dConv = Math.Abs(Math.Log(rise / (eb * EventSalienceFit.UsConversion))), dNone = Math.Abs(Math.Log(rise / eb));
                bool inside = Math.Abs(gBase / EventSalienceFit.GallupBase - 1.0) <= 0.15;
                baseStable &= inside; if (dConv < dNone) { nearer++; }
                check(total.Count == y.Columns && Near(gBase, y.Base) && Near(rise, y.Rise) && Near(eb, y.Eb) && Near(rise / eb, y.Ratio),
                    F("K102 {0}: the generated figures are the stored tables' - base {1:F4} over {2} columns, '{3}' {4} {5:F2} -> peak {6:F2}, rise {7:+0.0000}, EB {8} jump {9:+0.0000}, ratio {10:F4}", y.Year, gBase, total.Count, y.Item, y.Pre, item[y.Pre], peak, rise, y.Class, eb, rise / eb));
                sb.Append(F("    K102 {0} READING: Gallup's base {1:F4} ({2} the 2024 base's +-15 %); the share ratio {3:F4} against the conversion {4:F4}; |ln| to the converted {5:F3}, to the unconverted {6:F3}\n",
                    y.Year, gBase, inside ? "inside" : "OUTSIDE", rise / eb, EventSalienceFit.UsConversion, dConv, dNone));
            }
            bool kept = baseStable && nearer * 2 > years.Length;
            check(baseStable == EventSalienceFit.K102BaseStable && nearer == EventSalienceFit.K102ConvertedNearer && years.Length == EventSalienceFit.K102Years && kept == EventSalienceFit.K102Kept,
                F("K102: the generated verdict is the declared criterion's on the stored tables (base stable {0}, converted nearer in {1} of {2}, kept {3})", baseStable, nearer, years.Length, kept));
            sb.Append(F("    K102 VERDICT (a reading for Elias): the conversion {0} by the criterion declared before the test\n", kept ? "is KEPT" : "FAILS - dropped by K103, the USA at scale one"));
        }

        /// <summary>An independent reading of the excess's peak: the largest, over the decay waves, of the units' mean share less their pre-wave's (the
        /// post-wave's is the caller's) - grouped here by step alone, without the fit's own bookkeeping.</summary>
        private static double PeakOf(List<Row> rows)
        {
            var pre = rows.Where(r => r.Step == -1).ToDictionary(r => r.Unit, r => r.Share, StringComparer.Ordinal);
            var post = new HashSet<string>(rows.Where(r => r.Step == 0).Select(r => r.Unit), StringComparer.Ordinal);
            double best = double.NegativeInfinity;
            foreach (IGrouping<int, Row> g in rows.Where(r => r.Step > 0 && pre.ContainsKey(r.Unit) && post.Contains(r.Unit)).GroupBy(r => r.Step))
            {
                double m = g.Average(r => r.Share - pre[r.Unit]);
                if (m > best) { best = m; }
            }
            return best;
        }

