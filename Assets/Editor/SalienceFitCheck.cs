        /// <summary>The tool's `fit_rows`: K69's reading at the excess's PEAK - the step (0 the post-wave) whose mean excess over the pre-wave is the
        /// largest, the earliest on a tie, or <paramref name="peak"/> where a leave-one-out holds the full sample's - the jump that step's mean excess,
        /// the decay fitted on the steps after it with their times counted from it, the hold and the back-cast read at the peak's wave.</summary>
        private static Fit FitRows(List<Row> rows, int? peak = null)
        {
            var pre = new Dictionary<string, Row>(StringComparer.Ordinal); var post = new Dictionary<string, Row>(StringComparer.Ordinal);
            var at = new SortedDictionary<int, Dictionary<string, Row>>();
            foreach (Row r in rows)
            {
                if (r.Step == -1) { pre[r.Unit] = r; }
                else if (r.Step == 0) { post[r.Unit] = r; }
                else { if (!at.TryGetValue(r.Step, out Dictionary<string, Row> d)) { at[r.Step] = d = new Dictionary<string, Row>(StringComparer.Ordinal); } d[r.Unit] = r; }
            }
            List<string> units = pre.Keys.Where(post.ContainsKey).OrderBy(u => u, StringComparer.Ordinal).ToList();
            double first = 0; foreach (string u in units) { first += post[u].Share - pre[u].Share; } first /= units.Count;
            var steps = new List<(int Step, double Excess, double Dt, int In)>();
            foreach (KeyValuePair<int, Dictionary<string, Row>> kv in at)
            {
                List<string> inStep = units.Where(kv.Value.ContainsKey).ToList();
                if (inStep.Count == 0) { continue; }
                double e = 0, dt = 0;
                foreach (string u in inStep) { e += kv.Value[u].Share - pre[u].Share; dt += kv.Value[u].Date - post[u].Date; }
                steps.Add((kv.Key, e / inStep.Count, dt / inStep.Count, inStep.Count));
            }
            int p = 0;
            if (peak.HasValue) { p = peak.Value; }
            else { double best = first; foreach (var st in steps) { if (st.Excess > best) { p = st.Step; best = st.Excess; } } }
            Dictionary<string, Row> atPeak = p == 0 ? post : (at.TryGetValue(p, out Dictionary<string, Row> dp) ? dp : new Dictionary<string, Row>());
            List<string> inPeak = units.Where(atPeak.ContainsKey).ToList();
            double jump = first, dtp = 0;
            if (p != 0) { foreach (var st in steps) { if (st.Step == p) { jump = st.Excess; dtp = st.Dt; } } }
            var after = steps.Where(st => st.Step > p).Select(st => (st.Step, st.Excess, st.Dt - dtp, st.In)).ToList();
            (double lambda, int edge) = Decay(jump, after);
            double lb = edge == 0 ? lambda : 0.0, back = 0, lag = 0;
            foreach (string u in inPeak) { double d = atPeak[u].Date - post[u].Event; back += (atPeak[u].Share - pre[u].Share) * Math.Exp(lb * d); lag += d; }
            back /= inPeak.Count; lag /= inPeak.Count;
            double firstLag = 0; foreach (string u in units) { firstLag += post[u].Date - post[u].Event; } firstLag /= units.Count;   // K94: the event to the first wave, where the ramp starts
            return new Fit { Units = units, Jump = jump, First = first, FirstLag = firstLag, Peak = p, Lambda = lambda, Edge = edge, Back = back, Lag = lag, Pre = pre, Post = post, AtPeak = atPeak };
        }

        /// <summary>The tool's `decay`: the grid's best rate, refined by golden section between its neighbours; the edge flags as the tool's.</summary>
        private static (double, int) Decay(double j, List<(int Step, double Excess, double Dt, int In)> steps)
        {
            if (!(j > 0) || steps.Count == 0) { return (0, -1); }
            double Sse(double l) { double s = 0; foreach (var st in steps) { double d = st.Excess - j * Math.Exp(-l * st.Dt); s += d * d; } return s; }
            double Grid(int i) => EventSalienceFit.LambdaLow * Math.Pow(EventSalienceFit.LambdaHigh / EventSalienceFit.LambdaLow, (double)i / EventSalienceFit.GridPoints);
            double best = double.NaN; int bi = 0;
            for (int i = 0; i <= EventSalienceFit.GridPoints; i++) { double s = Sse(Grid(i)); if (double.IsNaN(best) || s < best) { best = s; bi = i; } }
            if (bi == 0 || bi == EventSalienceFit.GridPoints) { return (Grid(bi), bi == 0 ? -1 : 1); }
            double a = Grid(bi - 1), b = Grid(bi + 1), g = (Math.Sqrt(5) - 1) / 2;
            double c = b - g * (b - a), d2 = a + g * (b - a), fc = Sse(c), fd = Sse(d2);
            for (int it = 0; it < 100; it++)
            {
                if (fc < fd) { b = d2; d2 = c; fd = fc; c = b - g * (b - a); fc = Sse(c); }
                else { a = c; c = d2; fc = fd; d2 = a + g * (b - a); fd = Sse(d2); }
            }
            double lambda = (a + b) / 2, first = steps.Min(st => st.Dt);
            return (lambda, j * Math.Exp(-lambda * first) < EventSalienceFit.Resolution ? 1 : 0);
        }

        private static double JackSe(List<double> v)
        {
            double m = v.Average(), ss = 0; foreach (double x in v) { ss += (x - m) * (x - m); }
            return Math.Sqrt((v.Count - 1) / (double)v.Count * ss);
        }

        /// <summary>P(|T| &lt; t) for Student's t with integer <paramref name="nu"/> degrees of freedom (Abramowitz &amp; Stegun 26.7.3-4), the tool's.</summary>
        private static double TwoSided(double t, int nu)
        {
            double th = Math.Atan2(t, Math.Sqrt(nu)), s = Math.Sin(th), c = Math.Cos(th), sum = 1, term = 1;
            const double pi = 3.141592653589793;   // DERIVED: the tool's own figure for pi, so both evaluate one series
            if (nu % 2 == 1)
            {
                if (nu == 1) { return 2 * th / pi; }
                for (int k = 2; k <= nu - 3; k += 2) { term *= (double)k / (k + 1) * c * c; sum += term; }
                return 2 / pi * (th + s * c * sum);
            }
            for (int k = 1; k <= nu - 3; k += 2) { term *= (double)k / (k + 1) * c * c; sum += term; }
            return s * sum;
        }

        private static double Tq(int nu) { double lo = 0, hi = 1000; for (int i = 0; i < 200; i++) { double m = (lo + hi) / 2; if (TwoSided(m, nu) < 0.95) { lo = m; } else { hi = m; } } return (lo + hi) / 2; }

