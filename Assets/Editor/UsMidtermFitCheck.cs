    /// <summary>
    /// PS-6 US-27 - R-US20 RULED (b) (Elias's ruling I4, `COMPLETED.md` §856: "a FITTED midterm term on the president's party from the record since 1946, with n
    /// and its interval printed"): <b>the midterm term is the fit</b>. Re-reads US-13's record (`ElectionsData/usa/house_midterms.csv`, its digest over its text
    /// with LF line ends held against the one `Generated.UsMidtermTerm` carries), refits the term exactly as `Tools/us_midterm_fit.pl` defines it - every midterm
    /// 1946-2022, the president's party's swing in the SECONDARY column (Vital Statistics' change of the major-party vote, signed for that party), its mean and
    /// the 95 % interval of the mean on Student's t (the quantile by bisection on the regularised incomplete beta) - and the Clerk's own swing 2002-2022 beside;
    /// and fails while the generated constants are not the fit (the count exact, every figure within one part in a million million), or while the count does not
    /// read it (`UsCongressElection.MidtermTermPoints`). THE TEETH, every run: the t quantile against two values of the table it is computed for (planted:
    /// 2.0930240544 at 19 degrees of freedom and 2.5705818356 at 5, held to 1e-9), a swing's sign planted reversed moving the mean, and a planted digest refused.
    /// A stale constant is regenerated by the tool, never retyped: `perl Tools/us_midterm_fit.pl`. Prints `US MIDTERM FIT: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class UsMidtermFitCheck
    {
        private const string CsvRelative = "ElectionsData/usa/house_midterms.csv";
        private const double Relative = 1e-12;

        /// <summary>One midterm of the record as the fit reads it.</summary>
        internal sealed class Row
        {
            public int Year;
            public string Party;
            public string Government;
            public double Secondary;
            public double Clerk = double.NaN;
            public int SeatChange;
        }

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== UsMidtermFitCheck (PS-6 US-27, R-US20 (b)): the midterm term refit on US-13's record ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("US MIDTERM FIT: FAIL - " + what); }
            }
            try
            {
                string text = ReadRecord(out string digest);
                Check(digest == UsMidtermTerm.SourceDigest, F("{0} sha256 {1} (its text with LF line ends) is the digest the generated constants carry ({2})", CsvRelative, digest, UsMidtermTerm.SourceDigest));
                List<Row> rows = Midterms(text);
                Fit(rows.Select(r => r.Secondary).ToList(), out int n, out double mean, out double sd, out double t, out double lo, out double hi);
                Fit(rows.Where(r => !double.IsNaN(r.Clerk)).Select(r => r.Clerk).ToList(), out int cn, out double cmean, out double _, out double ct, out double clo, out double chi);
                List<Row> unified = rows.Where(r => r.Government == "unified").ToList(), divided = rows.Where(r => r.Government == "divided").ToList();
                double umean = unified.Sum(r => r.Secondary / unified.Count), dmean = divided.Sum(r => r.Secondary / divided.Count), smean = rows.Sum(r => (double)r.SeatChange / rows.Count);
                foreach (Row r in rows)
                {
                    sb.Append(F("      {0} {1} {2,-8} SECONDARY {3:+0.0;-0.0} the Clerk {4} seats {5:+0;-0}\n", r.Year, r.Party, r.Government, r.Secondary,
                        double.IsNaN(r.Clerk) ? "-" : r.Clerk.ToString("+0.0000;-0.0000", CultureInfo.InvariantCulture), r.SeatChange));
                }
                sb.Append(F("    THE TERM: n {0} midterms {1}-{2} (SECONDARY); mean {3:F6} pp, sd {4:F6}, t(0.975, {5}) {6:F9}; 95 % interval of the mean {7:F6} to {8:F6} pp\n",
                    n, UsMidtermTerm.From, UsMidtermTerm.To, mean, sd, n - 1, t, lo, hi));
                sb.Append(F("    beside: the Clerk n {0}, mean {1:F6} pp, 95 % interval {2:F6} to {3:F6} (t {4:F9}); unified n {5} mean {6:F4}, divided n {7} mean {8:F4}; seat change n {9} mean {10:F4}\n",
                    cn, cmean, clo, chi, ct, unified.Count, umean, divided.Count, dmean, rows.Count, smean));
                Check(n == UsMidtermTerm.N && rows.Select(r => r.Year).SequenceEqual(UsMidtermTerm.Years) && rows.Select(r => r.Secondary).SequenceEqual(UsMidtermTerm.SwingPoints)
                      && Near(mean, UsMidtermTerm.MeanPoints) && Near(sd, UsMidtermTerm.SdPoints) && Near(t, UsMidtermTerm.TQuantile) && Near(lo, UsMidtermTerm.LowerPoints) && Near(hi, UsMidtermTerm.UpperPoints),
                    F("the stored term is the fit: n {0} (stored {1}), mean {2:R} (stored {3:R}), interval {4:R} to {5:R} (stored {6:R} to {7:R}); a stale one is regenerated: perl Tools/us_midterm_fit.pl",
                        n, UsMidtermTerm.N, mean, UsMidtermTerm.MeanPoints, lo, hi, UsMidtermTerm.LowerPoints, UsMidtermTerm.UpperPoints));
                Check(cn == UsMidtermTerm.ClerkN && Near(cmean, UsMidtermTerm.ClerkMeanPoints) && Near(clo, UsMidtermTerm.ClerkLowerPoints) && Near(chi, UsMidtermTerm.ClerkUpperPoints)
                      && unified.Count == UsMidtermTerm.UnifiedN && divided.Count == UsMidtermTerm.DividedN && rows.Count == UsMidtermTerm.SeatN
                      && Near(umean, UsMidtermTerm.UnifiedMeanPoints) && Near(dmean, UsMidtermTerm.DividedMeanPoints) && Near(smean, UsMidtermTerm.SeatChangeMean),
                    F("the figures printed beside are the record's: the Clerk n {0}, unified n {1}, divided n {2}, seats n {3}", cn, unified.Count, divided.Count, rows.Count));
                Check(UsCongressElection.MidtermTermPoints == UsMidtermTerm.MeanPoints && lo < UsCongressElection.MidtermTermPoints && UsCongressElection.MidtermTermPoints < hi,
                    F("the count reads the fit: UsCongressElection.MidtermTermPoints {0:R} = the mean, inside its own interval", UsCongressElection.MidtermTermPoints));

                // THE TEETH
                Check(Math.Abs(TInverse(0.975, 19) - 2.0930240544) < 1e-9 && Math.Abs(TInverse(0.975, 5) - 2.5705818356) < 1e-9,
                    F("planted: Student's t at 0.975 is 2.0930240544 on 19 degrees of freedom and 2.5705818356 on 5 - computed {0:F10} and {1:F10}", TInverse(0.975, 19), TInverse(0.975, 5)));
                var flipped = rows.Select(r => r.Secondary).ToList();
                flipped[0] = -flipped[0];
                Fit(flipped, out int _, out double flippedMean, out double _, out double _, out double _, out double _);
                Check(!Near(flippedMean, UsMidtermTerm.MeanPoints), F("planted: the first midterm's sign reversed moves the mean ({0:F6} against {1:F6}) - the comparison has teeth", flippedMean, UsMidtermTerm.MeanPoints));
                Check(Sha(text + "\n") != UsMidtermTerm.SourceDigest, "planted: one byte more in the record gives another digest, which the check would refuse");
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "US MIDTERM FIT: PASS - the record is the one the term was fitted on, and the count reads its fit." : F("US MIDTERM FIT: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }

        /// <summary>The record's text with LF line ends, and its digest.</summary>
        internal static string ReadRecord(out string digest)
        {
            string text = File.ReadAllText(Path.Combine(Application.dataPath, "..", CsvRelative), new UTF8Encoding(false)).Replace("\r\n", "\n");
            digest = Sha(text);
            return text;
        }

        /// <summary>The midterms 1946-2022 as `Tools/us_midterm_fit.pl` reads them: the president's party, the government on the day (the House the election two
        /// years before chose and the Senate sitting), the SECONDARY swing signed for the president's party, the Clerk's swing where both elections carry it,
        /// and [HH-DIV]'s seat change.</summary>
        internal static List<Row> Midterms(string text)
        {
            string[] head = null;
            var byYear = new Dictionary<int, Dictionary<string, string>>();
            var years = new List<int>();
            foreach (string line in text.Split('\n'))
            {
                if (line.Length == 0 || line[0] == '#') { continue; }
                string[] f = line.Split(',');
                if (head == null) { head = f; continue; }
                if (f.Length != head.Length) { throw new FormatException(F("a row of {0} fields under a header of {1}", f.Length, head.Length)); }
                var h = new Dictionary<string, string>();
                for (int i = 0; i < f.Length; i++) { h[head[i]] = f[i]; }
                int y = int.Parse(h["year"], CultureInfo.InvariantCulture);
                byYear[y] = h;
                years.Add(y);
            }
            int I(string s) => int.Parse(s, CultureInfo.InvariantCulture);
            double D(string s) => double.Parse(s, CultureInfo.InvariantCulture);
            var rows = new List<Row>();
            foreach (int y in years)
            {
                Dictionary<string, string> r = byYear[y];
                if (r["kind"] != "midterm" || y < UsMidtermTerm.From || y > UsMidtermTerm.To) { continue; }
                string p = r["president_party"];
                if (p != "D" && p != "R") { throw new FormatException(F("{0}: the president's party '{1}' is neither D nor R", y, p)); }
                Dictionary<string, string> b = byYear[y - 2];
                string houseMajor = I(b["seats_r"]) > I(b["seats_d"]) ? "R" : I(b["seats_d"]) > I(b["seats_r"]) ? "D" : "-";
                var row = new Row
                {
                    Year = y, Party = p, Government = houseMajor == p && r["senate_majority"] == p ? "unified" : "divided",
                    Secondary = (r["vs_vote_direction"] == p ? 1 : -1) * D(r["vs_vote_change"]),
                    SeatChange = p == "R" ? I(r["seats_r"]) - I(b["seats_r"]) : I(r["seats_d"]) - I(b["seats_d"]),
                };
                if (r["clerk_r"] != "-" && b["clerk_r"] != "-")
                {
                    double after = (p == "R" ? D(r["clerk_r"]) : D(r["clerk_d"])) / (D(r["clerk_r"]) + D(r["clerk_d"]));
                    double before = (p == "R" ? D(b["clerk_r"]) : D(b["clerk_d"])) / (D(b["clerk_r"]) + D(b["clerk_d"]));
                    row.Clerk = 100.0 * (after - before);
                }
                rows.Add(row);
            }
            return rows;
        }

        /// <summary>The intercept fit: n, the mean, the sample sd, Student's t at 0.975 on n - 1 degrees of freedom and the 95 % interval of the mean.</summary>
        internal static void Fit(List<double> v, out int n, out double mean, out double sd, out double t, out double lo, out double hi)
        {
            n = v.Count;
            if (n < 2) { throw new InvalidOperationException("a fit of fewer than two observations"); }
            double sum = 0.0;
            foreach (double x in v) { sum += x; }
            mean = sum / n;
            double ss = 0.0;
            foreach (double x in v) { ss += (x - mean) * (x - mean); }
            sd = Math.Sqrt(ss / (n - 1));
            t = TInverse(0.975, n - 1);
            double half = t * sd / Math.Sqrt(n);
            lo = mean - half;
            hi = mean + half;
        }

        // ---- Student's t, as the tool computes it: ln Gamma by Lanczos (g = 7, nine terms - CONVENTION, the published coefficients), the regularised
        // incomplete beta by its continued fraction (Lentz), the quantile by bisection

        private static readonly double[] Lanczos = { 0.99999999999980993, 676.5203681218851, -1259.1392167224028, 771.32342877765313, -176.61502916214059,
            12.507343278686905, -0.13857109526572012, 9.9843695780195716e-6, 1.5056327351493116e-7 };

        private static double LnGamma(double x)
        {
            if (x < 0.5) { return Math.Log(Math.PI / Math.Abs(Math.Sin(Math.PI * x))) - LnGamma(1.0 - x); }
            x -= 1.0;
            double a = Lanczos[0], t = x + 7.5;
            for (int i = 1; i < 9; i++) { a += Lanczos[i] / (x + i); }
            return 0.5 * Math.Log(2.0 * Math.PI) + (x + 0.5) * Math.Log(t) - t + Math.Log(a);
        }

        private static double BetaContinuedFraction(double a, double b, double x)
        {
            const double tiny = 1e-300, eps = 1e-16;
            double qab = a + b, qap = a + 1.0, qam = a - 1.0, c = 1.0, d = 1.0 - qab * x / qap;
            if (Math.Abs(d) < tiny) { d = tiny; }
            d = 1.0 / d;
            double h = d;
            for (int m = 1; m <= 10000; m++)
            {
                int m2 = 2 * m;
                double aa = m * (b - m) * x / ((qam + m2) * (a + m2));
                d = 1.0 + aa * d; if (Math.Abs(d) < tiny) { d = tiny; }
                c = 1.0 + aa / c; if (Math.Abs(c) < tiny) { c = tiny; }
                d = 1.0 / d; h *= d * c;
                aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2));
                d = 1.0 + aa * d; if (Math.Abs(d) < tiny) { d = tiny; }
                c = 1.0 + aa / c; if (Math.Abs(c) < tiny) { c = tiny; }
                d = 1.0 / d;
                double del = d * c;
                h *= del;
                if (Math.Abs(del - 1.0) < eps) { return h; }
            }
            throw new InvalidOperationException("the incomplete beta's continued fraction did not converge");
        }

        private static double IncompleteBeta(double a, double b, double x)
        {
            if (x <= 0.0) { return 0.0; }
            if (x >= 1.0) { return 1.0; }
            double bt = Math.Exp(LnGamma(a + b) - LnGamma(a) - LnGamma(b) + a * Math.Log(x) + b * Math.Log(1.0 - x));
            return x < (a + 1.0) / (a + b + 2.0) ? bt * BetaContinuedFraction(a, b, x) / a : 1.0 - bt * BetaContinuedFraction(b, a, 1.0 - x) / b;
        }

        private static double TCdf(double t, double nu)
        {
            double tail = 0.5 * IncompleteBeta(nu / 2.0, 0.5, nu / (nu + t * t));
            return t >= 0.0 ? 1.0 - tail : tail;
        }

        internal static double TInverse(double p, double nu)
        {
            double lo = 0.0, hi = 1000.0;
            for (int i = 0; i < 200; i++) { double mid = 0.5 * (lo + hi); if (TCdf(mid, nu) < p) { lo = mid; } else { hi = mid; } }
            return 0.5 * (lo + hi);
        }

        private static bool Near(double a, double b) => Math.Abs(a - b) <= Relative * Math.Max(1.0, Math.Abs(b));

        internal static string Sha(string text)
        {
            using (var sha = SHA256.Create()) { return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(text))).Replace("-", string.Empty).ToLowerInvariant(); }
        }

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);
    }
