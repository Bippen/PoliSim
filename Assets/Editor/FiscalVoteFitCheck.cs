using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using PoliSim.Elections.Generated;
using UnityEngine;

namespace PoliSim.EditorTools
{
    /// <summary>
    /// A-LOOP q13 (2026-10-19, `docs/specs/A_LOOP_PLAN.md` §4 (3)): <b>sigma_v is the fit</b>. Re-reads the stored ParlGov election and cabinet tables
    /// (`docs/reference/raw/aloop/parlgov/`), holds each against its folder's `SHA256SUMS.txt` and against the digests the generated constants carry,
    /// refits sigma_v exactly as `Tools/aloop_sigma_fit.pl` defines it - over the frame the generated file names (its countries, its dates): one
    /// observation per parliamentary election, the prime minister's party of the cabinet in office at it (`previous_cabinet_id`), its vote share there
    /// less its share at the election before (`previous_parliament_election_id`) - and fails while `Generated.IncumbentVoteSwing` is not the fit
    /// (the count exact, every figure within one part in a million million). Prints n, the mean swing, sigma_v and its 95 % interval, and the
    /// observations per country. A stale constant is regenerated by the tool, never retyped: `perl Tools/aloop_sigma_fit.pl`.
    /// Prints `FISCAL VOTE FIT: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class FiscalVoteFitCheck
    {
        private const string Folder = "docs/reference/raw/aloop/parlgov/";
        private const double Relative = 1e-12;

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== FiscalVoteFitCheck (A-LOOP q13): sigma_v refit on the stored ParlGov tables ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("FISCAL VOTE FIT: FAIL - " + what); }
            }
            try
            {
                string sums = File.ReadAllText(PathOf(Folder + "SHA256SUMS.txt"), Encoding.ASCII).Replace("\r\n", "\n");
                byte[] electionBytes = File.ReadAllBytes(PathOf(Folder + "view_election.csv")), cabinetBytes = File.ReadAllBytes(PathOf(Folder + "view_cabinet.csv"));
                string electionDigest = Sha(electionBytes), cabinetDigest = Sha(cabinetBytes);
                Check(sums.Split('\n').Contains(electionDigest + " *view_election.csv") && electionDigest == IncumbentVoteSwing.ElectionDigest,
                    F("view_election.csv {0}: listed in SHA256SUMS.txt and the digest the generated constants carry", electionDigest));
                Check(sums.Split('\n').Contains(cabinetDigest + " *view_cabinet.csv") && cabinetDigest == IncumbentVoteSwing.CabinetDigest,
                    F("view_cabinet.csv {0}: listed in SHA256SUMS.txt and the digest the generated constants carry", cabinetDigest));

                List<Dictionary<string, string>> elections = Csv(Encoding.UTF8.GetString(electionBytes)), cabinets = Csv(Encoding.UTF8.GetString(cabinetBytes));
                var pmParty = new Dictionary<string, HashSet<string>>();
                foreach (Dictionary<string, string> c in cabinets)
                {
                    if (c["prime_minister"] != "1") { continue; }
                    if (!pmParty.TryGetValue(c["cabinet_id"], out HashSet<string> set)) { pmParty[c["cabinet_id"]] = set = new HashSet<string>(); }
                    set.Add(c["party_id"]);
                }
                var share = new Dictionary<string, Dictionary<string, string>>();
                var elec = new Dictionary<string, (string Country, string Date, string Prev, string Cabinet)>();
                foreach (Dictionary<string, string> e in elections)
                {
                    if (e["election_type"] != "parliament") { continue; }
                    string id = e["election_id"];
                    if (!share.TryGetValue(id, out Dictionary<string, string> byParty)) { share[id] = byParty = new Dictionary<string, string>(); }
                    byParty[e["party_id"]] = e["vote_share"];
                    if (!elec.ContainsKey(id)) { elec[id] = (e["country_name_short"], e["election_date"], e["previous_parliament_election_id"], e["previous_cabinet_id"]); }
                }
                var frame = new HashSet<string>(IncumbentVoteSwing.Countries);
                var swings = new List<double>();
                var perCountry = new SortedDictionary<string, int>(StringComparer.Ordinal);
                var leftOut = new SortedDictionary<string, int>(StringComparer.Ordinal);
                foreach (KeyValuePair<string, (string Country, string Date, string Prev, string Cabinet)> kv in elec
                    .OrderBy(kv => kv.Value.Country, StringComparer.Ordinal).ThenBy(kv => kv.Value.Date, StringComparer.Ordinal).ThenBy(kv => long.Parse(kv.Key, CultureInfo.InvariantCulture)))
                {
                    var e = kv.Value;
                    if (!frame.Contains(e.Country) || string.CompareOrdinal(e.Date, IncumbentVoteSwing.From) < 0 || string.CompareOrdinal(e.Date, IncumbentVoteSwing.To) > 0) { continue; }
                    List<string> pm = pmParty.TryGetValue(e.Cabinet, out HashSet<string> s) ? s.OrderBy(p => long.Parse(p, CultureInfo.InvariantCulture)).ToList() : new List<string>();
                    if (pm.Count != 1) { Count(leftOut, pm.Count == 0 ? "no prime minister's party in the cabinet in office" : "more than one prime minister's party"); continue; }
                    string now = share[kv.Key].TryGetValue(pm[0], out string n1) ? n1 : null;
                    string then = e.Prev != "" && share.TryGetValue(e.Prev, out Dictionary<string, string> prev) && prev.TryGetValue(pm[0], out string n0) ? n0 : null;
                    if (now == null || then == null) { Count(leftOut, "the party has no share at one of the two elections under its own id"); continue; }
                    if (now == "" || then == "") { Count(leftOut, "an empty share"); continue; }
                    swings.Add(double.Parse(now, CultureInfo.InvariantCulture) - double.Parse(then, CultureInfo.InvariantCulture));
                    Count(perCountry, e.Country);
                }
                int count = swings.Count;
                double sum = 0.0;
                foreach (double x in swings) { sum += x; }
                double mean = sum / count, ss = 0.0;
                foreach (double x in swings) { ss += (x - mean) * (x - mean); }
                double sd = Math.Sqrt(ss / (count - 1));
                int k = count - 1;
                const double z = 1.959963984540054;   // DERIVED: the normal's 97.5 % point, the tool's
                double Chi2(double zp) { double a = 2.0 / (9.0 * k); return k * Math.Pow(1.0 - a + zp * Math.Sqrt(a), 3); }
                double lo = sd * Math.Sqrt(k / Chi2(z)), hi = sd * Math.Sqrt(k / Chi2(-z));
                sb.Append(F("    SIGMA_V: n {0} elections in {1} countries ({2} to {3}); mean swing {4:F4} pp; sigma_v {5:F6} pp; 95 % interval {6:F6} - {7:F6} pp\n",
                    count, perCountry.Count, IncumbentVoteSwing.From, IncumbentVoteSwing.To, mean, sd, lo, hi));
                sb.Append("      " + string.Join(", ", perCountry.Select(p => p.Key + " " + p.Value)) + "\n");
                foreach (KeyValuePair<string, int> o in leftOut) { sb.Append(F("      left out: {0} {1}\n", o.Key, o.Value)); }
                Check(count == IncumbentVoteSwing.N && Near(mean, IncumbentVoteSwing.MeanPoints) && Near(sd, IncumbentVoteSwing.SigmaPoints)
                      && Near(lo, IncumbentVoteSwing.SigmaLowerPoints) && Near(hi, IncumbentVoteSwing.SigmaUpperPoints),
                    F("the stored constants are the fit: n {0} (stored {1}), sigma_v {2:R} (stored {3:R}), interval {4:R} - {5:R} (stored {6:R} - {7:R}), mean {8:R} (stored {9:R}); a stale one is regenerated: perl Tools/aloop_sigma_fit.pl",
                        count, IncumbentVoteSwing.N, sd, IncumbentVoteSwing.SigmaPoints, lo, hi, IncumbentVoteSwing.SigmaLowerPoints, IncumbentVoteSwing.SigmaUpperPoints, mean, IncumbentVoteSwing.MeanPoints));
                Check(Math.Abs(PoliSim.Elections.FiscalVote.SwingSpread - IncumbentVoteSwing.SigmaPoints / 100.0) == 0.0,
                    F("the vote reads the fit (FiscalVote.SwingSpread {0:R} = sigma_v / 100)", PoliSim.Elections.FiscalVote.SwingSpread));
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "FISCAL VOTE FIT: PASS - the stored ParlGov tables are the ones listed, and sigma_v is their fit." : F("FISCAL VOTE FIT: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }

        private static bool Near(double a, double b) => Math.Abs(a - b) <= Relative * Math.Max(1.0, Math.Abs(b));

        private static void Count(IDictionary<string, int> tally, string key) => tally[key] = tally.TryGetValue(key, out int n) ? n + 1 : 1;

        /// <summary>RFC 4180: quoted fields, doubled quotes; a CR before a LF dropped. Each row keyed by the header; a row of another width throws.</summary>
        private static List<Dictionary<string, string>> Csv(string text)
        {
            var rows = new List<List<string>>();
            var row = new List<string>();
            var field = new StringBuilder();
            bool quoted = false;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (quoted)
                {
                    if (c == '"') { if (i + 1 < text.Length && text[i + 1] == '"') { field.Append('"'); i++; } else { quoted = false; } }
                    else { field.Append(c); }
                    continue;
                }
                if (c == '"') { if (field.Length > 0) { throw new FormatException("a quote inside an unquoted field"); } quoted = true; }
                else if (c == ',') { row.Add(field.ToString()); field.Clear(); }
                else if (c == '\r') { }
                else if (c == '\n') { row.Add(field.ToString()); field.Clear(); rows.Add(row); row = new List<string>(); }
                else { field.Append(c); }
            }
            if (field.Length > 0 || row.Count > 0) { row.Add(field.ToString()); rows.Add(row); }
            if (quoted) { throw new FormatException("an unterminated quote"); }
            List<string> head = rows[0];
            var records = new List<Dictionary<string, string>>();
            for (int r = 1; r < rows.Count; r++)
            {
                if (rows[r].Count != head.Count) { throw new FormatException(F("row {0} has {1} fields under a header of {2}", r, rows[r].Count, head.Count)); }
                var rec = new Dictionary<string, string>(StringComparer.Ordinal);
                for (int i = 0; i < head.Count; i++) { rec[head[i]] = rows[r][i]; }
                records.Add(rec);
            }
            return records;
        }

        private static string Sha(byte[] bytes)
        {
            using (var sha = SHA256.Create()) { return BitConverter.ToString(sha.ComputeHash(bytes)).Replace("-", string.Empty).ToLowerInvariant(); }
        }

        private static string PathOf(string relative) => Path.Combine(Path.GetFullPath(Path.Combine(Application.dataPath, "..")), relative);

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);
    }
}
