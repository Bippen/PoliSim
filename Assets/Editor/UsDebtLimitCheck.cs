        /// <summary>The seed's US debt (a fresh default world, as every start creates it - the seed is one vintage per country, §621) against Treasury's
        /// perimeters at the seed's vintage.</summary>
        private static Bridge MeasureBridge(Record rec)
        {
            SimulationRandom.LiveState rng = SimulationRandom.CaptureLive();
            try
            {
                float seedBn = WorldFactory.CreateDefault().GetCountry(CountryId.USA).State.GovernmentDebt;
                decimal seedUsd = (decimal)(double)seedBn * 1000000000m;
                return new Bridge { SeedUsd = seedUsd, RatioDsl = rec.VintageDslUsd / seedUsd, RatioTpdo = rec.VintageTpdoUsd / seedUsd, RatioPublic = rec.VintagePublicUsd / seedUsd };
            }
            finally { SimulationRandom.Reinstate(rng); }
        }

        private static string EngineBlock(Bridge b, Record rec)
        {
            var s = new StringBuilder(EngineStamp).Append(" data-sha256: ").Append(rec.DataDigest).Append(" -->\n");
            s.Append(F("The game's US debt seed (`WorldFactory`, the USA's `GovernmentDebt` at creation, current prices): **{0}**.\n\n", Usd(b.SeedUsd)));
            s.Append(F("| Treasury's perimeter on {0:yyyy-MM-dd} (the seed's vintage) | USD | the seed less it | Treasury over the seed |\n|---|---:|---:|---:|\n", rec.VintageDate));
            s.Append(F("| debt subject to limit | {0} | {1} | {2} |\n", Usd(rec.VintageDslUsd), Usd(b.SeedUsd - rec.VintageDslUsd), Ratio(b.RatioDsl)));
            s.Append(F("| total public debt outstanding | {0} | {1} | {2} |\n", Usd(rec.VintageTpdoUsd), Usd(b.SeedUsd - rec.VintageTpdoUsd), Ratio(b.RatioTpdo)));
            s.Append(F("| debt held by the public | {0} | {1} | {2} |\n", Usd(rec.VintagePublicUsd), Usd(b.SeedUsd - rec.VintagePublicUsd), Ratio(b.RatioPublic)));
            s.Append(F("| debt subject to limit at the reinstatement (2 January 2025's opening) | {0} | {1} | {2} |\n\n", Usd(rec.ReinstatementDslUsd), Usd(b.SeedUsd - rec.ReinstatementDslUsd), Ratio(rec.ReinstatementDslUsd / b.SeedUsd)));
            s.Append(F("R-US21 (i)(a), the recommended bridge: debt subject to limit = the game's debt x {0} - the seed's own ratio to Treasury's debt subject to limit at the seed's vintage.\n", Ratio(b.RatioDsl)));
            return s.Append(EngineEnd).ToString();
        }

        private static string EngineBlockOf(string doc)
        {
            string text = doc.Replace("\r\n", "\n");
            int start = text.IndexOf(EngineStamp, StringComparison.Ordinal);
            int end = start < 0 ? -1 : text.IndexOf(EngineEnd, start, StringComparison.Ordinal);
            return end < 0 ? null : text.Substring(start, end + EngineEnd.Length - start);
        }

