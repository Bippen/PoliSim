        /// <summary>One reading of R-US21 (iii): a span in days after the reach, or a dollar headroom above the limit.</summary>
        private sealed class Span { public string Name; public int Days = -1; public double HeadroomUsd = -1; }

        /// <summary>One (bridge, law) pair's walk through a run: the first reach, the episodes' reliefs, the first binding day under each span.</summary>
        private sealed class Walk
        {
            public string Law;                      // "(ii)(a)" or "(ii)(b)"
            public string LawAtStart;
            public DateTime? EpisodeStart;
            public bool Reached;
            public readonly List<string> Events = new List<string>();   // every reach (with how far over the limit it lands) and every relief, in order
            public DateTime?[] Binds;
            public double? ReinstatedUsd;          // (ii)(a) from a suspended start: the game's own limit on 2 January 2025
            public bool Resolved => Binds.All(b => b.HasValue);
        }

        private static void MeasureDates(Record rec, Bridge bridge, StringBuilder sb, Action<bool, string> Check)
        {
            var spans = new[]
            {
                new Span { Name = F("+{0}d (the record's measures, as used)", rec.EmDaysUsed), Days = rec.EmDaysUsed },
                new Span { Name = F("+{0}d (to the projected exhaustion of cash AND measures, its first day)", rec.EmDaysToExhaustionFrom), Days = rec.EmDaysToExhaustionFrom },
                new Span { Name = F("+{0}d (cash AND measures, its last day)", rec.EmDaysToExhaustionTo), Days = rec.EmDaysToExhaustionTo },
                new Span { Name = F("+{0} (the measures' size)", Tn((double)rec.EmTotalMeasuresUsd)), HeadroomUsd = (double)rec.EmTotalMeasuresUsd },
            };
            decimal latest = rec.Laws.Last(l => l.LimitUsd.HasValue).LimitUsd.Value;
            sb.Append(F("    read      THE DATES. The limit by date (the record, R-US21 (ii)(b)): {0}. Spans after the reach (iii): {1} - the August projection is of Treasury's cash balance and the measures together, and the game holds no cash balance, so those two spans count days the cash bought as well. Debt subject to limit = the game's debt x {2} under (i)(a); under (i)(b) the US debt re-seeded to {3} (the seed's ratio, its comfort anchor and the ministry's memory re-read from it - the re-seed as WorldFactory's own rule would carry it).\n",
                string.Join("; ", rec.Laws.Select(l => F("{0:yyyy-MM-dd} {1}", l.From, l.LimitUsd.HasValue ? Usd(l.LimitUsd.Value) : "suspended"))), string.Join(", ", spans.Select(s => s.Name)), Ratio(bridge.RatioDsl), Usd(rec.VintageDslUsd)));
            sb.Append("    read      CRS IF10292 v22 (21 Sep 2026, ElectionsData/usa/debt_limit.md s4): outside projections from June 2026 put debt reaching the limit in \"early to mid-2027\", the measures delaying a binding limit \"by another several months\" - the record's distance from the seed's season, beside each start's SEED-TO-LIMIT.\n");
            DateTime epochBefore = SimulationManager.EpochDate;
            SimulationRandom.LiveState rng = SimulationRandom.CaptureLive();
            try
            {
                foreach (CountryId start in Starts)
                {
                    foreach (bool reseed in new[] { false, true })
                    {
                        RunStart(start, reseed, rec, bridge, spans, latest, sb, Check);
                    }
                }
            }
            finally { SimulationRandom.Reinstate(rng); }
            Check(SimulationManager.EpochDate == epochBefore, F("the epoch is put back after the runs ({0:yyyy-MM-dd})", SimulationManager.EpochDate));
        }

        private static void RunStart(CountryId player, bool reseed, Record rec, Bridge bridge, Span[] spans, decimal latest, StringBuilder sb, Action<bool, string> Check)
        {
            string bridgeName = reseed ? "(i)(b)" : "(i)(a)";
            SimulationRandom.Seed(NoPolicyCentury.Seed);
            using (SimulationManager.EpochScope())
            {
                WorldClock.ApplyStart(player);
                DateTime start = SimulationManager.EpochDate;
                World world = WorldFactory.CreateDefault();
                Country usa = world.GetCountry(CountryId.USA);
                if (reseed)
                {
                    usa.State.GovernmentDebt = (float)(double)(rec.VintageDslUsd / 1000000000m);
                    usa.DebtRatioSeed = usa.State.DebtToGdpRatio;
                    usa.ComfortableDebtToGdpPercent = usa.State.DebtToGdpRatio;
                    usa.ComfortableDebtToGdpPercentBase = usa.ComfortableDebtToGdpPercent;
                }
                double ratio = reseed ? 1.0 : (double)bridge.RatioDsl;
                double Dsl() => usa.State.GovernmentDebt * 1e9 * ratio;
                bool usaIsPlayer = player == CountryId.USA;
                var go = new GameObject("USDEBTLIMIT");
                try
                {
                    SimulationManager sim = go.AddComponent<SimulationManager>();
                    sim.SetWorld(world);
                    sim.PlayerCountryId = player;
                    var decisions = new Dictionary<CountryId, PolicyDecision>();
                    foreach (Country k in world.Countries) { decisions[k.Id] = PolicyDecision.None(); }

                    double dsl0 = Dsl();
                    // NOT A TEST OF THE RECORD in either bridge. Under (i)(b) it is true by construction - the re-seed sets the figure. Under (i)(a) the ratio
                    // was read from a world built outside any start's epoch (MeasureBridge) and is applied here to the world this start built: it holds only
                    // if the seed does not depend on the start - §621's one seed vintage per country - and that is what it tests. The line says which
                    Check(start == WorldClock.StartDate(player) && sim.CurrentDate == start && Math.Abs(dsl0 - (double)rec.VintageDslUsd) < 5e6,
                        F("{0} {1}: the run opens on the start {2:yyyy-MM-dd} with debt subject to limit {3} - the record's at the seed's vintage, within the float's resolution ({4}; not a test of the record)", player, bridgeName, start, Tn(dsl0),
                            reseed ? "the re-seed applied - true by construction" : "the bridge's ratio applied - the seed the same on this start as outside any, as §621's one seed per country holds"));

                    Law atStart = InForce(rec.Laws, start);
                    Law reinstatement = rec.Laws.FirstOrDefault(l => l.LimitUsd.HasValue && l.From > atStart.From && !atStart.LimitUsd.HasValue);
                    var walks = new[]
                    {
                        new Walk { Law = "(ii)(a)", LawAtStart = atStart.LimitUsd.HasValue ? Usd(atStart.LimitUsd.Value) + " (" + atStart.Act + ")" : "suspended (" + atStart.Act + ")", Binds = new DateTime?[spans.Length] },
                        new Walk { Law = "(ii)(b)", LawAtStart = atStart.LimitUsd.HasValue ? Usd(atStart.LimitUsd.Value) + " (" + atStart.Act + ")" : "suspended (" + atStart.Act + ")", Binds = new DateTime?[spans.Length] },
                    };
                    // (ii)(a): the law in force at the start, later acts the game's Congress's (none passes on this path); a suspended start is reinstated on the
                    // statute's day at the game's own debt subject to limit at the end of the previous day, plus the headroom s401(b) carried
                    double? LimitA(DateTime d, double dslYesterday, Walk w)
                    {
                        if (atStart.LimitUsd.HasValue) { return (double)atStart.LimitUsd.Value; }
                        if (reinstatement == null || d < reinstatement.From) { return null; }
                        if (!w.ReinstatedUsd.HasValue) { w.ReinstatedUsd = dslYesterday + (double)rec.HeadroomUsd; }
                        return w.ReinstatedUsd;
                    }
                    double? LimitB(DateTime d) { Law l = InForce(rec.Laws, d); return l.LimitUsd.HasValue ? (double?)(double)l.LimitUsd.Value : null; }

                    DateTime? seedToLimit = null;
                    double yesterday = dsl0;
                    void Evaluate(DateTime d)
                    {
                        double dsl = Dsl();
                        if (!seedToLimit.HasValue && dsl >= (double)latest) { seedToLimit = d; }
                        foreach (Walk w in walks)
                        {
                            double? limit = w.Law == "(ii)(a)" ? LimitA(d, yesterday, w) : LimitB(d);
                            bool over = limit.HasValue && dsl >= limit.Value;
                            if (over && !w.EpisodeStart.HasValue)
                            {
                                w.EpisodeStart = d;
                                w.Reached = true;
                                w.Events.Add(F("REACHED {0:yyyy-MM-dd} (over by {1}{2})", d, Tn(dsl - limit.Value), d == start ? ", the start day" : string.Empty));
                            }
                            else if (!over && w.EpisodeStart.HasValue) { w.Events.Add(F("relieved {0:yyyy-MM-dd} ({1})", d, limit.HasValue ? "the limit above the debt by " + Tn(limit.Value - dsl) : "the limit suspended")); w.EpisodeStart = null; }
                            if (!w.EpisodeStart.HasValue) { continue; }
                            for (int k = 0; k < spans.Length; k++)
                            {
                                if (w.Binds[k].HasValue) { continue; }
                                if (spans[k].Days >= 0 ? (d - w.EpisodeStart.Value).Days >= spans[k].Days : dsl >= limit.Value + spans[k].HeadroomUsd) { w.Binds[k] = d; }
                            }
                        }
                        yesterday = dsl;
                    }
                    Evaluate(start);

                    var ministry = new List<string>();
                    string firstFired = null;
                    FiscalTurnReport yearOne = null;
                    int years = 0;
                    for (int year = 1; year <= MaxYears; year++)
                    {
                        for (int day = 1; day < SimulationManager.DaysPerTurn; day++) { sim.AdvanceDay(); Evaluate(sim.CurrentDate); }
                        sim.AdvanceDay();
                        // (v) the ministry's rule on the boundary's eve, and whether its trigger fired, read from its own two-year memory after the turn
                        float seedRatio = usa.DebtRatioSeed, lastBefore = usa.DebtRatioLastReport, beforeBefore = usa.DebtRatioReportBefore, eveRatio = usa.State.DebtToGdpRatio;
                        float sequesterEve = 0f;
                        if (!usaIsPlayer && AiFinanceMinistry.UsTriggered(usa, eveRatio))
                        {
                            PolicyDecision eve = AiFinanceMinistry.Decide(usa, sim.GetLastFiscalReport(CountryId.USA));
                            foreach (SpendingLine line in usa.SpendingLines) { if (eve.SpendingLineChanges.TryGetValue(line.Category, out float pct) && pct < 0f) { sequesterEve += line.Amount * -pct / 100f; } }
                        }
                        DateTime boundary = sim.CurrentDate;
                        decisions[player] = PolicyDecision.None();
                        sim.AdvanceTurn(decisions);
                        Evaluate(boundary);
                        years = year;
                        if (year == 1) { yearOne = sim.GetLastFiscalReport(CountryId.USA); }
                        float newLast = usa.DebtRatioLastReport;
                        bool fired = seedRatio > 0f && newLast > seedRatio && lastBefore > 0f && newLast > lastBefore && beforeBefore > 0f && lastBefore > beforeBefore;
                        if (!usaIsPlayer)
                        {
                            double? limitThen = LimitB(boundary);
                            ministry.Add(F("{0:yyyy-MM-dd} {1:F1}%{2}", boundary, newLast, fired ? F(" FIRES (on the eve: sequester {0} = {1:F2}% of GDP; the limit of record (ii)(b) less the debt {2})", Tn(sequesterEve * 1e9), sequesterEve / usa.State.NominalGdp * 100f, limitThen.HasValue ? Tn(limitThen.Value - Dsl()) : "suspended") : string.Empty));
                            if (fired && firstFired == null) { firstFired = boundary.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture); }
                        }
                        bool resolved = walks.All(w => w.Resolved) && seedToLimit.HasValue;
                        if (resolved && (usaIsPlayer || reseed || year >= MinistryBoundaries)) { break; }
                    }

                    // the printed dates - each line quotable on its own
                    string role = usaIsPlayer ? "the USA the player - its book the instrument's hand, the AI ministry idle" : "the USA AI-governed - the ministry acting";
                    foreach (Walk w in walks)
                    {
                        string reach = w.Reached ? string.Join(" -> ", w.Events.Take(6)) + (w.Events.Count > 6 ? " -> ..." : string.Empty) : F("not reached by {0:yyyy-MM-dd}", sim.CurrentDate);
                        string binds = string.Join(" | ", spans.Select((s, k) => F("BINDS {0} {1}", s.Name, w.Binds[k].HasValue ? w.Binds[k].Value.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture) : "not by " + sim.CurrentDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))));
                        string reinstated = w.ReinstatedUsd.HasValue ? F(" (reinstated at the game's own {0} on {1:yyyy-MM-dd})", Usd((decimal)w.ReinstatedUsd.Value), reinstatement.From) : string.Empty;
                        sb.Append(F("    read      DATES {0} start {1:yyyy-MM-dd} | bridge {2} | law {3} | limit at the start {4}{5} | {6} | {7}\n", player, start, bridgeName, w.Law, w.LawAtStart, reinstated, reach, binds));
                    }
                    sb.Append(F("    read      SEED-TO-LIMIT {0} bridge {1}: the debt subject to limit reaches {2} {3}\n", player, bridgeName, Usd(latest),
                        seedToLimit.HasValue ? F("{0} days after the seed's state ({1:yyyy-MM-dd}; carried to the seed's own month-end {2:yyyy-MM-dd}: {3:yyyy-MM-dd})", (seedToLimit.Value - start).Days, seedToLimit, rec.VintageDate, rec.VintageDate.AddDays((seedToLimit.Value - start).Days)) : F("not within {0} years", years)));
                    if (yearOne != null)
                    {
                        float nonInterest = yearOne.TotalSpending - yearOne.InterestOnDebt;
                        sb.Append(F("    read      CUT {0} bridge {1}: the first year's balance {2} on non-interest outlays {3} - the pro-rata cut a binding limit asks (iv)(a): {4:F1}% of them\n", player, bridgeName,
                            Tn(yearOne.BudgetBalance * 1e9), Tn(nonInterest * 1e9), nonInterest > 0f ? -yearOne.BudgetBalance / nonInterest * 100f : 0f));
                    }
                    if (!reseed)
                    {
                        if (usaIsPlayer) { Check(usa.DebtRatioLastReport == 0f, F("{0}: the AI ministry never observed the USA ({1}) - its ratio-trend logic is idle on this start", player, role)); }
                        else
                        {
                            Check(usa.DebtRatioLastReport > 0f, F("{0}: the AI ministry observed the USA ({1})", player, role));
                            sb.Append(F("    read      MINISTRY {0} (v): the debt ratio's seed {1:F1}%, at each boundary {2}; {3}\n", player, usa.DebtRatioSeed, string.Join(", ", ministry),
                                firstFired == null ? F("the ratio-trend trigger does not fire within {0} boundaries", years) : "the ratio-trend trigger first fires on " + firstFired));
                        }
                    }
                }
                finally { Object.DestroyImmediate(go); }
            }
        }

        private static Law InForce(List<Law> laws, DateTime d)
        {
            Law inForce = null;
            foreach (Law l in laws) { if (l.From <= d) { inForce = l; } }
            if (inForce == null) { throw new InvalidOperationException(F("no limit on record for {0:yyyy-MM-dd} - the document's first step is {1:yyyy-MM-dd}", d, laws[0].From)); }
            return inForce;
        }

