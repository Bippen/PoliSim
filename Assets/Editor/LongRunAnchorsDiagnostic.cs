        /// <summary>A constant read by name, whatever its access - the check reads the figure the model reads.</summary>
        private static double Value(Type owner, string name)
        {
            FieldInfo field = owner.GetField(name, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static);
            if (field == null || !(field.IsLiteral || field.IsInitOnly)) { Check(false, F("{0}.{1} is not a constant or read-only figure here", owner.Name, name)); return double.NaN; }
            object raw = field.IsLiteral ? field.GetRawConstantValue() : field.GetValue(null);
            return raw is float f ? f : Convert.ToDouble(raw, CultureInfo.InvariantCulture);
        }

        /// <summary>K211: (d1) and (d2) are REGISTERED MISSES until K210 lands - a miss prints its figures under a named tag and does not fail the
        /// run (the K113/K114 pattern); every other departure still fails.</summary>
        private static void Registered(bool ok, string what)
        {
            if (ok) { _sb.Append("        ok   ").Append(what).Append('\n'); return; }
            _registered++;
            _sb.Append("        REGISTERED MISS (prereg 117aa45b; K210 to close) ").Append(what).Append('\n');
            Debug.Log("LONG-RUN ANCHORS: REGISTERED MISS (prereg 117aa45b; K210 to close) - " + what);
        }

        private static void Check(bool ok, string what)
        {
            _sb.Append(ok ? "        ok   " : "        FAIL ").Append(what).Append('\n');
            if (!ok) { _failures++; Debug.LogError("LONG-RUN ANCHORS: FAIL - " + what); }
        }

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);
