        // ============================================================ (a1) the calibration
        private static void Calibration()
        {
            _sb.Append("    a1. the calibrated seed schedule reads each country's sourced life expectancy\n");
            World world = SeededWorld();
            foreach (CountryId id in Six)
            {
                Country c = world.GetCountry(id);
                double cal = MortalitySchedule.Calibration(id, c.BaselineLifeExpectancy);
                double raw = E0(Schedule(id, LongRunAnchors.SeedYear), 1.0, 0.0);
                double calibrated = E0(Schedule(id, LongRunAnchors.SeedYear), cal, 0.0);
                Check(Math.Abs(calibrated - c.BaselineLifeExpectancy) <= LifeExpectancyTolerance,
                    F("(a1) {0,-8} e0 of the {1} schedule {2:F3} uncalibrated; at c = {3:F5} {4:F4} against the sourced {5:F1}", id, LongRunAnchors.SeedYear, raw, cal, calibrated, c.BaselineLifeExpectancy));
            }
        }

        // ============================================================ (a2) every day
        private static void DerivedEveryDay()
        {
            _sb.Append("    a2. life expectancy equals the derivation after every day (one world, every country, three years)\n");
            SimulationRandom.Seed(777);
            using IDisposable epoch = SimulationManager.EpochScope();
            Elections.WorldClock.ApplyStart(CountryId.Sweden);
            EnergyMarket.ResetCalibration();
            World world = WorldFactory.CreateDefault();
            var go = new GameObject("LONGRUNANCHORS_DAILY");
            try
            {
                SimulationManager sim = go.AddComponent<SimulationManager>();
                sim.SetWorld(world);
                sim.PlayerCountryId = CountryId.Sweden;
                var worst = new Dictionary<CountryId, double>();
                foreach (CountryId id in Six) { worst[id] = Math.Abs(world.GetCountry(id).State.LifeExpectancy - Derived(world.GetCountry(id), MortalitySchedule.YearOf(sim.CurrentDate))); }
                var decisions = new Dictionary<CountryId, PolicyDecision>();
                foreach (Country k in world.Countries) { decisions[k.Id] = PolicyDecision.None(); }
                for (int year = 0; year < 3; year++)
                {
                    for (int day = 0; day < SimulationManager.DaysPerTurn; day++)
                    {
                        sim.AdvanceDay();
                        double y = MortalitySchedule.YearOf(sim.CurrentDate);
                        foreach (CountryId id in Six)
                        {
                            Country c = world.GetCountry(id);
                            worst[id] = Math.Max(worst[id], Math.Abs(c.State.LifeExpectancy - Derived(c, y)));
                        }
                    }
                    sim.AdvanceTurn(decisions);
                }
                foreach (CountryId id in Six)
                {
                    Country c = world.GetCountry(id);
                    Check(worst[id] <= LifeExpectancyTolerance,
                        F("(a2) {0,-8} the largest daily gap between the state and the recomputation {1:E2} years (after three years: {2:F3}, multiplier {3:F5}, treatable excess {4:E2} a person-year)",
                          id, worst[id], c.State.LifeExpectancy, c.State.MortalityMultiplier, MortalitySchedule.TreatableExcessRate(c)));
                }
            }
            finally { Object.DestroyImmediate(go); }
        }

        // ============================================================ (b) directions
        private static void Directions()
        {
            _sb.Append("    b. the multipliers' directions (K140)\n");
            double poverty = Value(typeof(MacroSystem), "MortalityPovertySensitivity");
            double healthcare = Value(typeof(MacroSystem), "MortalityHealthcareSensitivity");
            foreach (CountryId id in Six)
            {
                World world = SeededWorld();
                Country c = world.GetCountry(id);
                float atSeed = MacroSystem.MortalityMultiplierTarget(c);
                c.State.PovertyRate = c.BaselinePovertyRate + 5f;
                float poorer = MacroSystem.MortalityMultiplierTarget(c);
                c.State.PovertyRate = c.BaselinePovertyRate;
                if (c.WelfarePrograms == null) { c.WelfarePrograms = new List<WelfareProgram>(); }
                c.WelfarePrograms.Add(new WelfareProgram(WelfareProgramType.UniversalHealthcare, 100f, true));
                float healthier = MacroSystem.MortalityMultiplierTarget(c);
                double cal = MortalitySchedule.Calibration(id, c.BaselineLifeExpectancy);
                double[] m = Schedule(id, LongRunAnchors.SeedYear);
                double e = E0(m, cal, 0.0);
                double perPoint = E0(m, cal * (1.0 + poverty), 0.0) - e;
                double fullCare = E0(m, cal * (1.0 - healthcare), 0.0) - e;
                double treatable = E0(m, cal, 10.0 / 100000.0) - e;
                double halved = c.Health != null && c.Health.Seeded && c.Health.TreatableMortality > 0f ? E0(m, cal, -c.Health.TreatableMortality / 2.0 / 100000.0) - e : double.NaN;
                _sb.Append(F("        info {0,-8} halving the seed's treatable mortality ({1:F0} per 100 000) buys {2:+0.000;-0.000} years (the retired authored term: +0.693)\n",
                    id, c.Health != null ? c.Health.TreatableMortality : float.NaN, halved));
                Check(Math.Abs(atSeed - 1f) <= 1e-6f && poorer > 1f && healthier < 1f && perPoint < 0.0 && fullCare > 0.0 && treatable < 0.0,
                    F("(b) {0,-8} target at the seed {1:F6}; poverty +5 points {2:F5} (> 1); full universal healthcare {3:F5} (< 1); a point of poverty {4:+0.000;-0.000} years (retired 0.08), full generosity {5:+0.000;-0.000} (retired 1.5), 10 treatable deaths per 100 000 {6:+0.000;-0.000}",
                      id, atSeed, poorer, healthier, perPoint, fullCare, treatable));
            }
        }

        // ============================================================ (c) the gap's persistence
        private static void Persistence()
        {
            _sb.Append("    c. the gap's persistence (HLW, annual) - a shock keeps it after one turn, both forms\n");
            double us = StandingGapShare(LongRunAnchors.HlwUsAy1, LongRunAnchors.HlwUsAy2), ea = StandingGapShare(LongRunAnchors.HlwEaAy1, LongRunAnchors.HlwEaAy2);
            foreach (CountryId id in Six)
            {
                double expected = id == CountryId.USA ? us : ea;
                World wa = SeededWorld(), wb = SeededWorld(), wc = SeededWorld(), wd = SeededWorld();
                Country a = wa.GetCountry(id), b = wb.GetCountry(id), ca = wc.GetCountry(id), cb = wd.GetCountry(id);
                Check(Math.Abs(MacroSystem.GapPersistence(a) - expected) <= 1e-5 && MacroSystem.GapSeeded(a),   // n929: the float lags' rounding moves the recomputation by over 1e-6
                    F("(c1) {0,-8} the model's persistence {1:F5} is HLW's standing-gap share {2:F5} (the {3} lags); the seed references captured", id, MacroSystem.GapPersistence(a), expected, id == CountryId.USA ? "US" : "euro area"));
                float rate = a.CurrencyZone.InterestRate;
                float propensity = MacroSystem.IdentityPropensity(a, rate, MacroSystem.EffectiveConsumerConfidence(a));
                float g = MacroSystem.IdentityGovernmentConsumption(a, DiscretionaryLines(a));
                b.State.GDP *= 0.97f; cb.State.GDP *= 0.97f;
                double gap0 = b.State.GDP - a.State.GDP;
                MacroSystem.ApplyNationalAccounts(a, g, rate);
                MacroSystem.ApplyNationalAccounts(b, g, rate);
                double growth = 1.0 + MacroSystem.ExpectedPotentialGrowth(a);   // K209: the level keeps rho (1 + g) - the gap against the period's potential keeps rho
                double turnKept = (b.State.GDP - a.State.GDP) / gap0 / growth;
                double dailyKept = DailyKept(ca, cb, g, rate, gap0) / growth;
                double kappa = MacroSystem.GapImpact(a);
                double modelExpected = MacroSystem.GapPersistence(a) + kappa * (propensity - a.IdentityPropensitySeed) / growth;
                double lambda = Value(typeof(MacroSystem), "DemandReferenceSpeed");
                double cum1 = CumulativeMultiplier(kappa, expected, lambda, 1), cum4 = CumulativeMultiplier(kappa, expected, lambda, 4);
                double eu1 = CumulativeMultiplier(kappa, StandingGapShare(LongRunAnchors.HlwEaAy1, LongRunAnchors.HlwEaAy2), lambda, 1);
                double eu4 = CumulativeMultiplier(kappa, StandingGapShare(LongRunAnchors.HlwEaAy1, LongRunAnchors.HlwEaAy2), lambda, 4);
                Check(kappa >= ImpactFloor && cum1 >= RameyFloor && cum1 <= RameyCeiling && cum4 >= RameyFloor && cum4 <= RameyCeiling
                      && Math.Abs(eu1 - eu4) <= 0.005 && Math.Abs(eu1 * HarnessRatio - RameyMidpoint) <= 0.01,
                    F("(c3) {0,-8} K209: kappa {1:F4}, lambda {2:F4} - arithmetic impact {1:F3} (D-13 (b)'s floor {3:F4}), cumulative at L+1 {4:F3} and L+4 {5:F3} (Ramey's {6:F1}-{7:F1}); the EU five's equal at both horizons ({8:F3}, {9:F3}) and at the midpoint on the harness's measured basis ({10:F3} x {11:F2}); a drift d a year in demand's share holds the gap near {12:F2} d - ResponsivenessAuditHarness holds the measured reading",
                      id, kappa, lambda, ImpactFloor, cum1, cum4, RameyFloor, RameyCeiling, eu1, eu4, eu1, HarnessRatio, kappa * (1.0 - lambda) / (lambda * (1.0 - expected))));
                Check(Math.Abs(propensity - a.IdentityPropensitySeed) <= 1e-4 && Math.Abs(turnKept - expected) <= PersistenceTolerance && Math.Abs(dailyKept - expected) <= PersistenceTolerance
                      && Math.Abs(turnKept - modelExpected) <= PersistenceTolerance,
                    F("(c2) {0,-8} a 3 % shock keeps {1:F4} of itself after a turn (turn form) and {2:F4} (daily form) against the persistence {3:F4}; the propensity {4:F5} at its seed reference {5:F5}",
                      id, turnKept, dailyKept, expected, propensity, a.IdentityPropensitySeed));
            }

            foreach (CountryId id in Six)
            {
                IReadOnlyList<NoPolicyCentury.Year> run = NoPolicyCentury.For(id);
                NoPolicyCentury.Year open = NoPolicyCentury.Opening(id);
                _sb.Append(F("        info {0,-8} the no-policy gap, GDP / potential - 1: opening {1:+0.00%;-0.00%}, year 1 {2:+0.00%;-0.00%}, 5 {3:+0.00%;-0.00%}\n",
                    id, open.OutputGap, run[0].OutputGap, run[4].OutputGap));
                int bounded = 0;
                foreach (int y in GapBoundYears)
                {
                    if (y > run.Count) { continue; }
                    bounded++;
                    Check(Math.Abs(run[y - 1].OutputGap) <= NoPolicyGapBound,
                        F("(c4) {0,-8} the no-policy gap at year {1}: {2:+0.00%;-0.00%} of potential (bound +/-{3:0%})", id, y, run[y - 1].OutputGap, NoPolicyGapBound));
                }
                Check(bounded == GapBoundYears.Length, F("(c4) {0,-8} the gap was bounded at {1} of the {2} declared years", id, bounded, GapBoundYears.Length));
            }
        }

        /// <summary>D-13 (b)'s basis, as ResponsivenessAuditHarness reads it: the cumulative multiplier at L+h of a sustained unit of purchases - the
        /// mean over years 0..h of the output response, kappa (1 − rho^(n+1)) ÷ (1 − rho) in year n - the gap form's own arithmetic, the Taylor
        /// rule's feedback left out.</summary>
        private static double CumulativeMultiplier(double kappa, double rho, double lambda, int h)
        {
            double sum = 0;
            for (int n = 0; n <= h; n++)
            {
                double y = 0;
                for (int j = 0; j <= n; j++) { y += Math.Pow(rho, n - j) * Math.Pow(1 - lambda, j); }   // K209: the impulse left after j closes of the reference, decaying at rho since
                sum += kappa * y;
            }
            return sum / (h + 1);
        }

        private static double DailyKept(Country a, Country b, float g, float rate, double gap0)
        {
            float potentialA = a.State.PotentialGDP, potentialB = b.State.PotentialGDP;
            float wageA = MacroSystem.RealWageGrowthGapPerTurnPercent(a, MacroSystem.ProductivityCycleGrowthPerTurnPercent(a, a.State.Unemployment));
            float wageB = MacroSystem.RealWageGrowthGapPerTurnPercent(b, MacroSystem.ProductivityCycleGrowthPerTurnPercent(b, b.State.Unemployment));
            for (int i = 0; i < SimulationManager.DaysPerTurn; i++)
            {
                MacroSystem.ApplyNationalAccountsDaily(a, g, rate, potentialA, wageA);
                MacroSystem.ApplyNationalAccountsDaily(b, g, rate, potentialB, wageB);
            }
            return (b.State.GDP - a.State.GDP) / gap0;
        }

        /// <summary>HLW's output-gap equation, g(t) = a1 g(t-1) + a2 g(t-2), the real-rate term at zero: the share of a gap standing in the two quarters
        /// before that is left four quarters on - recomputed here, independently of the prep tool.</summary>
        private static double StandingGapShare(double a1, double a2)
        {
            double back2 = 1.0, back1 = 1.0;
            for (int q = 0; q < 4; q++) { double now = a1 * back1 + a2 * back2; back2 = back1; back1 = now; }
            return back1;
        }

        // ============================================================ (d) the no-policy band
        private static void NoPolicyBand()
        {
            _sb.Append(F("    d. the no-policy path inside the sourced band (WEO +/-{0} pp, Ageing Report / CBO +/-{1} pp a {2}-year window, life-expectancy gain +/-{3} years)\n",
                WeoBandPp, PotentialBandPp, WindowYears, LifeExpectancyBandYears));
            foreach (CountryId id in Six)
            {
                IReadOnlyList<NoPolicyCentury.Year> run = NoPolicyCentury.For(id);
                NoPolicyCentury.Year open = NoPolicyCentury.Opening(id);
                var real = new Dictionary<int, double>();
                var potential = new Dictionary<int, double>();
                var productivity = new Dictionary<int, double>();
                foreach (NoPolicyCentury.Year r in run)
                {
                    int y = (int)Math.Floor(r.SpanMidYear);
                    if (!real.ContainsKey(y)) { real[y] = r.RealGrowth; potential[y] = r.PotentialGrowth; productivity[y] = r.ProductivityGrowth; }
                }

                // the WEO window
                float[] weo = LongRunAnchors.WeoRealGrowth[id];
                double sumModel = 0, sumWeo = 0; int n = 0, firstY = int.MaxValue;
                for (int y = LongRunAnchors.WeoFirstYear; y <= LongRunAnchors.WeoLastYear; y++)
                {
                    if (!real.ContainsKey(y)) { continue; }
