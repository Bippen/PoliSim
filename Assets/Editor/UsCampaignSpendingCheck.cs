using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using PoliSim.Data;
using PoliSim.Elections;
using PoliSim.Elections.Generated;
using UnityEngine;

namespace PoliSim.EditorTools
{
    /// <summary>
    /// K19 (Elias's ruling of 2026-10-23: "Source the war chest's price table from FEC spending"): <b>the US war chest is the FEC's</b>. Re-reads every OpenFEC
    /// response `Tools/us_campaign_spending_prep.pl` read (`ElectionsData/usa/raw/fec_spending/`, each against the digest the generated part carries) and the CSV
    /// it wrote (`ElectionsData/usa/campaign_spending.csv`, its digest over its text with LF line ends), and derives the war chest again: every report row a
    /// most-recent Form 3P report in its committee's response with the same coverage and the same total disbursements; each nominee's window disbursements the
    /// report rows counted by their days inside the window; the chest their mean. It fails while the window is not the game's 2024 campaign (the
    /// `CampaignCalendar` the US staging opens on, its first day to the day before the polling day), while a generated constant is not the derivation, or while
    /// the staging does not read the chest (`LiveCampaignSetup.UsWarChest`), or while the purse is not re-denominated by the chest's ratio (K110, `LiveCampaignSetup.PursePerUnit`). Printed, not judged: each nominee's cycle spending by the FEC's purpose category -
    /// the shares a fit of the act prices would be held to (asked, K19). THE TEETH: a report's days planted whole moves the chest; one byte more in the CSV
    /// gives another digest. A stale constant is regenerated by the tool, never retyped: `perl Tools/us_campaign_spending_prep.pl`.
    /// Prints `US CAMPAIGN SPENDING: PASS` and exits 0 when every check holds.
    /// </summary>
    public static class UsCampaignSpendingCheck
    {
        private const string CsvRelative = "ElectionsData/usa/campaign_spending.csv";
        private const string Header = "kind,committee,party,label,from,to,amount,days_in_window,days";

        private static string F(string format, params object[] args) => string.Format(CultureInfo.InvariantCulture, format, args);

        private static string Sha(string text)
        {
            using (SHA256 sha = SHA256.Create()) { return string.Concat(sha.ComputeHash(Encoding.UTF8.GetBytes(text)).Select(b => b.ToString("x2"))); }
        }

        private static string ShaOf(byte[] bytes)
        {
            using (SHA256 sha = SHA256.Create()) { return string.Concat(sha.ComputeHash(bytes).Select(b => b.ToString("x2"))); }
        }

        public static void Run()
        {
            CheckExit.ArmLogFold();
            int failures = 0;
            var sb = new StringBuilder("=== UsCampaignSpendingCheck (K19): the US war chest from FEC spending ===\n");
            void Check(bool ok, string what)
            {
                sb.Append(ok ? "    ok   " : "    FAIL ").Append(what).Append('\n');
                if (!ok) { failures++; Debug.LogError("US CAMPAIGN SPENDING: FAIL - " + what); }
            }
            try
            {
                string root = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
                string usa = Path.Combine(root, "ElectionsData", "usa");

                // the responses, byte for byte
                var stale = new List<string>();
                var responses = new Dictionary<string, string>(StringComparer.Ordinal);
                foreach ((string path, string sha) in UsCampaignSpending.RawSources)
                {
                    string full = Path.Combine(usa, path.Replace('/', Path.DirectorySeparatorChar));
                    if (!File.Exists(full)) { stale.Add(path + " is not on disk"); continue; }
                    byte[] bytes = File.ReadAllBytes(full);
                    if (ShaOf(bytes) != sha) { stale.Add(path + " changed since generation"); }
                    responses[Path.GetFileName(path)] = Encoding.UTF8.GetString(bytes);
                }
                Check(stale.Count == 0 && UsCampaignSpending.RawSources.Length > 0,
                    F("the {0} OpenFEC responses are the bytes the run read{1}", UsCampaignSpending.RawSources.Length, stale.Count == 0 ? string.Empty : " - " + string.Join("; ", stale)));

                // the CSV, its digest and its rows
                string text = File.ReadAllText(Path.Combine(root, CsvRelative.Replace('/', Path.DirectorySeparatorChar)), Encoding.UTF8).Replace("\r\n", "\n");
                Check(Sha(text) == UsCampaignSpending.SourceDigest, F("{0} (its text with LF line ends) is the digest the generated part carries", CsvRelative));
                List<string[]> rows = text.Split('\n').Where(l => l.Length > 0 && !l.StartsWith("#", StringComparison.Ordinal)).Select(l => l.Split(',')).ToList();
                bool headed = rows.Count > 0 && string.Join(",", rows[0]) == Header;
                if (headed) { rows.RemoveAt(0); }
                bool same = headed && rows.Count == UsCampaignSpending.Rows.Length && rows.Zip(UsCampaignSpending.Rows, (c, g) => c.Length == 9 && c[0] == g.Kind && c[1] == g.Committee && c[2] == g.Party
                    && c[3] == g.Label && c[4] == g.From && c[5] == g.To && double.Parse(c[6], CultureInfo.InvariantCulture) == g.Amount && c[7] == g.DaysInWindow && c[8] == g.Days).All(x => x);
                Check(same, F("the CSV's {0} rows are the generated part's, field for field", rows.Count));

                // the window is the game's 2024 campaign
                CampaignCalendar calendar = CampaignCalendar.FromWorldStart(WorldClock.ElectionDayOf(CountryId.USA, ElectionVintage.Usa2024), WorldClock.StartDate(CountryId.USA));
                string first = calendar.CampaignStart.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture), last = calendar.ElectionDate.AddDays(-1).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
                Check(first == UsCampaignSpending.WindowFrom && last == UsCampaignSpending.WindowTo,
                    F("the window {0} to {1} is the game's 2024 US campaign (CampaignCalendar: {2} to {3}, the day before the polling day)", UsCampaignSpending.WindowFrom, UsCampaignSpending.WindowTo, first, last));

                // every report row a most-recent Form 3P report in its committee's own response
                var missing = new List<string>();
                var windowOf = new Dictionary<string, double>(StringComparer.Ordinal);
                foreach (var r in UsCampaignSpending.Rows.Where(x => x.Kind == "report"))
                {
                    string json = responses.TryGetValue("fec_committee_" + r.Committee + "_reports_2024.json", out string j) ? j : string.Empty;
                    string amount = r.Amount.ToString("0.00", CultureInfo.InvariantCulture).TrimEnd('0').TrimEnd('.');
                    bool found = Regex.Matches(json, @"\{[^{}]*\}").Cast<Match>().Any(m => m.Value.Contains("\"coverage_start_date\":\"" + r.From + "T") && m.Value.Contains("\"coverage_end_date\":\"" + r.To + "T")
                        && m.Value.Contains("\"most_recent\":true") && m.Value.Contains("\"report_form\":\"Form 3P\"") && Regex.IsMatch(m.Value, "\"total_disbursements_period\":" + Regex.Escape(amount) + "[,}]"));
                    if (!found) { missing.Add(r.Committee + " " + r.Label + " " + r.From + " to " + r.To + " " + amount); }
                    int din = int.Parse(r.DaysInWindow, CultureInfo.InvariantCulture), dall = int.Parse(r.Days, CultureInfo.InvariantCulture);
                    windowOf[r.Party] = (windowOf.TryGetValue(r.Party, out double w) ? w : 0.0) + r.Amount * din / dall;
                    sb.Append(F("      {0} {1} {2,-18} {3} to {4}: {5:N2} dollars, {6} of its {7} days in the window\n", r.Party, r.Committee, r.Label, r.From, r.To, r.Amount, din, dall));
                }
                Check(missing.Count == 0, missing.Count == 0 ? "every report row is a most-recent Form 3P report in its committee's response, its coverage and its total disbursements the response's"
                    : "report rows not in their responses: " + string.Join("; ", missing));
                windowOf.TryGetValue("DEM", out double dem);
                windowOf.TryGetValue("REP", out double rep);
                double chest = (dem + rep) / 2.0;
                Check(Math.Abs(dem - UsCampaignSpending.WindowDisbursementsDem) < 0.01 && Math.Abs(rep - UsCampaignSpending.WindowDisbursementsRep) < 0.01 && Math.Abs(chest - UsCampaignSpending.WarChestUsd) < 0.01,
                    F("the chest derived again: DEM {0:N2}, REP {1:N2} over the window, their mean {2:N2} dollars (generated {3:N2}, {4:N2}, {5:N2}); a stale one is regenerated: perl Tools/us_campaign_spending_prep.pl",
                        dem, rep, chest, UsCampaignSpending.WindowDisbursementsDem, UsCampaignSpending.WindowDisbursementsRep, UsCampaignSpending.WarChestUsd));
                double perUnit = LiveCampaignSetup.PursePerUnit(CountryId.USA);
                Check(LiveCampaignSetup.UsWarChest == UsCampaignSpending.WarChestUsd && perUnit == UsCampaignSpending.WarChestUsd / LiveCampaignSetup.WarChest && perUnit > 1.0
                      && LiveCampaignSetup.PursePerUnit(CountryId.Sweden) == 1.0 && LiveCampaignSetup.PursePerUnit(CountryId.Germany) == 1.0,
                    F("K110: the US purse re-denominated - one unit of the model's table {0:N4} dollars, the FEC chest {1:N2} over the model's {2:N0} (derived from the two figures), so the staged {2:N0} units are K19's chest and every act's price is the model's times the ratio (a TV buy {3:N0} dollars, a rally {4:N0}); every other country one to one",
                        perUnit, UsCampaignSpending.WarChestUsd, LiveCampaignSetup.WarChest, CampaignActions.Spec(CampaignActionKind.TelevisionAd).MoneyCost * perUnit, CampaignActions.Spec(CampaignActionKind.Rally).MoneyCost * perUnit));

                // printed, not judged: the cycle's spending by purpose
                foreach (string party in new[] { "DEM", "REP" })
                {
                    double all = UsCampaignSpending.Rows.Where(x => x.Kind == "cycle" && x.Party == party).Select(x => x.Amount).FirstOrDefault();
                    sb.Append(F("      {0} cycle {1:N2} dollars; by purpose: {2}\n", party, all, string.Join(", ", UsCampaignSpending.Rows.Where(x => x.Kind == "purpose" && x.Party == party)
                        .Select(x => F("{0} {1:0.0} %", x.Label, all > 0.0 ? 100.0 * x.Amount / all : double.NaN)))));
                }

                // THE TEETH
                double planted = UsCampaignSpending.Rows.Where(x => x.Kind == "report" && x.Party == "DEM").Sum(x => x.Amount);
                Check(Math.Abs(planted - UsCampaignSpending.WindowDisbursementsDem) > 1.0, F("planted: the reports counted whole ({0:N2}) is not the window's {1:N2} - the days' share has teeth", planted, UsCampaignSpending.WindowDisbursementsDem));
                Check(Sha(text + "\n") != UsCampaignSpending.SourceDigest, "planted: one byte more in the CSV gives another digest, which the check would refuse");
            }
            catch (Exception e) { Check(false, "the run threw " + e.GetType().Name + ": " + e.Message); }
            Debug.Log(sb.ToString());
            Debug.Log(failures == 0 ? "US CAMPAIGN SPENDING: PASS - the war chest is the FEC's, derived again from the saved responses, and the staging reads it." : F("US CAMPAIGN SPENDING: FAIL - {0} check(s) failed.", failures));
            CheckExit.Finish(failures == 0 ? 0 : 1);
        }
    }
}
