#!/usr/bin/perl
# THE USA'S 51 JURISDICTIONS AS A TABLE FOR A DESIGN ASK (D-US part one, the night - USA_STAGE_PLAN.md US-17; on Tools/pl_districts_table.pl's
# pattern). Reads the generated catalog under ElectionsData/usa/ for one presidential year and writes, to the directory given:
#   states_<year>.csv      state;electors;house_seats;senate_races;pres_winner;rep_two_party;house_r;house_d - generated, never retyped
#   districts_<year>.csv   Maine's and Nebraska's congressional districts: state;district;electors;pres_winner;rep_two_party
# and, with -ask <ASK.md>, replaces a line reading exactly TABLE in that file with the jurisdictions as a markdown table.
#   electors      president_by_state.csv's electors for the year (the apportionment in force plus two, DC three)
#   house_seats   house_districts.csv's races of the year in that state (an at-large state is one; DC elects none)
#   senate_races  senate_races.csv's races of the year in that state, each "class N" with "special" where the term is unexpired; a state
#                 voting twice for one seat (an unexpired term and the full term after it) lists the seat once with both
#   pres_winner   R or D by the electors cast (cast_r / cast_d); a split state names both
#   rep_two_party votes_r / (votes_r + votes_d), the presidential two-party share of record, to four places
#   house_r/_d    the House seats each party won of record that year (house_districts.csv's winner)
# Dies unless the year's jurisdictions are 51, the electors sum to 538, the House seats to 435, and Maine's and Nebraska's districts are read.
# Usage (from the project root): perl Tools/us_states_table.pl <outdir> [year] [-ask <ASK.md>]
use strict;
use warnings;

my ($outdir, @rest) = @ARGV;
die "usage: perl Tools/us_states_table.pl <outdir> [year] [-ask <ASK.md>]\n" unless $outdir && -d $outdir;
my $year = (@rest && $rest[0] =~ /^\d{4}$/) ? shift @rest : 2024;
my ($flag, $ask) = @rest;
my $dir = 'ElectionsData/usa';

sub rows {
    my $file = shift;
    open my $in, '<:encoding(UTF-8)', "$dir/$file" or die "$file: $!";
    my @head; my @out;
    while (my $line = <$in>) {
        $line =~ s/\r?\n\z//;
        next if $line =~ /^#/ || $line eq '';
        my @f = split /,/, $line, -1;
        if (!@head) { @head = @f; next; }
        my %r; @r{@head} = @f; push @out, \%r;
    }
    close $in;
    return @out;
}

my %st;
for my $r (grep { $_->{year} == $year } rows('president_by_state.csv')) {
    my $two = $r->{votes_r} + $r->{votes_d};
    my $win = $r->{cast_r} > 0 && $r->{cast_d} > 0 ? 'R+D' : $r->{cast_r} > 0 ? 'R' : 'D';
    $st{$r->{state}} = { electors => $r->{electors}, win => $win, rep => sprintf('%.4f', $r->{votes_r} / $two), seats => 0, hr => 0, hd => 0, senate => [] };
}
for my $r (grep { $_->{year} == $year } rows('house_districts.csv')) {
    die "house: $r->{state} has no presidential row in $year\n" unless $st{$r->{state}};
    $st{$r->{state}}{seats}++;
    $st{$r->{state}}{hr}++ if $r->{winner} eq 'R';
    $st{$r->{state}}{hd}++ if $r->{winner} eq 'D';
}
my %seen;
for my $r (grep { $_->{year} == $year } rows('senate_races.csv')) {
    my $key = "$r->{state} $r->{class}";
    my $label = "class $r->{class}" . ($r->{term} eq 'unexpired' ? ' special' : '');
    if ($seen{$key}++) { $_ = "class $r->{class} (full and unexpired)" for grep { /^class \Q$r->{class}\E/ } @{ $st{$r->{state}}{senate} }; next; }
    push @{ $st{$r->{state}}{senate} }, $label;
}
my @dist = map { [ $_->{state}, $_->{district}, $_->{votes_r} / ($_->{votes_r} + $_->{votes_d}) ] } grep { $_->{year} == $year } rows('president_by_district.csv');

my @codes = sort keys %st;
my ($ev, $seats, $races) = (0, 0, 0);
for (@codes) { $ev += $st{$_}{electors}; $seats += $st{$_}{seats}; $races += @{ $st{$_}{senate} }; }
die "read " . scalar(@codes) . " jurisdictions, $ev electors, $seats House seats - not 51, 538 and 435\n" unless @codes == 51 && $ev == 538 && $seats == 435;
die "read " . scalar(@dist) . " Maine and Nebraska districts - not 5\n" unless @dist == 5;

open my $csv, '>:encoding(UTF-8)', "$outdir/states_$year.csv" or die $!;
print $csv "# USA $year - the 51 jurisdictions: electors, House seats, the Senate races of the day, and the record's presidential and House results [SOURCED]\n";
print $csv "# from ElectionsData/usa/president_by_state.csv, house_districts.csv and senate_races.csv; generated by Tools/us_states_table.pl, never retyped\n";
print $csv "state;electors;house_seats;senate_races;pres_winner;rep_two_party;house_r;house_d\n";
print $csv join(';', $_, @{ $st{$_} }{qw(electors seats)}, (join(' + ', @{ $st{$_}{senate} }) || '-'), @{ $st{$_} }{qw(win rep hr hd)}) . "\n" for @codes;
close $csv;

open my $dcsv, '>:encoding(UTF-8)', "$outdir/districts_$year.csv" or die $!;
print $dcsv "# USA $year - Maine's and Nebraska's congressional districts, one elector each by the district method; the presidential two-party share of record [SOURCED]\n";
print $dcsv "# from ElectionsData/usa/president_by_district.csv; generated by Tools/us_states_table.pl, never retyped\n";
print $dcsv "state;district;electors;pres_winner;rep_two_party\n";
printf $dcsv "%s;%s;1;%s;%.4f\n", $_->[0], $_->[1], ($_->[2] > 0.5 ? 'R' : 'D'), $_->[2] for @dist;
close $dcsv;
print "WROTE $outdir/states_$year.csv - 51 jurisdictions, $ev electors, $seats House seats, $races Senate seat(s) on the day; districts_$year.csv - 5 districts\n";

if (defined $flag && $flag eq '-ask') {
    open my $in, '<:raw', $ask or die "$ask: $!"; local $/; my $text = <$in>; close $in;
    my $nl = $text =~ /\r\n/ ? "\r\n" : "\n";
    my @t = ("| state | electors | House seats | Senate on the day | $year president | REP two-party | House R-D |", '|---|---:|---:|---|---|---:|---|');
    push @t, "| $_ | $st{$_}{electors} | $st{$_}{seats} | " . (join(' + ', @{ $st{$_}{senate} }) || '-') . " | $st{$_}{win} | $st{$_}{rep} | $st{$_}{hr}-$st{$_}{hd} |" for @codes;
    my $table = join($nl, @t);
    my $n = ($text =~ s/^TABLE\r?$/$table/m);
    die "$ask: no line reading exactly TABLE\n" unless $n;
    open my $out, '>:raw', $ask or die $!; print $out $text; close $out;
    print "WROTE the table into $ask\n";
}
