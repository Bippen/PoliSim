#!/usr/bin/perl
# S7 (Design's return of 2026-10-30, section 7 "The 51-jurisdiction map (7a)"): THE HQ'S US TILE MAP, GENERATED - never hand-edited.
#
#   perl Tools/s7_tiles.pl <us_tiles.json> <out.cs>      (from the project root)
#
# Reads Design's assets/s7/us_tiles.json (the return is kept out of tree, under PoliSim-captures/design/RETURN_2026-10-30_full/) and writes
# Assets/Scripts/UI/CampaignTiles.UsGenerated.cs: the 51 tiles as Design placed them - each tile's postal code, column and row - on Design's 11 x 8 grid,
# 34 px tiles 2 apart from the origin the json's own note gives at 1280. The tile's long label is the jurisdiction's name as the University of Florida's
# 2024 turnout file on disk writes it (raw/returns/ufl_turnout_2024G_v0.4.csv, held to its SHA256SUMS.txt line). The electors Design printed are held to
# the catalog's 2024 electors (ElectionsData/usa/president_by_state.csv) and the run dies on a mismatch - the tiles print the catalog's, never Design's.
# The json's own SHA-256 is written into the file, so a re-run against a newer delivery shows in the diff.
use strict; use warnings;
use JSON::PP;
use Digest::SHA qw(sha256_hex);
use Encode ();

my ($src, $out) = @ARGV;
die "usage: s7_tiles.pl <us_tiles.json> <out.cs>\n" unless $src && $out;
die "run from the project root\n" unless -d 'ElectionsData/usa';
sub slurp { my ($f) = @_; open my $h, '<:raw', $f or die "$f: $!\n"; local $/; my $b = <$h>; close $h; return $b; }
my $raw = slurp($src);
my $digest = sha256_hex($raw);
my $j = JSON::PP->new->utf8->decode($raw);
my ($gc, $gr) = @{ $j->{grid} };
my ($ox, $oy) = ($j->{note} // '') =~ /from \((\d+),\s*(\d+)\) at 1280/ or die "$src: its note gives no origin at 1280\n";
die "$src: the grid is ${gc} x ${gr}, not 11 x 8\n" unless $gc == 11 && $gr == 8;

# the names, from the UFL file held to its digest
my %listed;
for my $l (split /\r?\n/, slurp('ElectionsData/usa/raw/returns/SHA256SUMS.txt')) { $listed{$2} = $1 if $l =~ /^([0-9a-f]{64}) \*?(\S+)$/; }
my $ufl = slurp('ElectionsData/usa/raw/returns/ufl_turnout_2024G_v0.4.csv');
die "ufl_turnout_2024G_v0.4.csv: not the bytes SHA256SUMS.txt lists\n" unless ($listed{'ufl_turnout_2024G_v0.4.csv'} // '') eq sha256_hex($ufl);
my %name;
for my $l (split /\r?\n/, $ufl) { $name{$2} = $1 if $l =~ /^([A-Za-z .]+),([A-Z]{2}),/ && $2 ne 'US'; }

# the electors of record
my %electors;
for my $l (split /\r?\n/, slurp('ElectionsData/usa/president_by_state.csv')) { my @f = split /,/, $l; $electors{$f[1]} = $f[2] if @f > 2 && $f[0] eq '2024'; }
die "president_by_state.csv: " . scalar(keys %electors) . " jurisdictions of 2024, not 51\n" unless keys %electors == 51;

my (@problems, %seen, %cell);
for my $t (@{ $j->{tiles} }) {
    my $id = $t->{id};
    push @problems, "$id twice" if $seen{$id}++;
    push @problems, "$id is not a jurisdiction of 2024" unless exists $electors{$id};
    push @problems, "$id: Design prints $t->{electors} electors, the catalog's 2024 $electors{$id}" if exists $electors{$id} && $t->{electors} != $electors{$id};
    push @problems, "$id: no name in the UFL file" unless $name{$id};
    push @problems, "$id: off the grid at ($t->{col}, $t->{row})" unless $t->{col} >= 0 && $t->{col} < $gc && $t->{row} >= 0 && $t->{row} < $gr;
    push @problems, "$id shares ($t->{col}, $t->{row}) with $cell{\"$t->{col},$t->{row}\"}" if $cell{"$t->{col},$t->{row}"};
    $cell{"$t->{col},$t->{row}"} = $id;
}
push @problems, "no tile for $_" for grep { !$seen{$_} } sort keys %electors;
die join("\n", "s7_tiles.pl: nothing written -", map { "  $_" } @problems) . "\n" if @problems;

sub cq { my ($s) = @_; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return '"' . $s . '"'; }
my $n = scalar @{ $j->{tiles} };
my $cs = "// GENERATED by Tools/s7_tiles.pl from Design's us_tiles.json (S7 return, 2026-10-30) - never hand-edited.\r\n";
$cs .= "// Source SHA-256: $digest\r\n";
$cs .= "namespace PoliSim.UI\r\n{\r\n";
$cs .= "    public static partial class CampaignTiles\r\n    {\r\n";
$cs .= "        /// <summary>The digest of the us_tiles.json the US map was generated from.</summary>\r\n";
$cs .= "        public const string UsSourceDigest = \"$digest\";\r\n\r\n";
$cs .= "        /// <summary>Design's us_states: $n tiles on a ${gc} x ${gr} grid, $j->{tile} px tiles $j->{gap} apart from ($ox, $oy) at 1280 - the postal code over the\r\n";
$cs .= "        /// electors (the catalog's, read at run time); the long label the jurisdiction's name (the UFL 2024 turnout file's).</summary>\r\n";
$cs .= "        public static readonly TileMap UsStates = new TileMap(\"us_states\", $gc, $gr, $j->{tile}f, $j->{gap}f, ${ox}f, ${oy}f, new[]\r\n        {\r\n";
for my $t (@{ $j->{tiles} }) { $cs .= "            new Tile(" . cq($t->{id}) . ", $t->{col}, $t->{row}, " . cq($name{ $t->{id} }) . "),\r\n"; }
$cs .= "        });\r\n    }\r\n}\r\n";
open my $o, '>:raw', $out or die "$out: $!";
print $o Encode::encode('UTF-8', $cs);
close $o;
printf "%s: %d tiles from %s (sha256 %s); every elector the catalog's\n", $out, $n, $src, $digest;
