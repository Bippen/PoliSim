#!/usr/bin/perl
# MF-14 (q14; Elias's ruling K138, 2026-10-27): UNEMPLOYMENT'S FLOOR IS THE LOWEST OF THE OECD HARMONISED ANNUAL SERIES SINCE 1990, PER COUNTRY.
# Reads the stored OECD SDMX CSV (ElectionsData/macro/raw/oecd_hur/, fetched byte-exact by curl, its digest in that folder's SHA256SUMS.txt) and
# writes Assets/Scripts/Data/Generated/UnemploymentFloorData.cs: each country's floor (the lowest annual observation from 1990 on, or from the
# series' first year where the series starts later - declared per country), the year it was observed, the series' first year and the CSV's digest.
# UnemploymentFloorPhillipsDiagnostic re-reads the CSV and recomputes every figure.
# The series (read off the CSV's own code columns, and the tool dies unless every row carries them): dataflow OECD.SDD.TPS:DSD_LFS@DF_IALFS_UNE_M(1.0)
# "Monthly unemployment rates" (the infra-annual labour statistics: ICLS-19 definitions applied uniformly, "internationally comparable" - the
# dataflow's own description), MEASURE UNE_LF_M, UNIT_MEASURE PT_LF_SUB (per cent of the labour force), TRANSFORMATION _Z, ADJUSTMENT N (neither
# seasonally nor calendar adjusted - the annual average), SEX _T, AGE Y_GE15, ACTIVITY _Z, FREQ A.
# Usage (from the project root): perl Tools/unemployment_floor_prep.pl [cs]
# Writes LF line ends; the output is byte-identical on every run from the same CSV.
use strict;
use warnings;
use Digest::SHA qw(sha256_hex);

my $cs = $ARGV[0] // 'Assets/Scripts/Data/Generated/UnemploymentFloorData.cs';
my $dir = 'ElectionsData/macro/raw/oecd_hur/';
my $file = 'oecd_DF_IALFS_UNE_M_A_N_T_Y_GE15.csv';
my $fromYear = 1990;

open my $fh, '<:raw', $dir . $file or die "$dir$file: $!";
my $bytes = do { local $/; <$fh> };
close $fh;
my $digest = sha256_hex($bytes);
open my $sf, '<', $dir . 'SHA256SUMS.txt' or die "SHA256SUMS.txt: $!";
my $listed = grep { s/\r?\n\z//; $_ eq "$digest *$file" } <$sf>;
close $sf;
die "$file: digest $digest is not the one SHA256SUMS.txt lists\n" unless $listed;

my @lines = split /\r?\n/, $bytes;   # the OECD serves CRLF
die "$file: a quote in the CSV - the reader below splits on commas alone\n" if $bytes =~ /"/;
my @head = split /,/, shift @lines, -1;
my %col;
for my $i (0 .. $#head) { $col{$head[$i]} //= $i; }   # the code column comes first; its label twin (e.g. "Measure") differs in case
for my $c (qw(REF_AREA MEASURE UNIT_MEASURE TRANSFORMATION ADJUSTMENT SEX AGE ACTIVITY FREQ TIME_PERIOD OBS_VALUE OBS_STATUS)) {
    die "$file: no column $c\n" unless defined $col{$c};
}
my %want = (MEASURE => 'UNE_LF_M', UNIT_MEASURE => 'PT_LF_SUB', TRANSFORMATION => '_Z', ADJUSTMENT => 'N', SEX => '_T', AGE => 'Y_GE15', ACTIVITY => '_Z', FREQ => 'A');
my %area = (USA => 'USA', SWE => 'Sweden', DEU => 'Germany', FRA => 'France', ITA => 'Italy', POL => 'Poland');

my (%first, %floor, %floorYear, %floorText, %count);
for my $line (@lines) {
    next if $line eq '';
    my @f = split /,/, $line, -1;
    die "$file: a row of " . scalar(@f) . " fields, the header has " . scalar(@head) . "\n" unless @f == @head;
    for my $k (sort keys %want) { die "$file: $k is $f[$col{$k}], not $want{$k}\n" unless $f[$col{$k}] eq $want{$k}; }
    my $a = $f[$col{REF_AREA}];
    die "$file: an unexpected area $a\n" unless $area{$a};
    my ($y, $v) = ($f[$col{TIME_PERIOD}], $f[$col{OBS_VALUE}]);
    die "$file: $a: a period '$y' that is not a year\n" unless $y =~ /^[0-9]{4}$/;
    die "$file: $a $y: a value '$v' that is not a number\n" unless $v =~ /^[0-9]+(?:\.[0-9]+)?$/;
    $first{$a} = $y if !defined $first{$a} || $y < $first{$a};
    next if $y < $fromYear;
    $count{$a}++;
    if (!defined $floor{$a} || $v < $floor{$a} || ($v == $floor{$a} && $y < $floorYear{$a})) { ($floor{$a}, $floorYear{$a}, $floorText{$a}) = ($v, $y, $v); }
}
for my $a (sort keys %area) { die "$file: no observation for $a from $fromYear on\n" unless defined $floor{$a}; }

my @order = qw(USA SWE DEU FRA ITA POL);
my $out = '';
$out .= "// GENERATED by Tools/unemployment_floor_prep.pl. DO NOT EDIT BY HAND.\n";
$out .= "//\n";
$out .= "// Source : ElectionsData/macro/raw/oecd_hur/$file\n";
$out .= "// SHA-256: $digest\n";
$out .= "//\n";
$out .= "// UnemploymentFloorPhillipsDiagnostic re-reads the CSV and recomputes every figure.\n";
$out .= "\n";
$out .= "using System.Collections.Generic;\n";
$out .= "\n";
$out .= "namespace PoliSim.Data.Generated\n";
$out .= "{\n";
$out .= "    /// <summary>MF-14 (q14; Elias's ruling K138, 2026-10-27): unemployment's floor, per country - the lowest annual observation of the OECD harmonised\n";
$out .= "    /// unemployment rate (dataflow DSD_LFS\@DF_IALFS_UNE_M, UNE_LF_M, per cent of the labour force, 15 and over, annual, not adjusted) from $fromYear on, or\n";
$out .= "    /// from the series' first year where it starts later (Germany's series opens at reunification, Poland's later still: <see cref=\"SeriesStart\"/>).\n";
$out .= "    /// The value is the CSV's, unrounded. Generated, never hand-edited.</summary>\n";
$out .= "    public static class UnemploymentFloorData\n";
$out .= "    {\n";
$out .= "        public const string SourcePath = \"ElectionsData/macro/raw/oecd_hur/$file\";\n";
$out .= "        public const string SourceDigest = \"$digest\";\n";
$out .= "        /// <summary>The first year the floor reads (K138's \"since 1990\", read inclusive).</summary>\n";
$out .= "        public const int FromYear = $fromYear;\n";
$out .= "\n";
$out .= "        /// <summary>Each country's floor, its year, the series' first year in the file and the count of years from <see cref=\"FromYear\"/> (or the start) read.</summary>\n";
$out .= "        public static readonly Dictionary<CountryId, (float Floor, int Year, int SeriesStart, int Years)> Floors = new Dictionary<CountryId, (float Floor, int Year, int SeriesStart, int Years)>\n";
$out .= "        {\n";
for my $a (@order) {
    $out .= "            { CountryId.$area{$a}, ($floorText{$a}f, $floorYear{$a}, $first{$a}, $count{$a}) },\n";
}
$out .= "        };\n";
$out .= "\n";
$out .= "\n";
$out .= "    }\n";
$out .= "}\n";

open my $o, '>:raw', $cs or die "$cs: $!";
print $o $out;
close $o;
for my $a (@order) { printf "%-8s floor %s (%d), series from %d, %d years read from %d\n", $area{$a}, $floorText{$a}, $floorYear{$a}, $first{$a}, $count{$a}, ($first{$a} > $fromYear ? $first{$a} : $fromYear); }
print "wrote $cs\n";
