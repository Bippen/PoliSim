#!/usr/bin/perl
# POLAND'S OKREGI CARTOGRAM FOR THE SEJM NIGHT (D-PL; Design's boards 28a-28b). Reads Design's cartogram table as the channel returned it,
# decoded byte-exact and kept out of tree with its digest (../PoliSim-captures/design/dpl/night.json, SHA256SUMS.txt beside it): a 27 x 24 grid,
# one cell per deputy [col,row], each okreg's label cell and outline, the okreg and voivodeship borders (seg.ok, seg.voiv), the okregi's seat
# cities and voivodeships - and writes
#   Assets/Scripts/Elections/Generated/PolishOkregiCartogram.cs   the positions as the board's, never re-derived, the source's SHA-256 in its header.
# Design's own figures in the file (its illustrative votes and seats, its inks, its declaration order) are NOT carried: the night counts the game's.
# Dies unless the 41 okregi hold 460 cells, none twice, each inside the grid, each okreg contiguous, its label one of its own cells.
# PolishNightDiagnostic holds the generated table to the Sejm's magnitudes and its own invariants on every run.
# Usage: perl Tools/dpl_cartogram_prep.pl [night.json] [out]   (from the project root)
use strict; use warnings;
use Digest::SHA qw(sha256_hex);
use JSON::PP;

my $src = shift // '../PoliSim-captures/design/dpl/night.json';
my $out = shift // 'Assets/Scripts/Elections/Generated/PolishOkregiCartogram.cs';

open my $h, '<:raw', $src or die "$src: $!\n"; local $/; my $bytes = <$h>; close $h;
my $digest = sha256_hex($bytes);
my $j = JSON::PP->new->utf8->decode($bytes);
my ($cols, $rows) = ($j->{grid}{cols}, $j->{grid}{rows});
die "the grid must be 27 x 24, read $cols x $rows\n" unless $cols == 27 && $rows == 24;

my %seen; my $total = 0; my (@ok, %voivUsed);
for my $n (1..41) {
    my $o = $j->{ok}{$n} or die "okreg $n missing\n";
    my @cells = @{$o->{cells}};
    my %in;
    for my $c (@cells) {
        my ($x, $y) = @$c;
        die "okreg $n: cell $x,$y outside the grid\n" if $x < 0 || $x >= $cols || $y < 0 || $y >= $rows;
        die "okreg $n: cell $x,$y taken twice\n" if $seen{"$x,$y"}++;
        $in{"$x,$y"} = 1;
    }
    die "okreg $n: its label is not one of its cells\n" unless $in{"$o->{label}[0],$o->{label}[1]"};
    my @queue = ("$cells[0][0],$cells[0][1]"); my %reached = ($queue[0] => 1);
    while (@queue) {
        my ($x, $y) = split /,/, shift @queue;
        for my $d ([1, 0], [-1, 0], [0, 1], [0, -1]) {
            my $k = ($x + $d->[0]) . ',' . ($y + $d->[1]);
            if ($in{$k} && !$reached{$k}) { $reached{$k} = 1; push @queue, $k; }
        }
    }
    die "okreg $n is not contiguous\n" unless keys(%reached) == @cells;
    $total += @cells;
    $voivUsed{$o->{voiv}} = 1;
    push @ok, { n => $n, city => $o->{city}, voiv => $o->{voiv}, label => $o->{label}, cells => \@cells, outline => $o->{outline} };
}
die "460 cells expected, $total read\n" unless $total == 460;
die "16 voivodeships expected, " . scalar(keys %voivUsed) . " read\n" unless keys(%voivUsed) == 16;

sub str { my $s = shift; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return "\"$s\""; }
sub pairs { return join(', ', map { "{ $_->[0], $_->[1] }" } @{$_[0]}); }
sub segs { return join(', ', map { "{ $_->[0], $_->[1], $_->[2], $_->[3] }" } @{$_[0]}); }

my @okLines;
for my $o (@ok) {
    push @okLines, "            new Okreg($o->{n}, " . str($o->{city}) . ", " . str($o->{voiv}) . ", $o->{label}[0], $o->{label}[1],\n"
        . "                new[,] { " . pairs($o->{cells}) . " },\n"
        . "                new[,] { " . segs($o->{outline}) . " }),";
}
my @voiv = map { "            { " . str($_) . ", " . str($j->{voivNames}{$_}) . " }," } sort keys %{$j->{voivNames}};

open my $o, '>:raw:encoding(UTF-8)', $out or die "$out: $!\n";
print $o <<"EOT";
// GENERATED by Tools/dpl_cartogram_prep.pl. DO NOT EDIT BY HAND.
//
// Source : ../PoliSim-captures/design/dpl/night.json (Design's board 28a cartogram table, out of tree; SHA256SUMS.txt beside it)
// SHA-256: $digest
//
// PolishNightDiagnostic holds this table to the Sejm's magnitudes and to its own invariants.

namespace PoliSim.Elections.Generated
{
    /// <summary>D-PL (Design's boards 28a-28b): THE 41 OKREGI AS SEAT CELLS - one cell per deputy on a $cols x $rows grid, each okreg a contiguous block
    /// of its own magnitude, the okreg and voivodeship borders as segments on the grid's lines - positions as the board's, never re-derived. The night
    /// reads its counts from the model, never from here.</summary>
    public static class PolishOkregiCartogram
    {
        public const string SourceDigest = "$digest";

        /// <summary>The grid, in cells.</summary>
        public const int Columns = $cols, Rows = $rows;

        /// <summary>One okreg: its PKW number, seat city and voivodeship code, the cell its number is printed in, its cells [col, row] and its outline's
        /// segments [x1, y1, x2, y2] on the grid's lines.</summary>
        public sealed class Okreg
        {
            public readonly int Number;
            public readonly string City, Voivodeship;
            public readonly int LabelColumn, LabelRow;
            public readonly int[,] Cells, Outline;

            public Okreg(int number, string city, string voivodeship, int labelColumn, int labelRow, int[,] cells, int[,] outline)
            {
                Number = number; City = city; Voivodeship = voivodeship; LabelColumn = labelColumn; LabelRow = labelRow; Cells = cells; Outline = outline;
            }
        }

        /// <summary>The 41, okreg 1 to 41.</summary>
        public static readonly Okreg[] Okregi =
        {
@{[join("\n", @okLines)]}
        };

        /// <summary>The borders between okregi inside one voivodeship (a narrow gap).</summary>
        public static readonly int[,] OkregBorders = { @{[segs($j->{seg}{ok})]} };

        /// <summary>The borders between voivodeships (a wide gap).</summary>
        public static readonly int[,] VoivodeshipBorders = { @{[segs($j->{seg}{voiv})]} };

        /// <summary>The voivodeships' names by the codes the okregi carry.</summary>
        public static readonly System.Collections.Generic.Dictionary<string, string> VoivodeshipNames = new System.Collections.Generic.Dictionary<string, string>
        {
@{[join("\n", @voiv)]}
        };
    }
}
EOT
close $o;
print "wrote $out: 41 okregi, $total cells, " . scalar(@{$j->{seg}{ok}}) . " okreg borders, " . scalar(@{$j->{seg}{voiv}}) . " voivodeship borders; source $digest\n";
