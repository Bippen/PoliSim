#!/usr/bin/perl
# S4 (Design's return of 2026-10-30, "For Code" 1): THE HQ'S TILE MAPS, GENERATED - never hand-edited.
#
#   perl Tools/s4_tiles.pl <hq_tiles.json> <out.cs>
#
# Reads Design's assets/s4/hq_tiles.json (saved decoded, with its digest, under PoliSim-captures/design/RETURN_2026-10-30_S4/) and writes
# Assets/Scripts/UI/CampaignTiles.Generated.cs: the three maps (the okregi, the wojewodztwa, the valkretsar) as Design placed them -
# each tile's id, column, row and label, and each map's grid, tile, gap and origin at 1280. The positions are Design's; the labels are
# labels only ("magnitudes come from the game's own tables"). The json's own SHA-256 is written into the file, so a re-run against a newer
# delivery shows in the diff.
use strict; use warnings;
use JSON::PP;
use Digest::SHA qw(sha256_hex);
use Encode ();

my ($src, $out) = @ARGV;
die "usage: s4_tiles.pl <hq_tiles.json> <out.cs>\n" unless $src && $out;
open my $h, '<:raw', $src or die "$src: $!"; local $/; my $raw = <$h>; close $h;
my $digest = sha256_hex($raw);
my $j = JSON::PP->new->utf8->decode($raw);

sub cq { my ($s) = @_; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return '"' . $s . '"'; }

my @maps = (['pl_sejm', 'PolishSejm'], ['pl_wojewodztwa', 'PolishWojewodztwa'], ['se_valkretsar', 'SwedishValkretsar']);
my $cs = '';
$cs .= "// GENERATED by Tools/s4_tiles.pl from Design's hq_tiles.json (S4 return, 2026-10-30) - never hand-edited.\r\n";
$cs .= "// Source SHA-256: $digest\r\n";
$cs .= "namespace PoliSim.UI\r\n{\r\n";
$cs .= "    public static partial class CampaignTiles\r\n    {\r\n";
$cs .= "        /// <summary>The digest of the hq_tiles.json these tables were generated from.</summary>\r\n";
$cs .= "        public const string SourceDigest = \"$digest\";\r\n\r\n";
for my $m (@maps) {
    my ($key, $name) = @$m;
    my $map = $j->{$key} or die "no map $key in $src\n";
    my ($gc, $gr) = @{ $map->{grid} };
    my ($ox, $oy) = @{ $map->{origin_1280} };
    $cs .= "        /// <summary>Design's $key: " . scalar(@{ $map->{tiles} }) . " tiles on a ${gc} x ${gr} grid, $map->{tile} px tiles $map->{gap} apart from ($ox, $oy) at 1280 - $map->{label}.</summary>\r\n";
    $cs .= "        public static readonly TileMap $name = new TileMap(" . cq($key) . ", $gc, $gr, $map->{tile}f, $map->{gap}f, ${ox}f, ${oy}f, new[]\r\n        {\r\n";
    for my $t (@{ $map->{tiles} }) {
        $cs .= "            new Tile(" . cq($t->{id}) . ", $t->{col}, $t->{row}, " . cq($t->{name}) . "),\r\n";
    }
    $cs .= "        });\r\n\r\n";
}
$cs =~ s/\r\n\r\n$/\r\n/;
$cs .= "    }\r\n}\r\n";
open my $o, '>:raw', $out or die "$out: $!";
print $o Encode::encode('UTF-8', $cs);
close $o;
printf "%s: %d bytes from %s (sha256 %s)\n", $out, length(Encode::encode('UTF-8', $cs)), $src, $digest;
