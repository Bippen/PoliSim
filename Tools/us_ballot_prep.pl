#!/usr/bin/perl
# SP-6b (Design's section 7, the return of 2026-10-30): AN INDEPENDENT PRESIDENTIAL CANDIDATE'S BALLOT ACCESS IN THE 51 JURISDICTIONS, 2024 - FOR THE RUNTIME.
#
#   perl Tools/us_ballot_prep.pl          (from the project root)
#
# Reads only what is on disk, each held before a byte of it is used:
#   ElectionsData/usa/raw/ballot_access/nass_summary_ballot_access_laws_president_072924.pdf   NASS's "Summary: State Laws Regarding Presidential Ballot
#                       Access for the General Election" (updated July 2024), saved byte for byte, held to raw/ballot_access/SHA256SUMS.txt
#   ElectionsData/usa/ballot_access_read_2024.tsv   one row a jurisdiction READ from that summary: the signatures, the deadline, the fee, and the quote that
#                       carries them - every quote held to the state's own section of the summary's text (whitespace ignored: the PDF's text layer splits
#                       figures, "5 ,000"), every figure a rule names held to its quote
#   ElectionsData/usa/president_by_state.csv, house_by_state.csv   (generated by Tools/us_returns_prep.pl) the bases a formula names where they are on disk:
#                       2020's presidential vote (pres2020) and 2022's House vote (house2022) by state; 2024's electors
# and writes
#   ElectionsData/usa/ballot_access_2024.csv                       a row a jurisdiction: its electors, the signatures (empty where BILLED) and their basis,
#                                                                  the deadline for 5 Nov 2024 (empty where BILLED) and its rule, the fee and its route
#   Assets/Scripts/Elections/Generated/UsBallotAccess2024.cs       the CSV as C# literals with each jurisdiction's quote, and the digests of the PDF, the
#                                                                  READ table and the CSV
# UsBallotAccessCheck re-reads the CSV, the READ table and the PDF's digest against the generated part. It writes nothing and dies naming every mismatch.
#
# Readings (DECLARED, each printed on the row it decides): a fractional requirement rounds UP (no one signs a fraction); "the last general election" for
# president is 2020's; "the lesser of P % of a base not on disk and N" is N where P % of a base on disk that can never exceed it already reaches N (Illinois:
# the voters at the 2022 general election are at least the votes cast there for the House; South Carolina: the registered electors are at least the electors
# who voted in 2020 - a reading across four years, its margin printed); a day count is counted back from polling day; a business day is a weekday (the
# window Utah's rule falls in holds no federal holiday).
use strict; use warnings;
use Compress::Zlib;
use Digest::SHA qw(sha256_hex);
use Encode ();
use Time::Local qw(timegm);

my $usa = 'ElectionsData/usa';
die "run from the project root\n" unless -d $usa;
my $raw = "$usa/raw/ballot_access";
my $pdf_name = 'nass_summary_ballot_access_laws_president_072924.pdf';
my $read_tsv = "$usa/ballot_access_read_2024.tsv";
my $csv_out = "$usa/ballot_access_2024.csv";
my $cs_out = 'Assets/Scripts/Elections/Generated/UsBallotAccess2024.cs';
my @problems;
sub problem { push @problems, $_[0]; }
sub slurp { my ($f) = @_; open my $h, '<:raw', $f or die "$f: $!\n"; local $/; my $b = <$h>; close $h; return $b; }

# ---- the PDF, held to its digest ----------------------------------------------------------------------------------------------------------------
my %listed;
for my $l (split /\r?\n/, slurp("$raw/SHA256SUMS.txt")) { $listed{$2} = $1 if $l =~ /^([0-9a-f]{64}) \*?(\S+)$/; }
my $pdf = slurp("$raw/$pdf_name");
my $pdf_digest = sha256_hex($pdf);
die "$raw/$pdf_name: digest $pdf_digest is not the one SHA256SUMS.txt lists\n" unless ($listed{$pdf_name} // '') eq $pdf_digest;

# ---- its text: every page's content stream in page order, literal strings by WinAnsi, hex strings by the font's ToUnicode map ---------------------
my %obj;
while ($pdf =~ /(\d+) 0 obj(.*?)endobj/sg) { $obj{$1} = $2; }
sub stream_of {
    my ($n) = @_;
    my $b = $obj{$n} // return undef;
    return undef unless $b =~ /stream\r?\n(.*)endstream/s;
    my $s = $1;
    my $o = uncompress($s);
    if (!defined $o) { my ($i) = inflateInit(); ($o) = $i->inflate($s) if $i; }
    return $o;
}
my %cmap;
for my $n (keys %obj) {
    next unless $obj{$n} =~ m{/Type/Font/Subtype/Type0.*?/ToUnicode (\d+) 0 R}s;
    my $c = stream_of($1) // die "font $n: no ToUnicode stream $1\n";
    my %m;
    while ($c =~ /beginbfchar(.*?)endbfchar/sg) {
        my $blk = $1;
        while ($blk =~ /<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>/g) { my ($k, $v) = ($1, $2); $m{hex $k} = join '', map { chr hex } ($v =~ /(....)/g); }
    }
    while ($c =~ /beginbfrange(.*?)endbfrange/sg) {
        my $blk = $1;
        while ($blk =~ /<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>/g) { my ($a, $b, $u) = (hex $1, hex $2, hex $3); $m{$_} = chr($u + $_ - $a) for $a .. $b; }
    }
    $cmap{$n} = \%m;
}
my %win = (0x91 => "\x{2018}", 0x92 => "\x{2019}", 0x93 => "\x{201C}", 0x94 => "\x{201D}", 0x96 => "\x{2013}", 0x97 => "\x{2014}", 0x85 => "\x{2026}", 0x95 => "\x{2022}");
my ($pages) = grep { $obj{$_} =~ m{/Type/Pages/} } sort { $a <=> $b } keys %obj;
die "$pdf_name: no page tree\n" unless defined $pages;
my $text = '';
for my $p ($obj{$pages} =~ /Kids\[([^\]]*)\]/ ? ($1 =~ /(\d+) 0 R/g) : ()) {
    my $pg = $obj{$p};
    my %fonts;
    if ($pg =~ m{/Font<<(.*?)>>}s) { my $fl = $1; while ($fl =~ m{/(F\d+) (\d+) 0 R}g) { $fonts{$1} = $2; } }
    my ($cn) = $pg =~ m{/Contents (\d+) 0 R} or next;
    my $o = stream_of($cn) // next;
    my $font = '';
    while ($o =~ /(\/F\d+)\s+[\d.]+\s+Tf|(\[(?:[^\]\\]|\\.)*\]\s*TJ|\((?:[^)\\]|\\.)*\)\s*Tj|<[0-9A-Fa-f]+>\s*Tj)|(T\*|Td|TD|ET)/sg) {
        if (defined $1) { ($font = $1) =~ s{^/}{}; next; }
        if (defined $3) { $text .= ' '; next; }
        my $t = $2;
        my $cm = $cmap{ $fonts{$font} // -1 };
        while ($t =~ /\(((?:[^)\\]|\\.)*)\)|<([0-9A-Fa-f]+)>|(-?\d+\.?\d*)/g) {
            if (defined $1) {
                my $x = $1; $x =~ s/\\(\d{1,3})/chr(oct $1)/ge; $x =~ s/\\(.)/$1/g;
                $text .= join '', map { my $c = ord; $win{$c} // chr($c) } split //, $x;
            }
            elsif (defined $2) { my $hx = $2; $text .= $cm ? join('', map { $cm->{hex $_} // '?' } ($hx =~ /(....)/g)) : '?'; }
            elsif ($3 < -200) { $text .= ' '; }
        }
    }
    $text .= ' ';
}
$text =~ s/\s+/ /g;
die "$pdf_name: its text does not open on NASS's title\n" unless $text =~ /SUMMARY: STATE LAWS REGARDING PRESIDENTIAL BALLOT ACCESS FOR THE GENERAL ELECTION/;

# ---- the states' sections, in the summary's order (the District of Columbia is not among them) --------------------------------------------------
my @names = (['AL','Alabama'],['AK','Alaska'],['AZ','Arizona'],['AR','Arkansas'],['CA','California'],['CO','Colorado'],['CT','Connecticut'],['DE','Delaware'],
    ['FL','Florida'],['GA','Georgia'],['HI','Hawaii'],['ID','Idaho'],['IL','Illinois'],['IN','Indiana'],['IA','Iowa'],['KS','Kansas'],['KY','Kentucky'],
    ['LA','Louisiana'],['ME','Maine'],['MD','Maryland'],['MA','Massachusetts'],['MI','Michigan'],['MN','Minnesota'],['MS','Mississippi'],['MO','Missouri'],
    ['MT','Montana'],['NE','Nebraska'],['NV','Nevada'],['NH','New Hampshire'],['NJ','New Jersey'],['NM','New Mexico'],['NY','New York'],['NC','North Carolina'],
    ['ND','North Dakota'],['OH','Ohio'],['OK','Oklahoma'],['OR','Oregon'],['PA','Pennsylvania'],['RI','Rhode Island'],['SC','South Carolina'],
    ['SD','South Dakota'],['TN','Tennessee'],['TX','Texas'],['UT','Utah'],['VT','Vermont'],['VA','Virginia'],['WA','Washington'],['WV','West Virginia'],
    ['WI','Wisconsin'],['WY','Wyoming']);
my (%section, @starts);
my $from = 0;
for my $n (@names) {
    my $re = quotemeta($n->[1]); $re =~ s/\\ /\\s*/g;
    pos($text) = $from;
    $text =~ /\G.*?((?:State\s+)?$re)\s+(?:Political\s+Party|The\s+names\s+of\s+candidates)/sg or die "$pdf_name: no section for $n->[1]\n";
    push @starts, [$n->[0], $-[1]];
    $from = pos($text);
}
for my $i (0 .. $#starts) { my $end = $i < $#starts ? $starts[$i + 1][1] : length $text; $section{$starts[$i][0]} = substr($text, $starts[$i][1], $end - $starts[$i][1]); }
sub bare { my ($s) = @_; $s =~ s/\s+//g; return $s; }

# ---- the bases on disk ----------------------------------------------------------------------------------------------------------------------------
sub csv_rows {
    my ($file, $heading) = @_;
    my ($seen, @rows) = (0);
    for my $l (split /\r?\n/, slurp("$usa/$file")) {
        next if $l eq '' || $l =~ /^#/;
        if (!$seen) { die "$file: its heading '$l', not '$heading'\n" unless $l eq $heading; $seen = 1; next; }
        push @rows, [split /,/, $l, -1];
    }
    return @rows;
}
my (%pres2020, %electors2024, %house2022);
for my $r (csv_rows('president_by_state.csv', 'year,state,electors,votes_d,votes_r,votes_other,votes_total,cast_d,cast_r,cast_other,cast_other_to')) {
    $pres2020{$r->[1]} = $r->[6] if $r->[0] == 2020;
    $electors2024{$r->[1]} = $r->[2] if $r->[0] == 2024;
}
for my $r (csv_rows('house_by_state.csv', 'year,state,votes_r,votes_d,votes_other,votes_total')) { $house2022{$r->[1]} = $r->[5] if $r->[0] == 2022; }
die "president_by_state.csv: " . scalar(keys %electors2024) . " jurisdictions of 2024, not 51\n" unless keys %electors2024 == 51;
my %base_on_disk = (pres2020 => [\%pres2020, "2020's presidential vote"], house2022 => [\%house2022, "2022's House vote"]);
my %base_off_disk = (voters2022 => "the voters of 2022's general election", registered => "the registered electors");

# ---- the polling day and the calendar rules --------------------------------------------------------------------------------------------------------
my @poll = (2024, 11, 5);
my %mon = (Jan => 1, Feb => 2, Mar => 3, Apr => 4, May => 5, Jun => 6, Jul => 7, Aug => 8, Sep => 9, Oct => 10, Nov => 11, Dec => 12);
my %monname = (Jan => 'January', Feb => 'February', Mar => 'March', Apr => 'April', May => 'May', Jun => 'June', Jul => 'July', Aug => 'August', Sep => 'September', Oct => 'October', Nov => 'November', Dec => 'December');
my %dow = (Sun => 0, Mon => 1, Tue => 2, Wed => 3, Thu => 4, Fri => 5, Sat => 6);
my %dayname = (Mon => 'Monday', Tue => 'Tuesday', Wed => 'Wednesday', Thu => 'Thursday', Fri => 'Friday');
my %ordinal = (1 => 'first|1st', 2 => 'second|2nd', 3 => 'third|3rd', 4 => 'fourth|4th', last => 'last');
sub day_of { my ($y, $m, $d) = @_; return int(timegm(0, 0, 12, $d, $m - 1, $y) / 86400); }
sub ymd { my ($n) = @_; my @t = gmtime($n * 86400 + 43200); return sprintf('%04d-%02d-%02d', $t[5] + 1900, $t[4] + 1, $t[3]); }
sub wday { my ($n) = @_; return (gmtime($n * 86400 + 43200))[6]; }
my $poll_day = day_of(@poll);
sub nth_weekday {   # the k-th (or last) weekday of a month of the polling day's year
    my ($k, $wd, $m) = @_;
    my @hits = grep { wday($_) == $wd } map { day_of($poll[0], $m, 1) + $_ } 0 .. 30;
    @hits = grep { ymd($_) =~ /^\d{4}-\Q@{[sprintf '%02d', $m]}\E-/ } @hits;
    return $k eq 'last' ? $hits[-1] : $hits[$k - 1];
}

# ---- the READ rows -------------------------------------------------------------------------------------------------------------------------------
my $read = slurp($read_tsv);
$read =~ s/\r\n/\n/g;   # the digest is over its text with LF line ends, as the check reads it
my $read_digest = sha256_hex($read);
my $read_text = Encode::decode('UTF-8', $read);
my (@rows, %seen);
my $heading_seen = 0;
for my $l (split /\r?\n/, $read_text) {
    next if $l eq '' || $l =~ /^#/;
    my @f = split /\t/, $l, -1;
    if (!$heading_seen) { die "$read_tsv: its heading '$l'\n" unless $l eq "state\tsignatures\tdeadline\tfee\tquote"; $heading_seen = 1; next; }
    die "$read_tsv: a row of " . scalar(@f) . " fields: $l\n" unless @f == 5;
    my ($st, $sig, $dl, $fee, $quote) = @f;
    problem("$read_tsv: $st twice") if $seen{$st}++;
    problem("$read_tsv: $st is not a jurisdiction of 2024") unless exists $electors2024{$st};
    my @quotes = $quote eq '-' ? () : split / \| /, $quote;
    my $sec = $section{$st};
    if (@quotes && !defined $sec) { problem("$st: quoted, but the summary has no section for it"); }
    for my $q (@quotes) { problem("$st: the quote \"$q\" is not in the summary's section for it") if defined $sec && index(bare($sec), bare($q)) < 0; }
    my $qb = bare(join ' ', @quotes);
    my $has = sub { my ($re) = @_; return $qb =~ /$re/i; };
    my $figure = sub { my ($n) = @_; my $c = $n; 1 while $c =~ s/^(\d+)(\d{3})/$1,$2/; return $has->("(?<![\\d,.])(?:\Q$n\E|\Q$c\E)(?![\\d])"); };

    # the signatures
    my ($count, $sig_basis);
    if ($sig =~ /^count (\d+)$/) {
        $count = $1; $sig_basis = 'count';
        problem("$st: count $1 is not in its quote") unless $figure->($1);
    }
    elsif ($sig =~ /^pct ([\d.]+) (\w+)$/) {
        my ($p, $b) = ($1, $2);
        problem("$st: $p % is not in its quote") unless $has->("\Q$p\E%");
        my $on = $base_on_disk{$b} or die "$st: base $b is not on disk - BILL it\n";
        my $v = $on->[0]{$st} // die "$st: no $b row\n";
        $count = int(($v * $p + 99) / 100); $count = int($v * $p / 100 + 0.999999999) if $p != int $p;
        $sig_basis = "$p % of $on->[1] $v; rounded up";
    }
    elsif ($sig =~ /^lesser ([\d.]+) (\w+) (\d+)(?: bound (\w+))?$/) {
        my ($p, $b, $n, $bound) = ($1, $2, $3, $4);
        problem("$st: $p % is not in its quote") unless $has->("\Q$p\E%");
        problem("$st: $n is not in its quote") unless $figure->($n);
        if (my $on = $base_on_disk{$b}) {
            my $v = $on->[0]{$st} // die "$st: no $b row\n";
            my $pc = int(($v * $p + 99) / 100);
            $count = $pc < $n ? $pc : $n;
            $sig_basis = "the lesser of $p % of $on->[1] $v ($pc) and $n";
        }
        elsif ($bound && $base_on_disk{$bound}) {
            my $on = $base_on_disk{$bound};
            my $v = $on->[0]{$st} // die "$st: no $bound row\n";
            my $pc = int(($v * $p + 99) / 100);
            if ($pc >= $n) { $count = $n; $sig_basis = sprintf("the lesser of %s %% of %s and %d - %s %% of %s %d is already %d (x%.1f); DECLARED", $p, $base_off_disk{$b} // $b, $n, $p, $on->[1], $v, $pc, $pc / $n); }
            else { $sig_basis = "BILLED: $p % of $b is not on disk and $on->[1] does not decide it"; }
        }
        else { $sig_basis = "BILLED: $p % of $b is not on disk"; }
    }
    elsif ($sig =~ /^billed (.+)$/) { $sig_basis = "BILLED: $1"; }
    else { problem("$st: signatures '$sig' is no rule"); }

    # the deadline
    my ($deadline, $dl_basis);
    if ($dl =~ /^days (\d+)$/) {
        problem("$st: $1 days is not in its quote") unless $figure->($1);
        $deadline = $poll_day - $1; $dl_basis = "$1 days before polling day";
    }
    elsif ($dl =~ /^date (\d\d)-(\d\d)$/) {
        my ($m, $d) = ($1 + 0, $2 + 0);
        my ($mn) = grep { $mon{$_} == $m } keys %mon;
        problem("$st: $monname{$mn} $d is not in its quote") unless $has->("$monname{$mn}$d(?!\\d)");
        $deadline = day_of($poll[0], $m, $d); $dl_basis = "$monname{$mn} $d";
    }
    elsif ($dl =~ /^nth (\w+) (\w{3}) (\w{3})$/) {
        my ($k, $wd, $m) = ($1, $2, $3);
        problem("$st: the $k $wd of $m is not in its quote") unless $has->("(?:$ordinal{$k})$dayname{$wd}(?:in|of)$monname{$m}");
        $deadline = nth_weekday($k, $dow{$wd}, $mon{$m}); $dl_basis = "the " . ($ordinal{$k} =~ /^(\w+)/)[0] . " $dayname{$wd} in $monname{$m}";
    }
    elsif ($dl =~ /^after (\w+) (\w{3}) (\w{3}) (\w{3}) (\d)$/) {
        my ($k, $wd, $m, $wd2, $j) = ($1, $2, $3, $4, $5);
        problem("$st: the $j $wd2 after the $k $wd of $m is not in its quote") unless $has->("$dayname{$wd2}(?:following|after)the(?:$ordinal{$k})$dayname{$wd}in$monname{$m}");
        my $a = nth_weekday($k, $dow{$wd}, $mon{$m});
        my @after = grep { wday($_) == $dow{$wd2} } map { $a + $_ } 1 .. 21;
        $deadline = $after[$j - 1]; $dl_basis = "the " . ($ordinal{$j} =~ /^(\w+)/)[0] . " $dayname{$wd2} after the " . ($ordinal{$k} =~ /^(\w+)/)[0] . " $dayname{$wd} in $monname{$m}";
    }
    elsif ($dl =~ /^mondays (\d+)$/) {
        problem("$st: the $1th Monday is not in its quote") unless $has->("$1thMonday");
        my @mondays = grep { wday($_) == 1 } map { $poll_day - $_ } 1 .. 7 * $1 + 7;
        $deadline = $mondays[$1 - 1]; $dl_basis = "the $1th Monday before polling day";
    }
    elsif ($dl =~ /^business (\d) (\d\d)-(\d\d)$/) {
        my ($n, $m, $d) = ($1, $2 + 0, $3 + 0);
        problem("$st: the ${n}th business day is not in its quote") unless $has->("${n}thbusinessday");
        my @b = grep { my $w = wday($_); $w >= 1 && $w <= 5 } map { day_of($poll[0], $m, $d) + $_ } 1 .. 14;
        $deadline = $b[$n - 1]; $dl_basis = "the ${n}th business day after " . ymd(day_of($poll[0], $m, $d)) . "; a business day a weekday, DECLARED";
    }
    elsif ($dl =~ /^billed (.+)$/) { $dl_basis = "BILLED: $1"; }
    else { problem("$st: deadline '$dl' is no rule"); }

    # the fee
    my ($fee_usd, $route, $fee_basis) = ('', 'none', 'none named in the summary');
    if ($fee =~ /^usd (\d+) (add|alt)$/) {
        ($fee_usd, $route) = ($1, $2);
        problem("$st: \$$1 is not in its quote") unless $has->("\\\$\Q$1\E(?!\\d)");
        $fee_basis = $route eq 'alt' ? "a fee instead of the petition" : "a fee beside the petition";
    }
    elsif ($fee =~ /^billed (.+)$/) { ($route, $fee_basis) = ('billed', "BILLED: $1"); }
    elsif ($fee ne 'none') { problem("$st: fee '$fee' is no rule"); }

    for ($sig_basis, $dl_basis, $fee_basis) { $_ //= ''; 1 while s/(\d),(\d{3})/$1$2/; s/,/;/g; }
    push @rows, { st => $st, electors => $electors2024{$st}, count => $count, sig_basis => $sig_basis, deadline => defined $deadline ? ymd($deadline) : '',
        dl_basis => $dl_basis, fee => $fee_usd, route => $route, fee_basis => $fee_basis, quote => join(' | ', @quotes) };
}
problem("$read_tsv: no row for $_") for grep { !$seen{$_} } sort keys %electors2024;
problem("the summary's section for $_->[0] has no READ row") for grep { !$seen{$_->[0]} } @names;
die join("\n", "us_ballot_prep.pl: nothing written -", map { "  $_" } @problems) . "\n" if @problems;

# ---- the outputs ----------------------------------------------------------------------------------------------------------------------------------
my @order = sort { $a->{st} cmp $b->{st} } @rows;
my $csv = "# GENERATED by Tools/us_ballot_prep.pl from raw/ballot_access/$pdf_name (NASS, updated July 2024) and ballot_access_read_2024.tsv - DO NOT EDIT.\n"
    . "# SP-6b: an independent presidential candidate's ballot access for 5 Nov 2024, a row a jurisdiction. signatures empty and deadline empty: BILLED (the basis says why).\n"
    . "# fee_route: add (a fee beside the petition), alt (a fee instead of it), none (the summary names none), billed.\n"
    . "state,electors,signatures,signatures_basis,deadline,deadline_basis,fee_usd,fee_route,fee_basis\n";
$csv .= join(',', $_->{st}, $_->{electors}, $_->{count} // '', $_->{sig_basis}, $_->{deadline}, $_->{dl_basis}, $_->{fee}, $_->{route}, $_->{fee_basis}) . "\n" for @order;
my $csv_bytes = Encode::encode('UTF-8', $csv);
my $csv_digest = sha256_hex($csv_bytes);

sub cq { my ($s) = @_; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return '"' . $s . '"'; }
my $cs = "// GENERATED by Tools/us_ballot_prep.pl. DO NOT EDIT BY HAND.\n//\n"
    . "// Source: ElectionsData/usa/ballot_access_2024.csv (its SHA-256 below), written by the same run from NASS's summary (raw/ballot_access/, its SHA-256 below) and\n"
    . "// the READ table ballot_access_read_2024.tsv (its SHA-256 below). UsBallotAccessCheck re-reads all three.\n\n"
    . "namespace PoliSim.Elections.Generated\n{\n"
    . "    /// <summary>SP-6b (Design's section 7): an independent presidential candidate's ballot access for 5 Nov 2024, a row a jurisdiction - SOURCED from NASS's\n"
    . "    /// \"Summary: State Laws Regarding Presidential Ballot Access for the General Election\" (updated July 2024), each row READ with the quote that carries it\n"
    . "    /// (`ElectionsData/usa/ballot_access_read_2024.tsv`) and held to the summary's text by the tool. A signature count of -1 and an empty deadline are BILLED,\n"
    . "    /// their basis saying why. Generated, never hand-edited.</summary>\n"
    . "    public static class UsBallotAccess2024\n    {\n"
    . "        public const string SourceDigest = \"$csv_digest\";\n"
    . "        public const string SummaryDigest = \"$pdf_digest\";\n"
    . "        public const string ReadDigest = \"$read_digest\";\n"
    . "        /// <summary>The saved summary, by its path under `ElectionsData/usa/`.</summary>\n"
    . "        public const string SummaryPath = \"raw/ballot_access/$pdf_name\";\n\n"
    . "        /// <summary>The CSV's rows, and each jurisdiction's quote from the summary (\"-\" where it is not in it).</summary>\n"
